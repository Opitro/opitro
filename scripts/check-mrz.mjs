// РАЗБОР MRZ НА ОБРАЗЦАХ ИКАО.
//
// Проверяем НАСТОЯЩИЙ src/lib/mrz.js -- тот самый, что уходит на страницу, а не его пересказ.
// Образцы взяты из Doc 9303 (часть 3, приложения): у них известны и поля, и контрольные
// цифры, поэтому расхождение означает ошибку у нас, а не у образца.
import { разобратьМрз, разобратьСтроки, контрольная, вытащитьСтроки } from '../src/lib/mrz.js';

const беды = [];
const проба = (имя, ладно, что) => {
  console.log(`  ${ладно ? '✓' : '✗'} ${имя}${что !== undefined ? ' — ' + String(что).slice(0, 90) : ''}`);
  if (!ладно) беды.push(имя);
};

console.log('════ контрольные цифры');
проба('номер паспорта из образца ИКАО', контрольная('L898902C3') === '6', контрольная('L898902C3'));
проба('дата рождения', контрольная('740812') === '2', контрольная('740812'));
проба('пустое поле даёт ноль', контрольная('<<<<<<') === '0', контрольная('<<<<<<'));

console.log('\n════ паспорт (TD3)');
{
  const о = разобратьСтроки([
    'P<UTOERIKSSON<<ANNA<MARIA<<<<<<<<<<<<<<<<<<<',
    'L898902C36UTO7408122F1204159ZE184226B<<<<<10',
  ]);
  проба('вид определён', о.вид === 'TD3', о.вид);
  проба('фамилия', о.поля.фамилия === 'ERIKSSON', о.поля.фамилия);
  проба('имена', о.поля.имена === 'ANNA MARIA', о.поля.имена);
  проба('номер', о.поля.номер === 'L898902C3', о.поля.номер);
  проба('гражданство', о.поля.гражданство === 'UTO', о.поля.гражданство);
  проба('дата рождения 12.08.1974', о.поля.рождение && о.поля.рождение.iso === '1974-08-12', о.поля.рождение && о.поля.рождение.iso);
  проба('пол', о.поля.пол === 'ж', о.поля.пол);
  проба('срок 15.04.2012', о.поля.срок && о.поля.срок.iso === '2012-04-15', о.поля.срок && о.поля.срок.iso);
  проба('личный номер', о.поля.личный === 'ZE184226B', о.поля.личный);
  проба('все контрольные цифры сошлись', о.сошлось, JSON.stringify(о.проверки.map((п) => [п.имя, п.ок])));
}

console.log('\n════ ID-карта (TD1)');
{
  const о = разобратьСтроки([
    'I<UTOD231458907<<<<<<<<<<<<<<<',
    '7408122F1204159UTO<<<<<<<<<<<6',
    'ERIKSSON<<ANNA<MARIA<<<<<<<<<<',
  ]);
  проба('вид определён', о.вид === 'TD1', о.вид);
  проба('номер', о.поля.номер === 'D23145890', о.поля.номер);
  проба('фамилия и имена', о.поля.фамилия === 'ERIKSSON' && о.поля.имена === 'ANNA MARIA', `${о.поля.фамилия} / ${о.поля.имена}`);
  проба('дата рождения', о.поля.рождение.iso === '1974-08-12', о.поля.рождение.iso);
  проба('все контрольные цифры сошлись', о.сошлось, JSON.stringify(о.проверки.map((п) => [п.имя, п.ок])));
}

console.log('\n════ удостоверение (TD2)');
{
  const о = разобратьСтроки([
    'I<UTOERIKSSON<<ANNA<MARIA<<<<<<<<<<<',
    'D231458907UTO7408122F1204159<<<<<<<6',
  ]);
  проба('вид определён', о.вид === 'TD2', о.вид);
  проба('номер', о.поля.номер === 'D23145890', о.поля.номер);
  проба('фамилия', о.поля.фамилия === 'ERIKSSON', о.поля.фамилия);
  проба('все контрольные цифры сошлись', о.сошлось, JSON.stringify(о.проверки.map((п) => [п.имя, п.ок])));
}

console.log('\n════ виза (MRV-A)');
{
  const о = разобратьСтроки([
    'V<UTOERIKSSON<<ANNA<MARIA<<<<<<<<<<<<<<<<<<<',
    'L8988901C4XXX4009078F96121096ZE184226B<<<<<<',
  ]);
  проба('вид определён', о.вид === 'MRV-A', о.вид);
  проба('номер', о.поля.номер === 'L8988901C', о.поля.номер);
  проба('гражданство без страны', о.поля.безГражданства, о.поля.гражданство);
  проба('у визы нет общей контрольной цифры', !о.проверки.some((п) => п.имя === 'всё вместе'), JSON.stringify(о.проверки.map((п) => п.имя)));
  проба('остальные цифры сошлись', о.сошлось, JSON.stringify(о.проверки.map((п) => [п.имя, п.ок])));
}

console.log('\n════ страны словами');
{
  const о = разобратьСтроки([
    'P<DEUMUSTERMANN<<ERIKA<<<<<<<<<<<<<<<<<<<<<<',
    'C01X00T478DEU6408125F2702283<<<<<<<<<<<<<<<4',
  ]);
  проба('код страны переведён в две буквы', о.поля.странаВыдачи === 'DE', о.поля.странаВыдачи);
  проба('немецкий образец сошёлся целиком', о.сошлось, JSON.stringify(о.проверки.map((п) => [п.имя, п.ок])));
}

console.log('\n════ распознанное с мусором');
{
  // Ровно то, что приносит распознаватель с телефонного снимка: прилипшая единица слева,
  // строка имени из паспорта сверху и пустая строка.
  const текст = 'PASSPORT\n\nP<UTOERIKSSON<<ANNA<MARIA<<<<<<<<<<<<<<<<<<<\n1L898902C36UTO7408122F1204159ZE184226B<<<<<10\n';
  const строки = вытащитьСтроки(текст);
  проба('лишнее отброшено, осталось две строки', строки.length === 2, JSON.stringify(строки));
  const о = разобратьМрз(текст);
  проба('разобралось несмотря на мусор', о.вышло && о.сошлось, о.вышло ? о.поля.номер : о.причина);
}

console.log('\n════ подделка: одна цифра испорчена');
{
  const о = разобратьСтроки([
    'P<UTOERIKSSON<<ANNA<MARIA<<<<<<<<<<<<<<<<<<<',
    'L898902C36UTO7408125F1204159ZE184226B<<<<<10',
  ]);
  проба('поля всё равно показаны', о.вышло && о.поля.фамилия === 'ERIKSSON', о.поля && о.поля.фамилия);
  проба('но проверка честно провалена', !о.сошлось, JSON.stringify(о.проверки.filter((п) => !п.ок).map((п) => п.имя)));
}

console.log('\n════ подбор по контрольной цифре');
{
  // Распознаватель прочитал в номере «O» вместо нуля -- контрольная цифра это ловит, и
  // единственное написание, при котором она сходится, мы обязаны подставить сами.
  const о = разобратьСтроки([
    'P<UTOERIKSSON<<ANNA<MARIA<<<<<<<<<<<<<<<<<<<',
    'L8989O2C36UTO7408122F1204159ZE184226B<<<<<10',
  ]);
  проба('нуль восстановлен вместо буквы O', о.поля.номер === 'L898902C3', о.поля.номер);
  проба('сказано, что это подбор, а не чтение', о.проверки.find((п) => п.имя === 'номер').подобрано);
  проба('проверка при этом считается пройденной', о.сошлось);
}

console.log('\n════ пустой личный номер (так бывает у многих стран)');
{
  const о = разобратьСтроки([
    'P<GBRSMITH<<JOHN<<<<<<<<<<<<<<<<<<<<<<<<<<<<',
    '1234567897GBR8001014M2501017<<<<<<<<<<<<<<00',
  ]);
  проба('разобралось', о.вышло && о.поля.фамилия === 'SMITH', о.поля && о.поля.фамилия);
  проба('к пустому личному номеру не придираемся',
    !о.проверки.some((п) => п.имя === 'личный номер' && !п.ок),
    JSON.stringify(о.проверки.map((п) => [п.имя, п.ок])));
}

console.log(беды.length ? `\nбед: ${беды.length} — ${беды.join(', ')}` : '\nразбор MRZ: всё на месте');
process.exit(беды.length ? 1 : 0);
