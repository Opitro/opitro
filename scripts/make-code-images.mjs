// ОБРАЗЦЫ КОДОВ ДЛЯ ФАК: как выглядит Data Matrix, PDF417 и Aztec.
//
// Зачем файлами, а не рисунком в разметке: картинку с осмысленным именем и подписью находит
// поиск по изображениям -- это отдельный вход на страницу, помимо обычного поиска.
//
// В каждом коде записан адрес сайта. Это не украшение: человек может навести на картинку
// камеру этой же страницы и увидеть, что она читает -- проверка инструмента на самом себе.
//
// Рисует bwip-js -- чужая библиотека, по чужим правилам кодирования. Свой рисовальщик тут был
// бы лукавством: проверять свой распознаватель своими же картинками бессмысленно.
//
// Запуск: node scripts/make-code-images.mjs
// Размеры печатаются в конце -- их надо подставить в разметку ФАК (=ШxВ), чтобы место под
// картинку было занято заранее и страница не дёргалась при загрузке.
import fs from 'node:fs';
import path from 'node:path';
import bwipjs from 'bwip-js';

const КУДА = path.join(process.cwd(), 'public', 'i');
const АДРЕС = 'https://opitro.com';

// Картинки нарочно небольшие и аккуратные -- это пример в ответе, а не плакат. На странице
// они показываются вдвое мельче своего размера: так они остаются резкими на телефонах и
// хороших экранах, где один рисованный пиксель приходится на два настоящих.
const ОБРАЗЦЫ = [
  { bcid: 'datamatrix', файл: 'data-matrix-code-example.png', потолок: 360 },
  { bcid: 'pdf417', файл: 'pdf417-code-example.png', потолок: 640 },
  { bcid: 'azteccode', файл: 'aztec-code-example.png', потолок: 360 },
];

fs.mkdirSync(КУДА, { recursive: true });

/** Нарисовать код в заданном масштабе. Размер лежит в заголовке PNG: байты 16..23. */
async function нарисовать(bcid, scale) {
  const png = await bwipjs.toBuffer({
    bcid, text: АДРЕС, scale, paddingwidth: 3, paddingheight: 3,
    // Белое поле вокруг обязательно: без него распознаватель не видит края кода, и картинка
    // из «примера» превращается в нечитаемую.
    backgroundcolor: 'FFFFFF',
  });
  return { png, ш: png.readUInt32BE(16), в: png.readUInt32BE(20) };
}

for (const о of ОБРАЗЦЫ) {
  // Берём самый крупный масштаб, который ещё влезает в потолок: чем крупнее клетки, тем
  // вернее код читается с экрана, а мельчить незачем.
  let взято = null;
  for (let scale = 14; scale >= 2; scale--) {
    const проба = await нарисовать(о.bcid, scale);
    if (Math.max(проба.ш, проба.в) <= о.потолок) { взято = проба; break; }
  }
  if (!взято) throw new Error(`не подобрался масштаб для ${о.bcid}`);
  fs.writeFileSync(path.join(КУДА, о.файл), взято.png);
  console.log(`${о.файл} — файл ${взято.ш}x${взято.в}, на странице`
    + ` ${Math.round(взято.ш / 2)}x${Math.round(взято.в / 2)},`
    + ` ${(взято.png.length / 1024).toFixed(1)} КБ`);
}
