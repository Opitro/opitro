// Проверяем НАСТОЯЩИЙ src/lib/pdf-text.js -- тот самый, что уходит на страницу. Собираем файл
// и разбираем его обратно так, как это делает читалка: достаём поток листа, вытаскиваем
// шестнадцатеричные строки, переводим номера глифов в буквы по таблице ToUnicode из самого
// файла -- и сверяем с тем, что клали. Если таблица разъедется с содержимым, текст в читалке
// будет виден, но не найдётся поиском и скопируется кашей; здесь это видно сразу.
import { readFile } from 'node:fs/promises';
import { inflateSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const корень = join(dirname(fileURLToPath(import.meta.url)), '..');

// Единственная подмена: в браузере шрифт едет по сети, здесь берём его с диска.
globalThis.fetch = async (путь) => {
  const байты = await readFile(join(корень, 'public', путь));
  return {
    ok: true,
    status: 200,
    arrayBuffer: async () => байты.buffer.slice(байты.byteOffset, байты.byteOffset + байты.byteLength),
  };
};

const { собратьPdf, долянеЗнакомых } = await import(join(корень, 'src/lib/pdf-text.js'));

const беды = [];
const проба = (имя, ладно, что) => {
  console.log(`  ${ладно ? '✓' : '✗'} ${имя}${что !== undefined ? ' — ' + String(что).slice(0, 100) : ''}`);
  if (!ладно) беды.push(имя);
};

/* ---- Разбор готового файла --------------------------------------------------------------- */

/** Объекты файла по номерам: тело словаря и распакованный поток, если он есть. */
function разобрать(файл) {
  const текст = Buffer.from(файл).toString('latin1');
  const объекты = new Map();
  const образец = /(\d+) 0 obj\n/g;
  let м;
  while ((м = образец.exec(текст))) {
    const номер = Number(м[1]);
    const конец = текст.indexOf('\nendobj\n', м.index);
    const тело = текст.slice(м.index + м[0].length, конец);
    const где = тело.indexOf('\nstream\n');
    let поток = null;
    if (где >= 0) {
      const от = где + '\nstream\n'.length;
      const до = тело.lastIndexOf('\nendstream');
      const сырой = Buffer.from(тело.slice(от, до), 'latin1');
      поток = /\/FlateDecode/.test(тело.slice(0, где)) ? inflateSync(сырой) : сырой;
    }
    объекты.set(номер, { словарь: где >= 0 ? тело.slice(0, где) : тело, поток });
  }
  return { текст, объекты };
}

/** Таблица «номер глифа -> буква» из самого файла: её и читает читалка при поиске. */
function прочитатьToUnicode(поток) {
  const карта = new Map();
  const строки = поток.toString('latin1');
  const образец = /<([0-9A-Fa-f]{4})>\s*<([0-9A-Fa-f]+)>/g;
  let м;
  while ((м = образец.exec(строки))) {
    const цель = м[2];
    let буква = '';
    for (let и = 0; и < цель.length; и += 4) буква += String.fromCharCode(parseInt(цель.slice(и, и + 4), 16));
    карта.set(parseInt(м[1], 16), буква);
  }
  return карта;
}

/** Строки листа так, как их прочтёт читалка: номера глифов через таблицу в буквы. */
function текстЛиста(поток, карта) {
  const вышло = [];
  const образец = /<([0-9A-Fa-f]+)>\s*Tj/g;
  let м;
  while ((м = образец.exec(поток.toString('latin1')))) {
    let строка = '';
    for (let и = 0; и < м[1].length; и += 4) {
      строка += карта.get(parseInt(м[1].slice(и, и + 4), 16)) ?? '�';
    }
    вышло.push(строка);
  }
  return вышло;
}

/* ---- Пробы -------------------------------------------------------------------------------- */

const ИСХОДНЫЕ = [
  'Молоко ультрапастеризоване 2,5%',
  'LAIT · CONTRAT FILIÈRE DE',
  'Partenariats durables — Rémunération garantie',
  'Ціна: 45,90 ₴ · №12 · 100 °C × 3',
  'Їжа, що їсться: Ґудзик, Єнот, Ізюм — «лапки»',
  'Ελληνικά γράμματα δοκιμή',
];

console.log('════ обычный снимок: кириллица, латиница с надстрочными, знаки');
{
  const файл = await собратьPdf([{ строки: ИСХОДНЫЕ.map((текст) => ({ текст })) }], { заголовок: 'Проба' });
  const { текст, объекты } = разобрать(файл);

  проба('файл начинается как PDF', Buffer.from(файл.slice(0, 8)).toString() === '%PDF-1.7');
  проба('файл кончается как PDF', текст.trimEnd().endsWith('%%EOF'));
  проба('таблица смещений на месте', /\nstartxref\n(\d+)\n/.test(текст));

  // Смещения должны показывать ровно на «N 0 obj»: сдвиг на байт -- и читалка видит битый файл.
  const местаВерны = [...текст.matchAll(/^(\d{10}) 00000 n $/gm)]
    .map((м) => Number(м[1]))
    .every((место, и) => текст.startsWith(`${и + 1} 0 obj`, место));
  проба('каждое смещение показывает на свой объект', местаВерны);

  const шрифтовые = [...объекты.values()].filter((о) => /\/FontFile2/.test(о.словарь));
  проба('шрифт вложен в файл', шрифтовые.length === 1);
  const файлШрифта = [...объекты.values()].find((о) => /\/Length1 \d+/.test(о.словарь));
  проба('вложенный шрифт -- настоящий TTF',
    !!файлШрифта && файлШрифта.поток.length > 10000
    && (файлШрифта.поток.readUInt32BE(0) === 0x00010000 || файлШрифта.поток.slice(0, 4).toString() === 'true'));
  проба('шрифт сжат в файле', /\/FontFile2/.test(текст) && /\/FlateDecode/.test(текст));

  const сТаблицей = [...объекты.values()].find((о) => о.поток && /beginbfchar/.test(о.поток.toString('latin1')));
  проба('таблица поиска ToUnicode есть', !!сТаблицей);
  const карта = прочитатьToUnicode(сТаблицей.поток);

  const лист = [...объекты.values()].find((о) => о.поток && /\bTj\b/.test(о.поток.toString('latin1')));
  const прочитано = текстЛиста(лист.поток, карта);
  проба('строк столько же, сколько клали', прочитано.length === ИСХОДНЫЕ.length,
    `${прочитано.length} против ${ИСХОДНЫЕ.length}`);
  for (const [и, ждали] of ИСХОДНЫЕ.entries()) {
    проба(`строка ${и + 1} читается буква в букву`, прочитано[и] === ждали, прочитано[и]);
  }

  // Ширины нужны, чтобы читалка ставила буквы на те же места. Без них всё слипается.
  проба('ширины глифов записаны', /\/W \[\d+ \[[\d ]+\]/.test(текст));
  проба('кодировка двухбайтовая', /\/Encoding \/Identity-H/.test(текст));
  проба('номера глифов не переставляются', /\/CIDToGIDMap \/Identity/.test(текст));
}

console.log('\n════ перенос слов и листов');
{
  // Слово заведомо шире листа: должно порваться по буквам, а не уехать за край.
  const длинное = 'ОченьДлинноеСловоКотороеТочноНеПомещаетсяВОднуСтрокуЛистаA4ИДолжноПорватьсяПоБуквам';
  const много = Array.from({ length: 120 }, (_, и) => ({ текст: `Рядок номер ${и + 1} — перевірка переносу.` }));
  const файл = await собратьPdf([{ строки: [{ текст: длинное }] }, { строки: много }], {});
  const { текст, объекты } = разобрать(файл);

  const листов = Number((текст.match(/\/Count (\d+)/) || [])[1]);
  проба('листов стало больше одного', листов >= 3, листов);
  проба('в списке листов столько же ссылок',
    (текст.match(/\/Kids \[([^\]]*)\]/)[1].match(/\d+ 0 R/g) || []).length === листов);

  const сТаблицей = [...объекты.values()].find((о) => о.поток && /beginbfchar/.test(о.поток.toString('latin1')));
  const карта = прочитатьToUnicode(сТаблицей.поток);
  const всеСтроки = [...объекты.values()]
    .filter((о) => о.поток && /\bTj\b/.test(о.поток.toString('latin1')))
    .flatMap((о) => текстЛиста(о.поток, карта));

  проба('длинное слово разорвано, а не потеряно',
    всеСтроки.some((с) => с.length && длинное.startsWith(с) && с !== длинное)
    && всеСтроки.join('').includes(длинное));
  проба('все 120 строк на месте', много.every((с) => всеСтроки.includes(с.текст)),
    `нашлось ${всеСтроки.length}`);

  // Ни одна строка не должна залезать в поля листа. Места букв искать надо в РАСПАКОВАННЫХ
  // потоках листов: в самом файле они сжаты, и поиск по нему нашёл бы пустоту и молча
  // согласился, что всё хорошо.
  const места = [...объекты.values()]
    .filter((о) => о.поток && /\bTj\b/.test(о.поток.toString('latin1')))
    .flatMap((о) => [...о.поток.toString('latin1').matchAll(/1 0 0 1 ([\d.]+) ([\d.]+) Tm/g)]
      .map((м) => ({ х: Number(м[1]), у: Number(м[2]) })));
  проба('места строк вообще нашлись', места.length === всеСтроки.length, места.length);
  проба('ни одна строка не вылезла за поля',
    места.length > 0 && места.every(({ х, у }) => у >= 56.7 && у <= 841.89 - 56.7 && х >= 56.7),
    `снизу ${Math.min(...места.map((м) => м.у)).toFixed(1)}, сверху ${Math.max(...места.map((м) => м.у)).toFixed(1)}`);
}

console.log('\n════ письмо, которого в шрифте нет');
{
  проба('кириллица с латиницей шрифту знакома', await долянеЗнакомых('Привіт світ hello') === 0);
  проба('греческий знаком', await долянеЗнакомых('Ελληνικά') === 0);
  проба('иероглифы шрифту незнакомы', await долянеЗнакомых('这是中文文本') === 1);
  проба('иврит незнаком', await долянеЗнакомых('שלום עולם') === 1);
  проба('цифры и знаки не считаются буквами', await долянеЗнакомых('123 — · ₴') === 0);
}

console.log('\n════ пустое и почти пустое');
{
  const файл = await собратьPdf([{ строки: [{ текст: '   ' }] }], {});
  проба('из пробелов выходит целый файл на один лист',
    Buffer.from(файл.slice(0, 5)).toString() === '%PDF-' && /\/Count 1/.test(Buffer.from(файл).toString('latin1')));
}

