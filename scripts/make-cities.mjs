// СПИСОК ГОРОДОВ ДЛЯ ОПРЕДЕЛЕНИЯ МЕСТА СЪЁМКИ.
//
// Точный адрес в браузере получить нельзя: база адресов весит гигабайты. А вот ближайший
// город -- можно, и этого человеку обычно достаточно: «Москва, Россия» говорит больше, чем
// «55.755833, 37.617778».
//
// Берём города от пятнадцати тысяч жителей: их около двадцати четырёх тысяч, и в таком виде
// список весит 650 КБ (сжатым -- около 290 КБ). Он подгружается ТОЛЬКО когда в снимке есть
// координаты, поэтому пустая страница за него не платит.
//
// Имена международные (Moskva, Yaroslavl): кириллических названий в исходном наборе нет
// вовсе. Это честный предел сегодняшнего набора, и он написан прямо на странице.
//
// Запуск: node scripts/make-cities.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const города = require('all-the-cities');

const ПОРОГ = 15000;
const строки = города
  .filter((г) => г.population >= ПОРОГ)
  .map((г) => [
    г.name,
    г.country,
    г.loc.coordinates[1].toFixed(3),     // широта
    г.loc.coordinates[0].toFixed(3),     // долгота
  ].join('\t'));

// Одной строкой через перевод строки: так список весит вдвое меньше, чем набор объектов,
// и разбирается за доли миллисекунды.
const тело = строки.join('\n');
const файл = `// СПИСОК ГОРОДОВ. Собран scripts/make-cities.mjs из набора all-the-cities.
// Города от ${ПОРОГ.toLocaleString('ru')} жителей: имя, страна, широта, долгота -- через табуляцию,
// по строке на город. Правится не руками, а пересборкой.
export const ГОРОДА = ${JSON.stringify(тело)};
`;
const куда = path.join(process.cwd(), 'src', 'lib', 'cities.js');
fs.writeFileSync(куда, файл);
console.log(`городов: ${строки.length}, вес файла: ${(файл.length / 1024).toFixed(0)} КБ`);
