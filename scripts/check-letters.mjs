// ПРОВЕРКА НА ПОСТОРОННИЕ ПИСЬМЕННОСТИ В ТЕКСТАХ САЙТА.
//
// Зачем: я дважды за одну сессию оставил в русском тексте случайный иероглиф -- вместо «та»
// написалось «那», и заметить это глазами почти невозможно: знак похож по ширине на слово и
// не подчёркивается никакой проверкой орфографии. Здесь такие знаки ищутся по всем текстам
// разом.
//
// Запуск: npm run check:letters
//
// Ищем письменности, которых на сайте быть не должно ни при каких условиях: китайские и
// японские знаки, корейские, арабские, иврит, деванагари. Латиница, кириллица, цифры,
// знаки препинания и типографские кавычки -- законные.

import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = fileURLToPath(new URL('..', import.meta.url));

// Диапазоны, которых у нас быть не может.
const ЧУЖИЕ = [
  [0x0590, 0x05ff, 'иврит'],
  [0x0600, 0x06ff, 'арабское письмо'],
  [0x0900, 0x097f, 'деванагари'],
  [0x0e00, 0x0e7f, 'тайское письмо'],
  [0x3040, 0x30ff, 'японские каны'],
  [0x3400, 0x4dbf, 'иероглифы'],
  [0x4e00, 0x9fff, 'иероглифы'],
  [0xac00, 0xd7af, 'корейское письмо'],
];

const чей = (код) => {
  for (const [от, до, имя] of ЧУЖИЕ) if (код >= от && код <= до) return имя;
  return null;
};

// Списки голосов -- справочники, а не текст: там названия языков написаны своими
// письменностями, и это единственно верно. «العربية» в списке арабских голосов -- не опечатка.
const НЕ_ТРОГАТЬ = [
  'src/lib/piper-voices.js',
  'src/lib/piper/voices-static.js',
];

function обойти(папка, итог = []) {
  for (const имя of readdirSync(папка)) {
    const путь = join(папка, имя);
    if (statSync(путь).isDirectory()) { обойти(путь, итог); continue; }
    if (!/\.(md|astro|js|css|json)$/.test(имя)) continue;
    if (НЕ_ТРОГАТЬ.includes(relative(КОРЕНЬ, путь))) continue;
    итог.push(путь);
  }
  return итог;
}

const беды = [];
let проверено = 0;
for (const путь of обойти(join(КОРЕНЬ, 'src'))) {
  const текст = readFileSync(путь, 'utf8');
  проверено++;
  const строки = текст.split('\n');
  строки.forEach((строка, и) => {
    for (const знак of строка) {
      const имя = чей(знак.codePointAt(0));
      if (!имя) continue;
      беды.push({ файл: relative(КОРЕНЬ, путь), строка: и + 1, знак, имя,
        рядом: строка.slice(Math.max(0, строка.indexOf(знак) - 30), строка.indexOf(знак) + 30) });
      break;                       // по одной находке на строку -- остальное будет видно рядом
    }
  });
}

console.log(`Проверено файлов: ${проверено}`);
if (!беды.length) {
  console.log('  ✓ посторонних письменностей не найдено');
  process.exit(0);
}
for (const б of беды) {
  console.log(`  ✗ ${б.файл}:${б.строка} — ${б.имя} «${б.знак}»`);
  console.log(`      …${б.рядом}…`);
}
console.log(`\nНАЙДЕНО: ${беды.length}`);
process.exit(1);
