// GS1: КОДЫ, В КОТОРЫХ ЗАШИФРОВАНО БОЛЬШЕ, ЧЕМ НОМЕР ТОВАРА.
//
// Про товарный EAN-13 надо говорить прямо: ДАТЫ В НЁМ НЕТ. Тринадцать цифр -- это префикс
// организации, номер фирмы, номер позиции и контрольная цифра, и больше туда не помещается
// ничего. Страницы, которые обещают узнать по нему срок годности, обещают невозможное.
//
// Но на упаковке рядом с ним часто стоит ВТОРОЙ код -- длинный Code 128 или квадратный
// DataMatrix, -- и вот в нём лежит всё остальное: партия, дата изготовления, срок годности,
// вес, серийный номер. Записано это парами «код поля -- значение», где код поля называется
// идентификатором применения. Их и разбираем.
//
// Разделитель между полями переменной длины -- невидимый знак с кодом 29. Поля постоянной
// длины разделителя не имеют: их длина известна заранее, она в таблице ниже.

const РАЗДЕЛИТЕЛЬ = '\x1D';

/** Поля постоянной длины: код поля -> сколько цифр в значении. */
const ПОСТОЯННЫЕ = {
  '00': 18, '01': 14, '02': 14, '03': 14, '04': 16,
  11: 6, 12: 6, 13: 6, 14: 6, 15: 6, 16: 6, 17: 6, 18: 6, 19: 6,
  20: 2, 41: 13,
};

/** Что означает поле. Вид нужен, чтобы показать значение по-человечески. */
const ПОЛЯ = {
  '00': { имя: 'sscc' }, '01': { имя: 'gtin' }, '02': { имя: 'gtinВнутри' },
  10: { имя: 'партия' },
  11: { имя: 'изготовлено', вид: 'дата' }, 12: { имя: 'оплатитьДо', вид: 'дата' },
  13: { имя: 'упаковано', вид: 'дата' }, 15: { имя: 'лучшеДо', вид: 'дата' },
  16: { имя: 'продатьДо', вид: 'дата' }, 17: { имя: 'годенДо', вид: 'дата' },
  20: { имя: 'вариант' }, 21: { имя: 'серийный' },
  30: { имя: 'количество' }, 37: { имя: 'количество' },
  240: { имя: 'артикул' }, 241: { имя: 'артикулПоставщика' }, 250: { имя: 'серийныйВнутри' },
  400: { имя: 'заказ' }, 410: { имя: 'кудаGLN' }, 414: { имя: 'местоGLN' },
  8020: { имя: 'платёж' }, 8200: { имя: 'сайт' },
};

/** Меры: первые три цифры кода поля -> единица. Четвёртая говорит, где запятая. */
const МЕРЫ = {
  310: 'кг', 311: 'м', 312: 'м', 313: 'м', 314: 'м2', 315: 'л', 316: 'м3',
  320: 'фунт', 330: 'кг', 350: 'м2', 356: 'тр. унция', 360: 'л',
};

const мераЛи = (код) => /^3[0-6]\d\d$/.test(код) && !!МЕРЫ[код.slice(0, 3)];

/** Дата GS1: шесть цифр ГГММДД. День 00 значит «конец месяца». */
export function разобратьДату(с) {
  if (!/^\d{6}$/.test(с)) return null;
  const гг = Number(с.slice(0, 2));
  // Двузначный год по правилу GS1: ближайшие 49 лет вперёд и 50 назад от нынешнего.
  const век = гг >= 51 ? 1900 : 2000;
  const месяц = Number(с.slice(2, 4));
  const день = Number(с.slice(4, 6));
  if (месяц < 1 || месяц > 12 || день > 31) return null;
  // День 00 -- последний день месяца: нулевой день следующего и есть последний нынешнего.
  const дата = день === 0 ? new Date(век + гг, месяц, 0) : new Date(век + гг, месяц - 1, день);
  return { год: дата.getFullYear(), месяц: дата.getMonth() + 1, день: дата.getDate(),
    конецМесяца: день === 0, дата };
}

/** Мера: последняя цифра кода поля -- сколько знаков после запятой. */
function разобратьМеру(код, значение) {
  const после = Number(код[3]);
  return { число: Number(значение) / 10 ** после, единица: МЕРЫ[код.slice(0, 3)] || '' };
}

/**
 * Разбор строки GS1.
 * @returns [{код, имя, значение, вид, разбор}] либо пустой список, если строка не похожа
 *          на GS1 или разбирать в ней нечего.
 */
export function разобратьGS1(текст) {
  let с = String(текст ?? '');
  // Некоторые распознаватели ставят впереди служебную метку.
  с = с.replace(/^\]C1|^\]d2|^\]e0/, '');
  // Разделитель встречается и настоящим знаком, и записанным как <GS> в отладочных выводах.
  с = с.split('<GS>').join(РАЗДЕЛИТЕЛЬ);
  if (!/^\d{2}/.test(с)) return [];

  const итог = [];
  let и = 0;
  let охрана = 0;
  while (и < с.length && охрана++ < 64) {
    if (с[и] === РАЗДЕЛИТЕЛЬ) { и++; continue; }

    // Код поля -- от двух до четырёх цифр. Длинные пробуем первыми: 3103 важнее, чем 31.
    let код = null;
    for (const длина of [4, 3, 2]) {
      const проба = с.slice(и, и + длина);
      if (проба.length < длина || !/^\d+$/.test(проба)) continue;
      if (мераЛи(проба) || ПОЛЯ[проба] || ПОСТОЯННЫЕ[проба]) { код = проба; break; }
    }
    if (!код) break;                      // дальше не гадаем: на GS1 не похоже
    и += код.length;

    const длинаЗначения = ПОСТОЯННЫЕ[код] || (мераЛи(код) ? 6 : null);
    let значение;
    if (длинаЗначения) {
      значение = с.slice(и, и + длинаЗначения);
      и += длинаЗначения;
      if (значение.length < длинаЗначения) break;   // строка оборвалась -- это не GS1
    } else {
      const конец = с.indexOf(РАЗДЕЛИТЕЛЬ, и);
      значение = с.slice(и, конец === -1 ? undefined : конец);
      и = конец === -1 ? с.length : конец + 1;
    }
    if (!значение) break;

    const строка = { код, имя: (ПОЛЯ[код] || {}).имя || (мераЛи(код) ? 'мера' : 'иное'), значение };
    const вид = (ПОЛЯ[код] || {}).вид || (мераЛи(код) ? 'мера' : null);
    if (вид === 'дата') {
      строка.вид = 'дата';
      строка.разбор = разобратьДату(значение);
      // Шесть цифр, не складывающихся в дату, -- признак, что мы разбираем не то.
      if (!строка.разбор) return [];
    } else if (вид === 'мера') {
      строка.вид = 'мера';
      строка.разбор = разобратьМеру(код, значение);
    }
    итог.push(строка);
  }

  // Одинокий товарный номер -- это просто номер, а не разбор: голову им морочить незачем.
  if (итог.length === 1 && итог[0].имя === 'gtin') return [];
  return итог;
}
