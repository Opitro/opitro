// офлайн-режима». Для HTML и CSS такой разбор я написал сам -- там цена ошибки видна глазом.
// Для JavaScript писать его нельзя, и вот почему: сокращение имён (Mangle) требует знать
// ОБЛАСТЬ ВИДИМОСТИ каждой переменной. Без настоящего разбора нельзя отличить своё имя от
// чужого, и переименование молча ломает код -- не заметно, не сразу, а у пользователя.
//
// Terser строит синтаксическое дерево, как это делают сборщики настоящих проектов. Он весит
// 170 КБ по сети и подгружается ТОЛЬКО по нажатию кнопки: страница без него открывается
// пустой и лёгкой.
//
// Он же даёт то, что в задании названо «Syntax Guard»: при незакрытой скобке возвращает
// ошибку с номером строки и столбца, а не молчит и не портит вывод.

let движок = null;

/** Подтянуть Terser один раз за жизнь вкладки. */
async function взятьДвижок() {
  if (!движок) движок = await import('terser');
  return движок;
}

/**
 * @param {string} код
 * @param {object} наладки {комментарии, имена}
 * @returns {Promise<{код: string, беда: string|null, строка: number|null, столбец: number|null}>}
 */
export async function сжатьJS(код, наладки = {}) {
  const { комментарии = true, имена = true } = наладки;
  const текст = String(код ?? '');
  if (!текст.trim()) return { код: '', беда: null, строка: null, столбец: null };

  const { minify } = await взятьДвижок();
  try {
    const р = await minify(текст, {
      // Свёртка выражений и выброс мёртвого кода. Умолчания Terser нарочно осторожны:
      // ничего, что могло бы изменить поведение, они не делают.
      compress: true,
      mangle: имена,
      format: { comments: комментарии ? false : 'all' },
    });
    return { код: р.code ?? '', беда: null, строка: null, столбец: null };
  } catch (е) {
    return {
      код: '',
      беда: е.message || String(е),
      строка: е.line ?? null,
      столбец: е.col ?? null,
    };
  }
}

/** Тот же разбор, но без сокращения имён -- для скриптов внутри HTML. */
export const сжатьJSпросто = (код) => сжатьJS(код, { имена: false }).then((р) => {
  if (р.беда) throw new Error(р.беда);
  return р.код;
});
