/** Код страны или служебная пометка со «собачкой» впереди. Пусто -- префикс не назначен. */
export function поПрефиксу(три) {
  const н = Number(три);
  if (!Number.isInteger(н)) return '';
  for (const [от, до, код] of ПРЕФИКСЫ) if (н >= от && н <= до) return код;
  return '';
}

/**
 * Старый десятизначный ISBN из тринадцатизначного. Работает только для 978: у 979 нет
 * десятизначного соответствия, и придумывать его нельзя -- по такому номеру ничего не найдётся.
 */
export function isbn10(цифры) {
  const с = String(цифры);
  if (!/^978\d{10}$/.test(с)) return '';
  const тело = с.slice(3, 12);
  let сумма = 0;
  // Вес десять у первой цифры и далее вниз до двух; контрольная -- дополнение по модулю 11.
  for (let и = 0; и < 9; и++) сумма += (10 - и) * Number(тело[и]);
  const остаток = (11 - (сумма % 11)) % 11;
  return тело + (остаток === 10 ? 'X' : String(остаток));
}

const ДЛИНЫ = { EAN13: 13, EAN8: 8, UPCA: 12, UPCE: 8 };

/**
 * Разбор распознанного кода.
 * Возвращает {цифры, формат, контроль, страна, книга, ...}. Поля со «собачкой» -- ключи для
 * перевода на язык страницы; готовых слов здесь нет намеренно.
 */
export function разобратьШтрих(текст, формат) {
  const цифры = String(текст ?? '').replace(/\s/g, '');
  const вид = String(формат || '').toUpperCase().replace(/[-_]/g, '');
  const итог = { цифры, формат: вид, цифровой: /^\d+$/.test(цифры) };

  // CODE-128, CODE-39 и прочие непродуктовые: там внутри что угодно, страны и контроля нет.
  if (!ДЛИНЫ[вид] || !итог.цифровой || цифры.length !== ДЛИНЫ[вид]) return итог;

  // UPC-E -- сжатая запись UPC-A. Разворачивать её ради страны незачем: у всех UPC-E
  // первая цифра 0 или 1, а это в любом случае США и Канада.
  if (вид === 'UPCE') {
    итог.контроль = { сошлась: контрольнаяЦифра(цифры.slice(0, 7)) === Number(цифры[7]) };
    итог.страна = 'US';
    return итог;
  }

  const должна = контрольнаяЦифра(цифры.slice(0, -1));
  const стоит = Number(цифры[цифры.length - 1]);
  итог.контроль = { сошлась: должна === стоит, должна, стоит };

  // UPC-A -- это EAN-13 с нулём впереди, и префикс страны читается точно так же.
  const полный = вид === 'UPCA' ? '0' + цифры : цифры;
  const метка = поПрефиксу(полный.slice(0, 3));
  if (метка.startsWith('@')) {
    итог.пометка = метка.slice(1);
    if (метка === '@книга') {
      // 9790 -- это не книга, а ноты: отдельный стандарт ISMN.
      итог.пометка = полный.startsWith('9790') ? 'ноты' : 'книга';
      итог.isbn13 = полный;
      итог.isbn10 = isbn10(полный);
    }
  } else if (метка) {
    итог.страна = метка;
  }
  return итог;
}

/** Название страны на языке страницы -- силами самого браузера, без своих словарей. */
export function названиеСтраны(код, язык) {
  if (!код) return '';
  try {
    const имя = new Intl.DisplayNames([язык], { type: 'region' }).of(код);
    return имя && имя !== код ? имя : '';
  } catch (е) {
    return '';
  }
}
