// СБОРКА ФАЙЛА .ICO ИЗ ГОТОВЫХ КАРТИНОК.
//
// ICO -- не картинка, а КОНТЕЙНЕР: внутри лежит несколько изображений разного размера, и
// система берёт то, которое ей нужно. Ради этого файл и делают: в 16 пикселях мелкие детали
// логотипа превращаются в кашу, и рисунок для этого размера обычно упрощают отдельно.
//
// ПОЧЕМУ ВНУТРИ BMP, А НЕ PNG. С Windows Vista в .ico разрешено класть PNG прямо как есть, и
// так делают многие генераторы -- это проще и файл меньше. Но весь смысл .ico сегодня в
// СОВМЕСТИМОСТИ СО СТАРЫМ: современный браузер прекрасно возьмёт и favicon.svg, а .ico кладут
// в корень ради тех, кто новых форматов не понимает. Класть в файл для старых систем формат,
// который старые системы не читают, -- значит делать бесполезную работу. Поэтому здесь честный
// BMP без сжатия, как в первоначальном описании формата.
//
// Устройство файла:
//   ICONDIR       6 байт   -- сколько картинок внутри;
//   ICONDIRENTRY  16 байт  -- по одной на картинку: размер, длина, смещение;
//   данные                 -- для каждой картинки заголовок BITMAPINFOHEADER, затем точки
//                             снизу вверх в порядке синий-зелёный-красный-прозрачность, затем
//                             маска прозрачности по биту на точку.

/** Маска прозрачности: по биту на точку, строки выровнены по четыре байта, снизу вверх. */
function маска(точки, ш, в) {
  const вСтроке = Math.ceil(ш / 32) * 4;
  const итог = new Uint8Array(вСтроке * в);
  for (let y = 0; y < в; y++) {
    // Снизу вверх: BMP хранит строки в обратном порядке.
    const строка = (в - 1 - y) * вСтроке;
    for (let x = 0; x < ш; x++) {
      // Единица -- «здесь прозрачно». Ставим её только для полностью прозрачных точек:
      // полупрозрачность передаёт канал прозрачности в самих данных.
      if (точки[(y * ш + x) * 4 + 3] === 0) итог[строка + (x >> 3)] |= 0x80 >> (x & 7);
    }
  }
  return итог;
}

/** Одна картинка внутри файла: заголовок, точки, маска. */
function слой(точки, ш, в) {
  const тело = new Uint8Array(ш * в * 4);
  for (let y = 0; y < в; y++) {
    const строка = (в - 1 - y) * ш * 4;
    for (let x = 0; x < ш; x++) {
      const и = (y * ш + x) * 4;
      const о = строка + x * 4;
      // BMP хранит цвет в обратном порядке: синий, зелёный, красный.
      тело[о] = точки[и + 2];
      тело[о + 1] = точки[и + 1];
      тело[о + 2] = точки[и];
      тело[о + 3] = точки[и + 3];
    }
  }
  const м = маска(точки, ш, в);
  const шапка = new Uint8Array(40);
  const в32 = new DataView(шапка.buffer);
  в32.setUint32(0, 40, true);        // длина заголовка
  в32.setInt32(4, ш, true);          // ширина
  в32.setInt32(8, в * 2, true);      // высота ВДВОЕ: картинка и маска идут одна за другой
  в32.setUint16(12, 1, true);        // плоскостей
  в32.setUint16(14, 32, true);       // бит на точку
  в32.setUint32(16, 0, true);        // без сжатия
  в32.setUint32(20, тело.length + м.length, true);
  const кусок = new Uint8Array(шапка.length + тело.length + м.length);
  кусок.set(шапка, 0);
  кусок.set(тело, шапка.length);
  кусок.set(м, шапка.length + тело.length);
  return кусок;
}

/**
 * @param картинки -- [{точки: Uint8ClampedArray RGBA, ширина, высота}, ...]
 * @returns Uint8Array с содержимым файла .ico
 */
export function собратьIco(картинки) {
  if (!картинки.length) throw new Error('нечего складывать в ico');
  const слои = картинки.map((к) => слой(к.точки, к.ширина, к.высота));
  const началоДанных = 6 + 16 * картинки.length;

  const итог = new Uint8Array(началоДанных + слои.reduce((с, к) => с + к.length, 0));
  const в = new DataView(итог.buffer);
  в.setUint16(0, 0, true);                  // всегда ноль
  в.setUint16(2, 1, true);                  // 1 -- значок, 2 -- указатель мыши
  в.setUint16(4, картинки.length, true);

  let смещение = началоДанных;
  картинки.forEach((к, и) => {
    const о = 6 + 16 * и;
    // Размер 256 записывается нулём: в байт больше не помещается.
    итог[о] = к.ширина >= 256 ? 0 : к.ширина;
    итог[о + 1] = к.высота >= 256 ? 0 : к.высота;
    итог[о + 2] = 0;                        // цветов в палитре -- палитры нет
    итог[о + 3] = 0;
    в.setUint16(о + 4, 1, true);            // плоскостей
    в.setUint16(о + 6, 32, true);           // бит на точку
    в.setUint32(о + 8, слои[и].length, true);
    в.setUint32(о + 12, смещение, true);
    итог.set(слои[и], смещение);
    смещение += слои[и].length;
  });
  return итог;
}
