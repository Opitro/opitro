/* ТРИ ДВИЖКА ОЗВУЧКИ ЗА ОДНОЙ ДВЕРЬЮ.
 *
 * Piper, Kokoro и Supertonic считают речь по-разному, но разговаривают ОДИНАКОВО: страница
 * шлёт {тип} и получает {тип}. Здесь это сведено в одно место, чтобы страница не разбиралась,
 * какой из трёх сейчас выбран, и чтобы четвёртый добавлялся правкой одного файла.
 *
 * ЧТО ИЗМЕРЕНО (живой браузер, чистый профиль):
 *
 *   движок       вес        языки              счёт           проверено
 *   Piper       60-109 МБ   ru uk en es        быстрый        стоял и раньше
 *   Kokoro       93 МБ      только английский  6,5 с / 2,5 с  файл 111 КБ, пик 0,440
 *   Supertonic   380 МБ     31 язык, ru и uk   2,6 с / 4 с    файл 192 КБ, пик 0,459
 *
 * ВАЖНОЕ, ЧТО НАДО СКАЗАТЬ ЧЕЛОВЕКУ: вес и скорость здесь НЕ СВЯЗАНЫ. Самая тяжёлая модель
 * считает вдвое быстрее самой лёгкой. Выбирать по одному весу -- значит выбрать худшее.
 *
 * Потоки держатся по одному на движок и переживают переключение: человек, сходивший туда и
 * обратно, не ждёт повторной загрузки.
 */

const ПОТОКИ = {
  piper: () => new Worker(new URL('./tts-piper-worker.js', import.meta.url), { type: 'module' }),
  kokoro: () => new Worker(new URL('./tts-kokoro-worker.js', import.meta.url), { type: 'module' }),
  supertonic: () => new Worker(new URL('./tts-supertonic-worker.js', import.meta.url), { type: 'module' }),
};

const живые = new Map();

/** Поток нужного движка. Создаётся один раз и живёт до перезагрузки страницы. */
export function поток(движок) {
  if (живые.has(движок)) return живые.get(движок);
  const делать = ПОТОКИ[движок];
  if (!делать) throw new Error('неизвестный движок: ' + движок);
  const п = делать();
  живые.set(движок, п);
  return п;
}

/** Есть ли такой движок вообще. */
export const естьДвижок = (д) => Boolean(ПОТОКИ[д]);

/**
 * Спросить движок и дождаться ответа.
 * Сообщения о ходе идут в приХоде, итог возвращается обещанием.
 *
 * @param движок  'piper' | 'kokoro' | 'supertonic'
 * @param задание {тип, текст, голос, язык, скорость, номер}
 * @param приХоде (этап, доля) -- зовётся много раз по дороге
 */
export function спросить(движок, задание, приХоде) {
  return new Promise((готово, беда) => {
    const п = поток(движок);

    const слушать = (е) => {
      const д = е.data || {};
      if (д.тип === 'ход') { if (приХоде) приХоде(д.этап, д.доля); return; }
      п.removeEventListener('message', слушать);
      п.removeEventListener('error', наОшибку);
      if (д.тип === 'беда') беда(new Error(д.текст || 'ошибка'));
      else готово(д);
    };
    const наОшибку = (е) => {
      п.removeEventListener('message', слушать);
      п.removeEventListener('error', наОшибку);
      беда(new Error((е && е.message) || 'поток не отвечает'));
    };

    п.addEventListener('message', слушать);
    п.addEventListener('error', наОшибку);
    п.postMessage(задание);
  });
}

/**
 * Разбить длинный текст на куски по концам предложений.
 *
 * ЗАЧЕМ. Модель считает текст целиком, и на книге это десятки секунд без единого признака
 * жизни: шкала стоит, слушать нечего. Резать посреди слова нельзя -- на стыке будет щелчок
 * и оборванный слог. Режем по точке, вопросу, восклицанию и переводу строки; если предложение
 * само длиннее предела, добираем по запятой, а в крайнем случае по пробелу.
 *
 * @param текст  что читать
 * @param предел сколько знаков в куске (300 -- столько же берут авторы Supertonic)
 */
export function накуски(текст, предел = 300) {
  const с = String(текст || '').trim();
  if (!с) return [];
  if (с.length <= предел) return [с];

  // Границы предложений вместе со знаком: точка должна остаться в своём куске.
  const предложения = с.split(/(?<=[.!?…])\s+|\n+/).filter((к) => к.trim());
  const куски = [];
  let текущий = '';

  const положить = () => { if (текущий.trim()) куски.push(текущий.trim()); текущий = ''; };

  for (let п of предложения) {
    п = п.trim();
    if (!п) continue;

    // Предложение само не влезает -- добираем по запятым, потом по пробелам.
    if (п.length > предел) {
      положить();
      let остаток = п;
      while (остаток.length > предел) {
        let где = остаток.lastIndexOf(',', предел);
        if (где < предел * 0.4) где = остаток.lastIndexOf(' ', предел);
        if (где < предел * 0.4) где = предел;   // слово длиннее предела -- рвём как есть
        куски.push(остаток.slice(0, где + 1).trim());
        остаток = остаток.slice(где + 1).trim();
      }
      текущий = остаток;
      continue;
    }

    if ((текущий + ' ' + п).trim().length > предел) положить();
    текущий = текущий ? текущий + ' ' + п : п;
  }
  положить();
  return куски;
}

/**
 * Склеить куски WAV в один файл.
 * Каждый кусок приходит от движка отдельным файлом; человеку нужен один.
 */
export function склеить(куски) {
  if (!куски.length) return null;
  if (куски.length === 1) return куски[0];

  // Заголовок берём у первого: частота и разрядность у всех кусков одинаковы -- их считал
  // один и тот же движок.
  const шапка = new DataView(куски[0]);
  const частота = шапка.getUint32(24, true);
  const тел = куски.map((б) => new Uint8Array(б, 44));
  const всего = тел.reduce((с, т) => с + т.length, 0);

  const итог = new ArrayBuffer(44 + всего);
  const в = new DataView(итог);
  const строка = (сдвиг, с) => { for (let и = 0; и < с.length; и++) в.setUint8(сдвиг + и, с.charCodeAt(и)); };
  строка(0, 'RIFF'); в.setUint32(4, 36 + всего, true); строка(8, 'WAVE');
  строка(12, 'fmt '); в.setUint32(16, 16, true); в.setUint16(20, 1, true); в.setUint16(22, 1, true);
  в.setUint32(24, частота, true); в.setUint32(28, частота * 2, true);
  в.setUint16(32, 2, true); в.setUint16(34, 16, true);
  строка(36, 'data'); в.setUint32(40, всего, true);

  const куда = new Uint8Array(итог, 44);
  let сдвиг = 0;
  for (const т of тел) { куда.set(т, сдвиг); сдвиг += т.length; }
  return итог;
}
