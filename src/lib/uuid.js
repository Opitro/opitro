// ГЕНЕРАТОР UUID.
//
// ПОЧЕМУ НЕ Math.random(). Он даёт числа, которые ВЫГЛЯДЯТ случайными, но получены из
// внутреннего состояния по известному правилу: увидев несколько подряд, можно предсказать
// следующие. Для перемешивания карточек это неважно, для ключа записи -- важно: угадав
// чужой ключ, человек попадает туда, куда не должен. Поэтому берутся байты от системного
// источника случайности, того же, на котором стоят ключи шифрования.
//
// СТРОЕНИЕ. Все сто двадцать восемь бит расписаны стандартом, и два места в них -- не
// случайные, а служебные:
//   -- четыре бита версии: тринадцатый знак записи. У четвёртой версии там всегда 4;
//   -- два бита разновидности: старшие биты семнадцатого знака. Там всегда 10 в двоичном
//      виде, отчего сам знак бывает только 8, 9, a или b.
// Генератор, который этого не делает, выдаёт похожую на UUID строку, которую чужие
// библиотеки не примут.

const шестнадцать = '0123456789abcdef';

/** Случайные байты от системы. Другого источника здесь нет и быть не должно. */
function байты(сколько) {
  const б = new Uint8Array(сколько);
  crypto.getRandomValues(б);
  return б;
}

const вЗнаки = (б) => {
  let с = '';
  for (const з of б) с += шестнадцать[з >> 4] + шестнадцать[з & 15];
  return с;
};

/** Расстановка дефисов по стандарту: 8-4-4-4-12. */
const сДефисами = (с) =>
  `${с.slice(0, 8)}-${с.slice(8, 12)}-${с.slice(12, 16)}-${с.slice(16, 20)}-${с.slice(20, 32)}`;

/**
 * Четвёртая версия -- полностью случайная. Ровно то, что просят под словом UUID, если
 * версию не оговаривают отдельно.
 */
export function uuid4() {
  // Родной способ есть не везде: crypto.randomUUID работает только на защищённом
  // соединении. На http его попросту нет, и подстраховка обязательна -- иначе страница,
  // открытая через http, молча перестала бы работать.
  if (typeof crypto !== 'undefined' && crypto.randomUUID) return crypto.randomUUID();

  const б = байты(16);
  б[6] = (б[6] & 0x0f) | 0x40;      // версия 4
  б[8] = (б[8] & 0x3f) | 0x80;      // разновидность 10xx
  return сДефисами(вЗнаки(б));
}

// Счётчик на случай, когда за одну миллисекунду просят много ключей: без него они выходят
// в случайном порядке внутри миллисекунды, и главное свойство седьмой версии -- возрастание --
// теряется как раз там, где ключи создают пачками.
let прошлоеВремя = -1;
let счётчик = 0;

/**
 * Седьмая версия -- время впереди, случайность позади. Строки идут по возрастанию, и это
 * не украшение: в базе данных ключ-указатель хранится отсортированным, и случайные ключи
 * заставляют её дописывать в середину, разрывая страницы. Возрастающие ложатся в конец.
 */
export function uuid7(сейчас = Date.now()) {
  if (сейчас === прошлоеВремя) счётчик = (счётчик + 1) & 0x0fff;
  else { прошлоеВремя = сейчас; счётчик = байты(2)[0] & 0x0f; }

  const б = байты(16);
  // Сорок восемь бит времени, старшим байтом вперёд.
  б[0] = (сейчас / 2 ** 40) & 0xff;
  б[1] = (сейчас / 2 ** 32) & 0xff;
  б[2] = (сейчас / 2 ** 24) & 0xff;
  б[3] = (сейчас / 2 ** 16) & 0xff;
  б[4] = (сейчас / 2 ** 8) & 0xff;
  б[5] = сейчас & 0xff;
  // Версия и двенадцать бит счётчика -- он и держит порядок внутри миллисекунды.
  б[6] = 0x70 | ((счётчик >> 8) & 0x0f);
  б[7] = счётчик & 0xff;
  б[8] = (б[8] & 0x3f) | 0x80;      // разновидность 10xx
  return сДефисами(вЗнаки(б));
}

/** Пачка ключей нужной версии. */
export function пачка(сколько, версия = 4) {
  const н = Math.min(500, Math.max(1, Math.round(сколько) || 1));
  const итог = [];
  for (let и = 0; и < н; и++) итог.push(версия === 7 ? uuid7() : uuid4());
  return итог;
}

/** Вид записи: заглавными и без дефисов -- как просят некоторые базы данных. */
export function оформить(ключ, { заглавными = false, безДефисов = false } = {}) {
  let с = безДефисов ? ключ.replace(/-/g, '') : ключ;
  return заглавными ? с.toUpperCase() : с;
}

/**
 * Проверка записи на соответствие стандарту. Нужна не странице, а проверкам: без неё
 * «сгенерировали строку из шестнадцатеричных знаков» ничего не доказывает.
 */
export function годен(строка, версия = null) {
  const с = String(строка ?? '').trim().toLowerCase();
  const без = с.replace(/-/g, '');
  if (!/^[0-9a-f]{32}$/.test(без)) return false;
  // Дефисы либо стоят по местам, либо их нет вовсе -- третьего не дано.
  if (с.includes('-') && !/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(с)) {
    return false;
  }
  if (версия !== null && без[12] !== String(версия)) return false;
  // Разновидность: старшие биты семнадцатого знака должны читаться как 10.
  if (!'89ab'.includes(без[16])) return false;
  return true;
}
