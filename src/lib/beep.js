// КОРОТКИЙ СИГНАЛ ОБ УСПЕХЕ.
//
// Зачем он нужен: человек со сканером смотрит НА КОРОБКУ, а не на экран. Пока он ведёт
// камеру, глаза заняты кодом, и понять, что код уже прочитан, ему нечем. Звук решает это
// раньше любой подсветки рамки.
//
// Собирается на месте из генератора тона -- файл не качается, разрешений не просит.
// Звук нарочно короткий и высокий: такой не раздражает при десятке сканирований подряд.
//
// ПОЧЕМУ КОНТЕКСТ ЖИВЁТ ДОЛГО, А НЕ СОЗДАЁТСЯ НА КАЖДЫЙ ПИК. Так было сначала -- и звука
// не было слышно вовсе (владелец 12.09.2026: «я не слышу звука»). Причина: браузер отдаёт
// звук только контексту, созданному в ЖЕСТЕ человека, а код читается через полторы секунды
// после нажатия, когда жест уже «остыл». Созданный тогда контекст остаётся спящим
// (state === 'suspended'), генератор в нём работает молча, и никакой ошибки при этом нет.
//
// Поэтому: контекст заводится в момент нажатия -- подготовитьЗвук() -- и живёт до конца
// страницы. Один живой контекст безопасен; беда бывает от МНОЖЕСТВА незакрытых, а не от
// одного.

let ак = null;

/**
 * Завести звук заранее. Звать ТОЛЬКО из обработчика нажатия: в этот миг браузер даёт
 * контексту играть, и дальше он остаётся рабочим.
 */
export function подготовитьЗвук() {
  try {
    if (!ак) ак = new (window.AudioContext || window.webkitAudioContext)();
    if (ак.state === 'suspended') ак.resume();
  } catch (е) { /* звука нет -- работа от этого не встанет */ }
  return ак;
}

/** Пикнуть. Молча ничего не делает, если звук в этом браузере недоступен. */
export function пикнуть() {
  try {
    подготовитьЗвук();
    if (!ак) return;
    const ген = ак.createOscillator();
    const гром = ак.createGain();
    ген.type = 'sine';
    ген.frequency.value = 1320;
    // Начинаем и заканчиваем почти нулём: резкий старт тона даёт щелчок.
    гром.gain.setValueAtTime(0.0001, ак.currentTime);
    гром.gain.exponentialRampToValueAtTime(0.09, ак.currentTime + 0.01);
    гром.gain.exponentialRampToValueAtTime(0.0001, ак.currentTime + 0.14);
    ген.connect(гром); гром.connect(ак.destination);
    ген.start(); ген.stop(ак.currentTime + 0.15);
  } catch (е) { /* звук -- приятная мелочь, без него всё работает */ }
}

/** Для проверок: спит контекст или играет. Без него «не слышно» нечем поймать машиной. */
export function состояниеЗвука() {
  return ак ? ак.state : 'нет';
}
