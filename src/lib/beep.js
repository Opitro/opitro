//
// Зачем он нужен: человек со сканером смотрит НА КОРОБКУ, а не на экран. Пока он ведёт
// камеру, глаза заняты кодом, и понять, что код уже прочитан, ему нечем. Звук решает это
// раньше любой подсветки рамки.
//
// Собирается на месте из генератора тона -- файл не качается, разрешений не просит.
// Звук нарочно короткий и высокий: такой не раздражает при десятке сканирований подряд.
//
// Раньше эта же двадцатка строк лежала внутри сканера штрихкодов. Когда появились сканеры
// Data Matrix, PDF417 и Aztec, копировать её в каждый было нельзя -- при пяти сотнях страниц
// копии расходятся первыми.

/** Пикнуть. Молча ничего не делает, если звук в этом браузере недоступен. */
export function пикнуть() {
  try {
    const ак = new (window.AudioContext || window.webkitAudioContext)();
    const ген = ак.createOscillator();
    const гром = ак.createGain();
    ген.type = 'sine';
    ген.frequency.value = 1320;
    // Начинаем и заканчиваем почти нулём: резкий старт тона даёт щелчок.
    гром.gain.setValueAtTime(0.0001, ак.currentTime);
    гром.gain.exponentialRampToValueAtTime(0.08, ак.currentTime + 0.01);
    гром.gain.exponentialRampToValueAtTime(0.0001, ак.currentTime + 0.12);
    ген.connect(гром); гром.connect(ак.destination);
    ген.start(); ген.stop(ак.currentTime + 0.13);
    // Закрываем: незакрытые контексты на iPhone копятся и однажды перестают открываться.
    setTimeout(() => ак.close(), 400);
  } catch (е) { /* звук -- приятная мелочь, без него всё работает */ }
}
