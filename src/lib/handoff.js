// ПЕРЕДАЧА РАБОТЫ НА СОСЕДНЮЮ СТРАНИЦУ.
//
// «Убрать голос» и «убрать музыку» -- две страницы под два разных запроса, но для человека
// это один инструмент. Поэтому при переходе с ним едет всё, что уже сделано: исходный файл
// и, если расчёт прошёл, обе готовые дорожки. Соседняя страница подхватывает и показывает
// результат сразу -- заново грузить и считать не нужно.
//
// Ничего никуда не отправляется: всё лежит в хранилище браузера на этом же устройстве.
// Запись живёт до подхвата и в любом случае протухает через десять минут -- чужой файл не
// должен всплыть сам собой через час.

const БАЗА = 'opitro-handoff';
const СКЛАД = 'работа';
const ЖИЗНЬ = 10 * 60 * 1000;

function открыть() {
  return new Promise((готово, беда) => {
    const зпр = indexedDB.open(БАЗА, 1);
    зпр.onupgradeneeded = () => {
      const db = зпр.result;
      if (!db.objectStoreNames.contains(СКЛАД)) db.createObjectStore(СКЛАД);
    };
    зпр.onsuccess = () => готово(зпр.result);
    зпр.onerror = () => беда(зпр.error);
  });
}

function действие(режим, дело) {
  return открыть().then((db) => new Promise((готово, беда) => {
    const т = db.transaction(СКЛАД, режим);
    const зпр = дело(т.objectStore(СКЛАД));
    зпр.onsuccess = () => готово(зпр.result);
    зпр.onerror = () => беда(зпр.error);
  }));
}

/**
 * Отложить работу для соседней страницы.
 * `запас` -- все уже посчитанные способы: { light: {музыка, голос}, browser: {...} }. Едут все,
 * чтобы соседняя страница не считала заново то, что уже сделано.
 * @param {{имя:string, файл:Blob, запас?:Object, способ?:string}} что
 */
export async function отложить(что) {
  try {
    await действие('readwrite', (склад) => склад.put({ ...что, когда: Date.now() }, 'текущая'));
    return true;
  } catch (e) { return false; }
}

/**
 * Забрать отложенную работу. Забирается ОДИН раз: сразу после чтения запись стирается,
 * иначе она всплывёт при следующем заходе на страницу.
 */
export async function забрать() {
  try {
    const что = await действие('readonly', (склад) => склад.get('текущая'));
    await действие('readwrite', (склад) => склад.delete('текущая'));
    if (!что) return null;
    if (Date.now() - (что.когда || 0) > ЖИЗНЬ) return null;
    return что;
  } catch (e) { return null; }
}
