
export function сшить(строки) {
  const годные = строки.filter((с) => (с.текст || '').trim() && с.место);
  if (!годные.length) return [];

  const высоты = годные.map((с) => с.место.в).sort((а, б) => а - б);
  const высота = высоты[высоты.length >> 1] || 0.02;
  const правыйКрай = Math.max(...годные.map((с) => с.место.х + с.место.ш));
  const левыйКрай = Math.min(...годные.map((с) => с.место.х));
  const ширинаБлока = Math.max(0.05, правыйКрай - левыйКрай);

  const недоходПредел = ширинаБлока * 0.25;

  const зазоры = [];
  for (let и = 1; и < годные.length; и++) {
    зазоры.push(годные[и].место.у - (годные[и - 1].место.у + годные[и - 1].место.в));
  }
  const поПорядку = зазоры.filter((з) => з >= 0).sort((а, б) => а - б);
  const типовойЗазор = поПорядку.length ? поПорядку[поПорядку.length >> 1] : высота * 0.3;
  const зазорПредел = Math.max(типовойЗазор * 1.6, высота * 0.25);

  const абзацы = [];
  let текущий = null;
  for (let и = 0; и < годные.length; и++) {
    const с = годные[и], т = с.текст.trim();
    if (!текущий) { текущий = { текст: т, строки: [с] }; continue; }
    const пред = годные[и - 1].место, этот = с.место;
    const продолжение =
      правыйКрай - (пред.х + пред.ш) <= недоходПредел
      && этот.у - (пред.у + пред.в) <= зазорПредел
      && этот.х <= левыйКрай + высота * 1.5;
    if (!продолжение) { абзацы.push(текущий); текущий = { текст: т, строки: [с] }; continue; }

    текущий.текст = /[-‐-—]$/.test(текущий.текст)
      ? текущий.текст.replace(/[-‐-—]$/, '') + т
      : текущий.текст + ' ' + т;
    текущий.строки.push(с);
  }
  if (текущий) абзацы.push(текущий);
  return абзацы;
}
