/**
 * СТРОКИ В АБЗАЦЫ.
 *
 * И распознаватель снимка, и текстовый слой PDF отдают текст ПОЛОСАМИ: по строке на каждую
 * строку листа. Показать их как есть -- значит выдать столбик обрывков: договор, набранный
 * сплошным текстом, выглядит списком из сорока строчек, и читать его нельзя. Владелец так и
 * сказал: «пиши как текст, а не столбиком отсканированный».
 *
 * Сшиваем ПО ГЕОМЕТРИИ, а не по знакам препинания: строка, дошедшая до правого поля,
 * оборвалась не сама -- её перенесли, и следующая её продолжает. Строка, кончившаяся заметно
 * раньше поля, -- конец абзаца. По той же причине этикетка, ценник и вывеска, где каждая
 * надпись короткая и сама по себе, остаются отдельными строками: до правого поля они не
 * доходят, сшивать нечего.
 *
 * Общий файл на две страницы -- сканер текста с фото и извлечение текста из PDF. Правка здесь
 * задевает обе: после неё гонять `npm run check:text-scan` и `npm run check:pdf-text`.
 *
 * @param {Array<{текст: string, место: {х: number, у: number, ш: number, в: number}}>} строки
 *        Места -- В ДОЛЯХ листа или снимка, не в точках: мерки тогда одинаковы для страницы
 *        формата A4 и для фотографии в двенадцать мегапикселей.
 * @returns {Array<{текст: string, строки: Array}>} Абзац помнит, из каких строк он сложен:
 *        по ним зажигается подсветка на снимке.
 */
export function сшить(строки) {
  const годные = строки.filter((с) => (с.текст || '').trim() && с.место);
  if (!годные.length) return [];
  // Высота строки -- мерка для всех расстояний: «близко» на снимке крупным планом и на снимке
  // целой страницы означает разное число точек, а в высотах строк -- одно и то же.
  const высоты = годные.map((с) => с.место.в).sort((а, б) => а - б);
  const высота = высоты[высоты.length >> 1] || 0.02;
  const правыйКрай = Math.max(...годные.map((с) => с.место.х + с.место.ш));
  const левыйКрай = Math.min(...годные.map((с) => с.место.х));
  const ширинаБлока = Math.max(0.05, правыйКрай - левыйКрай);

  // НЕДОХОД ДО ПРАВОГО ПОЛЯ МЕРЯЕМ ОТ ШИРИНЫ БЛОКА, А НЕ ОТ ВЫСОТЫ СТРОКИ.
  //
  // ЗАМЕРЫ, на которых выбран порог (доли листа, оба сняты живьём):
  //   текстовый слой PDF -- перенесённые строки 0,016 и 0,024, конец абзаца 0,73;
  //   фотография листа  -- перенесённые 0,006-0,120, конец абзаца 0,77.
  //
  // Верхние 0,12 на фотографии -- не промах распознавателя, а обычное дело: если следующее
  // слово длинное, строка кончается заметно раньше поля. Поэтому порог в одно слово (0,1)
  // рвал такие абзацы пополам, а прежний порог в одну высоту строки (около 0,018) рвал их
  // почти всегда.
  //
  // Четверть ширины блока стоит С ЗАПАСОМ ОТ ОБЕИХ СТОРОН: вдвое больше самого широкого
  // перенесённого хвоста и втрое меньше самого узкого конца абзаца.
  //
  // ЧЕГО ЭТО НЕ РЕШАЕТ. Абзац, последняя строка которого занимает больше трёх четвертей
  // ширины, геометрией от переноса не отличить вовсе -- никаким порогом. Такие случаи ловит
  // второй признак, зазор (ниже), и только если между абзацами есть отступ.
  const недоходПредел = ширинаБлока * 0.25;

  // ВТОРОЙ ПРИЗНАК -- ЗАЗОР. Между абзацами он заметно больше, чем между строками одного:
  // на том же договоре 0,0117 против 0,0034. Берём типичный зазор по документу и считаем
  // разрывом всё, что в полтора раза больше. Само по себе это слабый признак (во многих
  // документах отступов между абзацами нет вовсе), поэтому он идёт В ДОПОЛНЕНИЕ к недоходу.
  const зазоры = [];
  for (let и = 1; и < годные.length; и++) {
    зазоры.push(годные[и].место.у - (годные[и - 1].место.у + годные[и - 1].место.в));
  }
  const поПорядку = зазоры.filter((з) => з >= 0).sort((а, б) => а - б);
  const типовойЗазор = поПорядку.length ? поПорядку[поПорядку.length >> 1] : высота * 0.3;
  const зазорПредел = Math.max(типовойЗазор * 1.6, высота * 0.25);

  const абзацы = [];
  let текущий = null;
  for (let и = 0; и < годные.length; и++) {
    const с = годные[и], т = с.текст.trim();
    if (!текущий) { текущий = { текст: т, строки: [с] }; continue; }
    const пред = годные[и - 1].место, этот = с.место;
    const продолжение =
      правыйКрай - (пред.х + пред.ш) <= недоходПредел   // прошлая дошла до правого поля
      && этот.у - (пред.у + пред.в) <= зазорПредел      // эта идёт сразу под ней
      && этот.х <= левыйКрай + высота * 1.5;            // и начинается от левого поля
    if (!продолжение) { абзацы.push(текущий); текущий = { текст: т, строки: [с] }; continue; }
    // Перенос по слогам: чёрточку в конце строки убираем и склеиваем слово обратно.
    текущий.текст = /[-‐-—]$/.test(текущий.текст)
      ? текущий.текст.replace(/[-‐-—]$/, '') + т
      : текущий.текст + ' ' + т;
    текущий.строки.push(с);
  }
  if (текущий) абзацы.push(текущий);
  return абзацы;
}
