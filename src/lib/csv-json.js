
const КАВЫЧКА = '"';

export function угадатьРазделитель(текст) {
  const кусок = текст.slice(0, 65536);
  const счёт = { ',': 0, ';': 0, '\t': 0, '|': 0 };
  let вКавычках = false;
  for (let и = 0; и < кусок.length; и++) {
    const з = кусок[и];
    if (з === КАВЫЧКА) { вКавычках = !вКавычках; continue; }
    if (!вКавычках && з in счёт) счёт[з]++;
  }
  let лучший = ',';
  for (const з of Object.keys(счёт)) if (счёт[з] > счёт[лучший]) лучший = з;
  return счёт[лучший] ? лучший : ',';
}

export function разобратьCSV(исходный, разделитель = ',') {

  let текст = String(исходный ?? '').replace(/^﻿/, '');
  if (!текст.trim()) return { таблица: [] };

  const таблица = [];
  let строка = [];
  let поле = '';
  let вКавычках = false;
  let былоПоле = false;
  let номерСтроки = 1;

  const закрытьПоле = () => { строка.push(поле); поле = ''; былоПоле = false; };
  const закрытьСтроку = () => {
    закрытьПоле();

    if (!(строка.length === 1 && строка[0] === '')) таблица.push(строка);
    строка = [];
  };

  for (let и = 0; и < текст.length; и++) {
    const з = текст[и];

    if (вКавычках) {
      if (з === КАВЫЧКА) {
        if (текст[и + 1] === КАВЫЧКА) { поле += КАВЫЧКА; и++; }
        else вКавычках = false;
      } else {
        if (з === '\n') номерСтроки++;
        поле += з;
      }
      continue;
    }

    if (з === КАВЫЧКА) {
      if (поле !== '' ) {
        return { ошибка: { текст: 'Кавычка посреди поля: если она нужна как знак, её удваивают', строка: номерСтроки } };
      }
      вКавычках = true;
      былоПоле = true;
      continue;
    }
    if (з === разделитель) { закрытьПоле(); былоПоле = true; continue; }
    if (з === '\r') { if (текст[и + 1] === '\n') и++; закрытьСтроку(); номерСтроки++; continue; }
    if (з === '\n') { закрытьСтроку(); номерСтроки++; continue; }
    поле += з;
    былоПоле = true;
  }
  if (вКавычках) return { ошибка: { текст: 'Кавычка не закрыта до конца файла', строка: номерСтроки } };
  if (поле !== '' || былоПоле || строка.length) закрытьСтроку();
  return { таблица };
}

export function умноеЗначение(с) {
  if (/^(true|false)$/i.test(с)) return с.toLowerCase() === 'true';
  if (с === '') return '';

  const н = Number(с);
  if (!Number.isNaN(н) && String(н) === с) return н;
  return с;
}

export function вJSON(таблица, { заголовки = true, умныеТипы = true } = {}) {
  const значение = умныеТипы ? умноеЗначение : (с) => с;
  if (!таблица.length) return { значение: [], колонок: 0, строк: 0 };
  if (!заголовки) {
    return {
      значение: таблица.map((р) => р.map(значение)),
      колонок: Math.max(...таблица.map((р) => р.length)),
      строк: таблица.length,
    };
  }
  const имена = таблица[0].map((и, н) => (i(и) ? и : `поле${н + 1}`));
  function i(с) { return String(с).trim() !== ''; }

  const занято = new Map();
  const ключи = имена.map((и) => {
    const было = занято.get(и) || 0;
    занято.set(и, было + 1);
    return было ? `${и}_${было + 1}` : и;
  });
  const из = [];
  for (let р = 1; р < таблица.length; р++) {
    const объект = {};
    for (let к = 0; к < ключи.length; к++) объект[ключи[к]] = значение(таблица[р][к] ?? '');
    из.push(объект);
  }
  return { значение: из, колонок: ключи.length, строк: из.length, ключи };
}

function расплющить(значение, приставка, куда) {
  if (значение === null || typeof значение !== 'object') {
    куда[приставка] = значение;
    return;
  }
  if (Array.isArray(значение)) {
    if (!значение.length) { куда[приставка] = ''; return; }
    значение.forEach((з, и) => расплющить(з, приставка ? `${приставка}.${и}` : String(и), куда));
    return;
  }
  const ключи = Object.keys(значение);
  if (!ключи.length) { куда[приставка] = ''; return; }
  for (const к of ключи) расплющить(значение[к], приставка ? `${приставка}.${к}` : к, куда);
}

const НАДО_КАВЫЧКИ = (с, разделитель) =>
  с.includes(разделитель) || с.includes(КАВЫЧКА) || /[\r\n]/.test(с);

export function вCSV(значение, { разделитель = ',', перенос = '\r\n', заголовки = true } = {}) {
  let ряды;
  if (Array.isArray(значение)) ряды = значение;
  else if (значение && typeof значение === 'object') ряды = [значение];
  else return { ошибка: 'Для таблицы нужен массив объектов или объект, а здесь одно значение' };
  if (!ряды.length) return { csv: '', строк: 0, колонок: 0 };

  const плоские = ряды.map((р) => {
    const куда = {};
    if (р === null || typeof р !== 'object') куда['значение'] = р;
    else расплющить(р, '', куда);
    return куда;
  });

  const колонки = [];
  const виденные = new Set();
  for (const п of плоские) {
    for (const к of Object.keys(п)) if (!виденные.has(к)) { виденные.add(к); колонки.push(к); }
  }

  const клетка = (з) => {
    if (з === null || з === undefined) return '';
    const с = typeof з === 'string' ? з : String(з);
    return НАДО_КАВЫЧКИ(с, разделитель)
      ? КАВЫЧКА + с.split(КАВЫЧКА).join(КАВЫЧКА + КАВЫЧКА) + КАВЫЧКА
      : с;
  };
  const строки = [];
  if (заголовки) строки.push(колонки.map(клетка).join(разделитель));
  for (const п of плоские) строки.push(колонки.map((к) => клетка(п[к])).join(разделитель));
  return { csv: строки.join(перенос), строк: плоские.length, колонок: колонки.length };
}
