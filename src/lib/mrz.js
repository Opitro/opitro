/**
 * РАЗБОР MRZ -- ДВУХ ИЛИ ТРЁХ СТРОК ВНИЗУ ПАСПОРТА, ВИЗЫ, ID-КАРТЫ.
 *
 * Чем эта страница отличается от всех остальных сканеров: ответ здесь ДОКАЗУЕМ. В MRZ
 * вписаны контрольные цифры, посчитанные по весам 7-3-1, и мы их пересчитываем. Если цифра
 * сошлась -- поле прочитано верно, и это не «кажется», а арифметика. Поэтому распознавание
 * букв тут можно чинить самим: там, где по стандарту стоит цифра, «O» обязана быть нулём.
 *
 * Стандарт: ИКАО Doc 9303. Виды, какие бывают:
 *   TD1  -- 3 строки по 30 знаков (пластиковые ID-карты, виды на жительство)
 *   TD2  -- 2 строки по 36 (старые удостоверения, некоторые визы -- MRV-B)
 *   TD3  -- 2 строки по 44 (паспорта, визы MRV-A)
 *
 * Ничего никуда не отправляется: и распознавание, и разбор идут в браузере. Для страницы с
 * паспортом это не красивые слова, а условие, без которого её нельзя делать вовсе.
 */
import { двеБуквы, БЕЗ_СТРАНЫ } from './mrz-countries.js';

const ВЕСА = [7, 3, 1];

/** Цена знака в контрольной сумме: цифра -- сама собой, буква -- по месту в алфавите, «<» -- ноль. */
function цена(знак) {
  if (знак === '<') return 0;
  if (знак >= '0' && знак <= '9') return знак.charCodeAt(0) - 48;
  if (знак >= 'A' && знак <= 'Z') return знак.charCodeAt(0) - 55;
  return 0;
}

/** Контрольная цифра по весам 7-3-1 -- та самая, что печатают следом за полем. */
export function контрольная(кусок) {
  let сумма = 0;
  for (let i = 0; i < кусок.length; i++) сумма += цена(кусок[i]) * ВЕСА[i % 3];
  return String(сумма % 10);
}

/**
 * Что распознаватель путает чаще всего. Слева -- как увидено, справа -- как должно быть.
 * Разложено на две таблицы: в числовом поле буквы быть не может, в буквенном -- цифры.
 * Это не угадывание: место знака задано стандартом жёстко, и контрольная цифра потом
 * скажет, помогла правка или нет.
 */
const В_ЦИФРУ = { O: '0', Q: '0', D: '0', U: '0', I: '1', L: '1', T: '7', Z: '2', S: '5', B: '8', G: '6', A: '4', E: '8' };
const В_БУКВУ = { 0: 'O', 1: 'I', 2: 'Z', 5: 'S', 8: 'B', 6: 'G', 4: 'A' };

const толькоЦифры = (с) => [...с].map((з) => В_ЦИФРУ[з] || з).join('');
const толькоБуквы = (с) => [...с].map((з) => В_БУКВУ[з] || з).join('');

/**
 * ПОДБОР ПО КОНТРОЛЬНОЙ ЦИФРЕ -- то, ради чего эти цифры и придуманы.
 *
 * Номер документа бывает смешанным («L898902C3»), и там ни буквы, ни цифры не запретишь.
 * Если контрольная цифра не сошлась, перебираем спорные знаки (O против 0, I против 1…) и
 * смотрим, при каком написании арифметика сходится. Подошёл ровно один вариант -- значит
 * прочитано верно, и это доказано, а не угадано. Подошло несколько -- молчим и оставляем
 * как было: выбирать наугад в документе нельзя.
 */
const СПОРНЫЕ = { O: '0', 0: 'O', I: '1', 1: 'I', S: '5', 5: 'S', B: '8', 8: 'B',
  Z: '2', 2: 'Z', G: '6', 6: 'G', Q: '0', D: '0', U: '0', A: '4', 4: 'A' };
const ПРЕДЕЛ_ПЕРЕБОРА = 1 << 12;   // дальше перебор дороже, чем польза от него

export function подобрать(кусок, цифра, только = 'любой') {
  if (контрольная(кусок) === цифра) return { строка: кусок, подобрано: false };
  const места = [];
  for (let i = 0; i < кусок.length; i++) {
    const замена = СПОРНЫЕ[кусок[i]];
    if (!замена) continue;
    // В поле, где по стандарту только цифры, подбирать можно лишь «букву -> цифру». Иначе
    // подбор замаскирует настоящую ошибку: испорченную дату он «починит» буквой, и человек
    // решит, что документ в порядке.
    if (только === 'цифры' && !(замена >= '0' && замена <= '9')) continue;
    места.push(i);
  }
  if (!места.length || (1 << места.length) > ПРЕДЕЛ_ПЕРЕБОРА) return { строка: кусок, подобрано: false };
  // Подходящих написаний обычно несколько -- но одно из них отличается от прочитанного
  // ОДНОЙ правкой, а остальные тремя. Верим наименьшей правке: распознаватель ошибается
  // редко, и сразу три ошибки в одном поле куда менее вероятны, чем одна. Если наименьших
  // поровну -- молчим и оставляем как было: выбирать наугад в документе нельзя.
  let лучшее = null, правок = 99, поровну = false;
  for (let маска = 1; маска < (1 << места.length); маска++) {
    const знаки = [...кусок];
    let сколькоПравок = 0;
    for (let i = 0; i < места.length; i++) {
      if (маска & (1 << i)) { знаки[места[i]] = СПОРНЫЕ[кусок[места[i]]]; сколькоПравок++; }
    }
    if (сколькоПравок > правок) continue;
    const вариант = знаки.join('');
    if (контрольная(вариант) !== цифра) continue;
    if (сколькоПравок < правок) { лучшее = вариант; правок = сколькоПравок; поровну = false; }
    else if (вариант !== лучшее) поровну = true;
  }
  return лучшее && !поровну ? { строка: лучшее, подобрано: true } : { строка: кусок, подобрано: false };
}

/** Обрезать хвост из «<» -- в MRZ ими добивают поле до нужной длины. */
const обрезать = (с) => с.replace(/<+$/, '');

/**
 * Привести распознанное к виду MRZ: заглавные латинские, цифры и «<».
 * Пробелы выкидываем: их в MRZ нет вовсе, а распознаватель любит их придумывать.
 * Кириллические двойники («А», «В», «С», «Е»…) переводим в латиницу: человек мог вставить
 * строку руками, скопировав её из чужого места.
 */
const ДВОЙНИКИ = { А: 'A', В: 'B', С: 'C', Е: 'E', Н: 'H', К: 'K', М: 'M', О: 'O', Р: 'P', Т: 'T', У: 'Y', Х: 'X', І: 'I' };
export function причесать(строка) {
  return String(строка || '')
    .toUpperCase()
    .replace(/[«»]/g, '<')
    .split('').map((з) => ДВОЙНИКИ[з] || з).join('')
    .replace(/[^A-Z0-9<]/g, '');
}

/**
 * Выбрать из распознанного текста сами строки MRZ.
 *
 * Распознаватель приносит и лишнее: обрывок имени над зоной, «1» от края страницы, случайную
 * точку. Поэтому берём только строки длиной от 28 знаков, где больше половины -- знаки MRZ, и
 * подрезаем их до положенной длины: у образца с телефона впереди прилипала лишняя единица.
 */
export function вытащитьСтроки(текст) {
  const все = String(текст || '').split(/[\r\n]+/).map(причесать).filter((с) => с.length >= 28);
  if (!все.length) return [];
  // Длина MRZ известна заранее. Если строка длиннее -- ищем в ней кусок, который начинается
  // с осмысленного знака: у TD3 это «P», у TD1/TD2 -- буква вида документа.
  const подрезать = (с, длина) => {
    if (с.length <= длина) return с;
    const с_конца = с.slice(с.length - длина);
    const с_начала = с.slice(0, длина);
    // Строка имён кончается «<», строка данных -- цифрой. Берём ту, что кончается «правильно».
    return /[<0-9]$/.test(с_конца) ? с_конца : с_начала;
  };
  const длинная = Math.max(...все.map((с) => с.length));
  const длина = длинная >= 42 ? 44 : (длинная >= 34 ? 36 : 30);
  return все.map((с) => подрезать(с, длина)).filter((с) => с.length >= длина - 2);
}

/** Дата из шести цифр. Век выбираем по смыслу поля: рождение -- позади, срок -- впереди. */
function датой(шесть, вперёд) {
  if (!/^\d{6}$/.test(шесть)) return null;
  const гг = +шесть.slice(0, 2), мм = +шесть.slice(2, 4), дд = +шесть.slice(4, 6);
  if (мм < 1 || мм > 12 || дд < 1 || дд > 31) return null;
  const сейчас = new Date().getFullYear();
  const двузначный = сейчас % 100;
  // Срок действия: 25 -- это 2025, а не 1925. День рождения: 25 -- это 2025 только если год
  // ещё не наступил, иначе 1925. Порог в стандарте не задан, берём здравый смысл.
  const год = вперёд
    ? 2000 + гг
    : (гг > двузначный + 5 ? 1900 + гг : 2000 + гг);
  const д = new Date(Date.UTC(год, мм - 1, дд));
  if (д.getUTCMonth() !== мм - 1 || д.getUTCDate() !== дд) return null;
  return { год, месяц: мм, день: дд, iso: `${год}-${String(мм).padStart(2, '0')}-${String(дд).padStart(2, '0')}` };
}

/** Имена: «ФАМИЛИЯ<<ИМЯ<ОТЧЕСТВО» -- две угловые скобки делят фамилию и остальное. */
function именами(кусок) {
  const чистый = обрезать(кусок);
  const [фам, прочее = ''] = чистый.split('<<');
  return {
    фамилия: фам.replace(/</g, ' ').trim(),
    имена: прочее.split('<').filter(Boolean).join(' ').trim(),
  };
}

const ПОЛЫ = { M: 'м', F: 'ж', '<': '', X: '' };

/**
 * Разобрать ГОТОВЫЕ строки MRZ.
 * Возвращаем: вид, поля, список проверок (каждая -- со своим именем и итогом) и сами строки
 * после правок. Ничего не прячем: если цифра не сошлась, так и говорим -- поле показываем, но
 * помечаем. Врать «всё в порядке» на документе нельзя.
 */
export function разобратьСтроки(строки) {
  const с = (строки || []).map(причесать).filter(Boolean);
  if (с.length < 2) return { вышло: false, причина: 'мало' };

  const длина = с[0].length;
  let вид = '';
  if (с.length >= 3 && длина >= 28 && длина <= 31) вид = 'TD1';
  else if (длина >= 34 && длина <= 37) вид = с[0][0] === 'V' ? 'MRV-B' : 'TD2';
  else if (длина >= 42 && длина <= 45) вид = с[0][0] === 'V' ? 'MRV-A' : 'TD3';
  else return { вышло: false, причина: 'непонятно' };

  const проверки = [];
  /**
   * Проверить поле и, если цифра не сошлась, попробовать подобрать спорные знаки.
   * Возвращаем строку, какую считаем верной: подобранную или исходную.
   */
  const проверить = (имя, кусок, цифра, только) => {
    const { строка, подобрано } = подобрать(кусок, цифра, только);
    const ок = контрольная(строка) === цифра;
    проверки.push({ имя, ок, подобрано, ждали: контрольная(кусок), было: цифра });
    return { ок, строка };
  };

  let поля = {}, строкаДанных = '', строкаИмён = '';

  if (вид === 'TD1') {
    const [а, б, в] = с;
    const номер = а.slice(5, 14);
    const рожд = толькоЦифры(б.slice(0, 6));
    const срок = толькоЦифры(б.slice(8, 14));
    поля = {
      документ: обрезать(а.slice(0, 2)),
      выдан: а.slice(2, 5),
      номер: обрезать(номер),
      гражданство: б.slice(15, 18),
      рождение: датой(рожд, false),
      пол: ПОЛЫ[б[7]] ?? '',
      срок: датой(срок, true),
      ещё: обрезать(а.slice(15, 30) + б.slice(18, 29)),
      ...именами(в),
    };
    // Показываем ПОДОБРАННОЕ написание там, где оно доказано контрольной цифрой.
    поля.номер = обрезать(проверить('номер', номер, толькоЦифры(а[14])).строка);
    проверить('рождение', рожд, толькоЦифры(б[6]), 'цифры');
    проверить('срок', срок, толькоЦифры(б[14]), 'цифры');
    const номерТД1 = (поля.номер + '<'.repeat(9)).slice(0, 9);
    проверить('всё вместе', номерТД1 + а.slice(14, 30) + рожд + б.slice(6, 7) + срок + б.slice(14, 15) + б.slice(18, 29), толькоЦифры(б[29]));
    строкаДанных = а + '\n' + б; строкаИмён = в;
  } else {
    const [а, б] = с;
    const узкий = вид === 'TD2' || вид === 'MRV-B';
    const имёнДо = узкий ? 36 : 44;
    const номер = б.slice(0, 9);
    const рожд = толькоЦифры(б.slice(13, 19));
    const срок = толькоЦифры(б.slice(21, 27));
    поля = {
      документ: обрезать(а.slice(0, 2)),
      выдан: а.slice(2, 5),
      номер: обрезать(номер),
      гражданство: б.slice(10, 13),
      рождение: датой(рожд, false),
      пол: ПОЛЫ[б[20]] ?? '',
      срок: датой(срок, true),
      ...именами(а.slice(5, имёнДо)),
    };
    поля.номер = обрезать(проверить('номер', номер, толькоЦифры(б[9])).строка);
    проверить('рождение', рожд, толькоЦифры(б[19]), 'цифры');
    проверить('срок', срок, толькоЦифры(б[27]), 'цифры');
    if (вид === 'TD3') {
      const личный = б.slice(28, 42);
      поля.личный = обрезать(личный);
      // Личный номер бывает пустым, и тогда его контрольная цифра -- «<» или «0». Это по
      // стандарту законно, и придираться к такому полю нельзя.
      const цифраЛичного = б[42];
      if (обрезать(личный) || (цифраЛичного !== '<' && цифраЛичного !== '0')) {
        поля.личный = обрезать(проверить('личный номер', личный, толькоЦифры(цифраЛичного)).строка);
      }
      const собрано = (поля.номер + '<'.repeat(9)).slice(0, 9) + б.slice(9, 10)
        + рожд + б.slice(19, 20) + срок + б.slice(27, 28)
        + ((поля.личный || '') + '<'.repeat(14)).slice(0, 14) + б.slice(42, 43);
      проверить('всё вместе', собрано, толькоЦифры(б[43]));
    } else if (вид === 'TD2') {
      поля.ещё = обрезать(б.slice(28, 35));
      проверить('всё вместе', (поля.номер + '<'.repeat(9)).slice(0, 9) + б.slice(9, 10)
        + рожд + б.slice(19, 20) + срок + б.slice(27, 28) + б.slice(28, 35), толькоЦифры(б[35]));
    } else {
      // У виз общей контрольной цифры нет вовсе -- проверять нечего, и выдумывать не будем.
      поля.ещё = обрезать(б.slice(28, узкий ? 36 : 44));
    }
    строкаДанных = б; строкаИмён = а;
  }

  поля.странаВыдачи = двеБуквы(поля.выдан);
  поля.странаГражданства = двеБуквы(поля.гражданство);
  поля.безГражданства = БЕЗ_СТРАНЫ.includes(поля.гражданство);
  поля.видДокумента = поля.документ;

  const сошлось = проверки.every((п) => п.ок);
  return {
    вышло: true, вид, поля, проверки, сошлось,
    строки: вид === 'TD1' ? с.slice(0, 3) : с.slice(0, 2),
    строкаДанных, строкаИмён,
  };
}

/** Разобрать распознанный текст целиком: сначала выбрать строки MRZ, потом разобрать. */
export function разобратьМрз(текст) {
  const строки = вытащитьСтроки(текст);
  if (строки.length < 2) return { вышло: false, причина: 'мало' };
  return разобратьСтроки(строки);
}

/**
 * Просрочен ли документ. Отдельно от разбора: это не то, что записано в MRZ, а вывод из
 * даты, и человеку его показывают словами, а не числом.
 */
export function просрочен(срок, сегодня = new Date()) {
  if (!срок || !срок.iso) return null;
  const д = new Date(срок.iso + 'T23:59:59Z');
  return д.getTime() < сегодня.getTime();
}
