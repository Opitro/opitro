// СИНТЕЗ РЕЧИ МОДЕЛЬЮ KOKORO -- в стороне от страницы.
//
// Договор сообщений ТОТ ЖЕ, что у tts-piper-worker.js: {тип} туда, {тип} обратно. Страница
// не знает, с каким движком разговаривает, и переключение между ними ей ничего не стоит.
//
// ЧТО ИЗМЕРЕНО В ЖИВОМ БРАУЗЕРЕ, а не взято из описаний:
//   -- голосов 28, ВСЕ АНГЛИЙСКИЕ (en-us 20, en-gb 8). Испанские лежат в хранилище, но
//      обёртка kokoro-js 1.2.1 их не знает: вызов ef_dora отвергается словами «голос не
//      найден». Поэтому языки этой модели -- только английский, и на странице она предлагается
//      только там, где это уместно;
//   -- при dtype 'q8' скачивается model_quantized.onnx, 93 МБ. Не 82: восемьдесят два весит
//      другой файл (q8f16), и библиотека его не берёт;
//   -- счёт на обычном процессоре: 6,5 секунды на 2,55 секунды звука.
//
// Модель кладётся в хранилище браузера самой библиотекой (Cache API). Текст никуда не уходит:
// его некуда отправлять, весь расчёт здесь.

const АДРЕС_БИБЛИОТЕКИ = 'https://cdn.jsdelivr.net/npm/kokoro-js@1.2.1/+esm';
const ХРАНИЛИЩЕ = 'onnx-community/Kokoro-82M-v1.0-ONNX';

const шли = (весть, перенос) => self.postMessage(весть, перенос || []);

let модель = null;
let грузится = null;

/** Есть ли видеокарта. С ней счёт заметно быстрее, без неё считает процессор. */
async function естьВидеокарта() {
  try {
    if (!self.navigator || !self.navigator.gpu) return false;
    const п = await self.navigator.gpu.requestAdapter();
    return Boolean(п);
  } catch (е) { return false; }
}

async function готовая(приХоде) {
  if (модель) return модель;
  if (грузится) return грузится;

  грузится = (async () => {
    const { KokoroTTS } = await import(АДРЕС_БИБЛИОТЕКИ);
    const видеокарта = await естьВидеокарта();
    модель = await KokoroTTS.from_pretrained(ХРАНИЛИЩЕ, {
      // На видеокарте берём точные веса, на процессоре -- сжатые: иначе счёт становится
      // невыносимо долгим. Так же поступает живой сторонний сайт с этой моделью.
      dtype: видеокарта ? 'fp32' : 'q8',
      device: видеокарта ? 'webgpu' : 'wasm',
      progress_callback: (п) => {
        if (!п || п.status !== 'progress' || !п.total) return;
        приХоде(Math.min(100, (п.loaded / п.total) * 100));
      },
    });
    return модель;
  })();

  try { return await грузится; } finally { грузится = null; }
}

/** Отсчёты в файл WAV: страница ждёт готовые байты, как от Piper. */
function вWav(отсчёты, частота) {
  const н = отсчёты.length;
  const буфер = new ArrayBuffer(44 + н * 2);
  const в = new DataView(буфер);
  const строка = (сдвиг, с) => { for (let и = 0; и < с.length; и++) в.setUint8(сдвиг + и, с.charCodeAt(и)); };
  строка(0, 'RIFF'); в.setUint32(4, 36 + н * 2, true); строка(8, 'WAVE');
  строка(12, 'fmt '); в.setUint32(16, 16, true); в.setUint16(20, 1, true); в.setUint16(22, 1, true);
  в.setUint32(24, частота, true); в.setUint32(28, частота * 2, true);
  в.setUint16(32, 2, true); в.setUint16(34, 16, true);
  строка(36, 'data'); в.setUint32(40, н * 2, true);
  for (let и = 0; и < н; и++) {
    // Обрезаем по краям, иначе громкий кусок завернётся и щёлкнет.
    const з = Math.max(-1, Math.min(1, отсчёты[и]));
    в.setInt16(44 + и * 2, з < 0 ? з * 0x8000 : з * 0x7fff, true);
  }
  return буфер;
}

self.onmessage = async (е) => {
  const д = е.data || {};
  try {
    if (д.тип === 'что-скачано') {
      // У этой модели голоса не качаются по одному: файл один на всех.
      шли({ тип: 'что-скачано', список: модель ? ['kokoro'] : [] });
      return;
    }

    if (д.тип === 'забыть') {
      модель = null;
      // Библиотека держит файл в Cache API под своим именем -- вычищаем по имени хранилища.
      if (self.caches) {
        for (const имя of await self.caches.keys()) {
          const х = await self.caches.open(имя);
          for (const з of await х.keys()) {
            if (з.url.includes('Kokoro-82M')) await х.delete(з);
          }
        }
      }
      шли({ тип: 'забыто', голос: д.голос, список: [] });
      return;
    }

    if (д.тип === 'скачать') {
      шли({ тип: 'ход', этап: 'скачивание', доля: 0 });
      await готовая((доля) => шли({ тип: 'ход', этап: 'скачивание', доля }));
      шли({ тип: 'готов', голос: д.голос, список: ['kokoro'] });
      return;
    }

    if (д.тип === 'синтез') {
      шли({ тип: 'ход', этап: 'подготовка', доля: 0 });
      const м = await готовая((доля) => шли({ тип: 'ход', этап: 'скачивание', доля }));
      шли({ тип: 'ход', этап: 'синтез', доля: 0 });
      const начало = performance.now();
      const звук = await м.generate(д.текст, {
        voice: д.голос || 'af_heart',
        speed: д.скорость && д.скорость > 0 ? д.скорость : 1,
      });
      const байты = вWav(звук.audio, звук.sampling_rate);
      шли({
        тип: 'готово',
        байты,
        секунд: (performance.now() - начало) / 1000,
        список: ['kokoro'],
      }, [байты]);
      return;
    }
  } catch (ошибка) {
    // Недогруженная модель не должна застревать: следующая попытка начинает заново.
    модель = null;
    грузится = null;
    шли({ тип: 'беда', текст: String((ошибка && (ошибка.message || ошибка)) || 'ошибка') });
  }
};
