/**
 * ВЫБОР ФАЙЛА БЕЗ ПОЛЯ НА СТРАНИЦЕ.
 *
 * Спрятанный `<input type="file">` -- давняя беда, и владелец ловил её трижды: на странице
 * метаданных, на сканере MRZ и на сканере цвета. Safari (прежде всего на iPhone) рисует
 * такому полю собственную кнопку, и она всплывает ПОВЕРХ страницы и ездит за прокруткой. Ни
 * `display: none`, ни увод за край с `clip-path` его не останавливают -- проверено, обе меры
 * стояли, а кнопка всё равно появлялась.
 *
 * Поэтому поля на странице нет вовсе. Оно создаётся в миг нажатия, открывает выбор и тут же
 * удаляется: рисовать браузеру нечего. Заодно исчезает вечная возня с `value = ''` -- поле
 * каждый раз новое, и один и тот же файл можно выбрать дважды подряд.
 *
 * Возвращает файл (или список при `многие: true`), либо null, если человек передумал.
 */
export function выбратьФайл({ берём = 'image/*', многие = false, съёмка = '' } = {}) {
  return new Promise((готово) => {
    const поле = document.createElement('input');
    поле.type = 'file';
    if (берём) поле.accept = берём;
    if (многие) поле.multiple = true;
    // capture просит телефон открыть сразу камеру, а не галерею.
    if (съёмка) поле.setAttribute('capture', съёмка);
    // Живёт доли секунды и всё равно за краем экрана: пусть его не видно и в эти доли.
    поле.style.cssText = 'position:fixed;left:-10000px;top:0;width:1px;height:1px;opacity:0;pointer-events:none';
    document.body.appendChild(поле);

    let отдано = false;
    const отдать = (что) => {
      if (отдано) return;
      отдано = true;
      // Убираем поле СЛЕДУЮЩИМ шагом: браузер ещё дочитывает выбранное из него.
      setTimeout(() => { try { поле.remove(); } catch (е) {} }, 0);
      готово(что);
    };

    поле.addEventListener('change', () => {
      const файлы = поле.files ? Array.from(поле.files) : [];
      отдать(многие ? файлы : (файлы[0] || null));
    }, { once: true });
    // Человек закрыл окно выбора -- отвечаем пустым, чтобы вызывающий не ждал вечно.
    поле.addEventListener('cancel', () => отдать(многие ? [] : null), { once: true });
    // Запасной выход: не во всех браузерах есть событие 'cancel'. Возврат на страницу без
    // выбора -- тот же отказ. Ждём ПОЛТОРЫ СЕКУНДЫ, а не миг: браузер отдаёт фокус раньше,
    // чем дочитывает выбранный файл, и на коротком ожидании настоящий выбор объявлялся
    // отказом -- поймано пробой, где файл выбирается мгновенно.
    window.addEventListener('focus', () => {
      setTimeout(() => { if (!поле.files || !поле.files.length) отдать(многие ? [] : null); }, 1500);
    }, { once: true });

    поле.click();
  });
}
