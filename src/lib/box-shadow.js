// СБОРКА СТРОКИ box-shadow.
//
// Тень в CSS -- это пять чисел и цвет: сдвиг по горизонтали, сдвиг по вертикали, размытие,
// растяжение и, если нужно, слово inset. Слоёв может быть сколько угодно, они пишутся через
// запятую, и ПОРЯДОК ВАЖЕН: первый слой лежит поверх остальных.
//
// Здесь только правила записи. Показывает браузер -- значит и проверить правильность можно
// им же, а не своим кодом.

import { вHex, вСтрокуRgb } from './color-convert.js';

/** Цвет слоя: плотный -- коротким HEX, с прозрачностью -- через rgba. */
function записьЦвета(цвет) {
  const a = цвет.a ?? 1;
  return a >= 1 ? вHex({ ...цвет, a: 1 }) : вСтрокуRgb(цвет);
}

/** Один слой в записи CSS. */
export function слойВСтроку(слой) {
  const части = [
    `${Math.round(слой.x)}px`,
    `${Math.round(слой.y)}px`,
    `${Math.round(слой.размытие)}px`,
    `${Math.round(слой.растяжение)}px`,
    записьЦвета(слой.цвет),
  ];
  // Слово inset стандарт разрешает ставить и в начале, и в конце. Пишем впереди: так его
  // видно сразу, не дочитывая строку до конца, а в многослойной тени это важно.
  return (слой.внутрь ? 'inset ' : '') + части.join(' ');
}

/** Вся тень целиком. Слои идут в том же порядке, в каком заданы: первый -- поверх. */
export function вСтроку(слои) {
  if (!слои || !слои.length) return 'none';
  return слои.map(слойВСтроку).join(', ');
}

/** Готовая строка для вставки в стили. */
export function кодCSS(слои) {
  return `box-shadow: ${вСтроку(слои)};`;
}

/**
 * Готовая мягкая тень из нескольких слоёв.
 *
 * Одиночная тень выглядит наклейкой: у настоящей тени край у самого предмета резкий, а чем
 * дальше, тем более размытый и слабый. Набирается это несколькими слоями -- ближним плотным
 * и дальними размытыми, у которых плотность падает быстрее, чем растёт размытие.
 *
 * @param сила -- 1..5, насколько предмет «приподнят».
 */
export function мягкаяТень(сила = 3, цвет = { r: 0, g: 0, b: 0 }) {
  const с = Math.min(5, Math.max(1, Math.round(сила)));
  const слои = [];
  for (let и = 1; и <= 3; и++) {
    const шаг = и * с;
    слои.push({
      x: 0,
      y: шаг,
      размытие: шаг * 2,
      растяжение: -Math.round(шаг / 3),
      // Дальние слои заметно слабее ближних: иначе тень выходит грязной.
      цвет: { ...цвет, a: Math.round((0.14 / и) * 100) / 100 },
      внутрь: false,
    });
  }
  return слои;
}
