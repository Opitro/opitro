// СБОРКА ФАЙЛА .htaccess.
//
// Это самый опасный инструмент на сайте. Ошибка в нём не портит вид страницы -- она кладёт
// чужой сайт целиком: либо ответом 500 на каждый запрос, либо вечным кругом перенаправлений,
// из которого браузер выходит с «слишком много переадресаций». Поэтому здесь больше осторожности,
// чем сжатия, и каждое правило завёрнуто в проверку наличия модуля.
//
// ЧЕТЫРЕ БЕДЫ, КОТОРЫЕ ЗДЕСЬ ОБОЙДЕНЫ. Их выдают почти все готовые генераторы:
//
//   1. ВЕЧНЫЙ КРУГ ЗА ПОСРЕДНИКОМ. Когда сайт стоит за Cloudflare или подобным, шифрование
//      обрывается на посреднике, и до Apache запрос доходит обычным. Правило «если не https,
//      перенаправить на https» тогда срабатывает ВСЕГДА, и сайт уходит в бесконечный круг.
//      Лечится взглядом на заголовок X-Forwarded-Proto.
//   2. ДВА ПЕРЕНАПРАВЛЕНИЯ ПОДРЯД. Отдельное правило на схему и отдельное на www дают
//      http://www.сайт -> https://www.сайт -> https://сайт. Два прыжка вместо одного: медленнее
//      для человека и хуже для поиска. Здесь схема и хост правятся ОДНИМ правилом.
//   3. ЗАЩИТА ОТ ХОТЛИНКА, КОТОРАЯ БЬЁТ ПО СВОИМ. Наивное правило запрещает картинки при
//      пустом источнике перехода -- то есть при прямом открытии картинки, при сохранении её
//      на диск и у тех, кто отключил передачу источника. И заодно закрывает картинки от
//      поиска по картинкам. Здесь пустой источник и поисковики разрешены.
//   4. ЗАПРЕТ АДРЕСА НА ЧУЖОМ НАРЕЧИИ. У Apache 2.2 это «Deny from», у 2.4 -- «Require not ip».
//      Написать одно там, где ждут другое, значит получить 500. Здесь пишутся оба, каждое под
//      своей проверкой наличия модуля.

const ЩИТ = /[.^$*+?()[\]{}|\\]/g;
const защитить = (с) => String(с).replace(ЩИТ, '\\$&');

// Хост: буквы, цифры, дефисы, точки. Точку в конце и подчёркивания не принимаем.
const ХОСТ = /^(?=.{1,253}$)([a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/i;

const IPv4 = /^(25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)(\.(25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)){3}$/;

/** Проверка записи адреса: IPv4, IPv6 и обе с длиной приставки. */
export function годенАдрес(строка) {
  const с = String(строка || '').trim();
  if (!с) return false;
  const [тело, приставка, лишнее] = с.split('/');
  if (лишнее !== undefined) return false;
  if (приставка !== undefined && !/^\d{1,3}$/.test(приставка)) return false;
  const н = приставка === undefined ? null : Number(приставка);
  if (IPv4.test(тело)) return н === null || (н >= 0 && н <= 32);
  // IPv6 проверяем самим браузером, если он есть: свой разбор двоеточий врёт на сокращениях.
  if (тело.includes(':')) {
    if (н !== null && (н < 0 || н > 128)) return false;
    if (typeof URL === 'function') {
      try { return new URL(`http://[${тело}]/`).hostname === `[${тело.toLowerCase()}]`; }
      catch (е) { return false; }
    }
    return /^[0-9a-f:]+$/i.test(тело) && (тело.match(/::/g) || []).length <= 1;
  }
  return false;
}

/** Разбор списка адресов: возвращает годные и негодные отдельно. */
export function разобратьАдреса(текст) {
  const строки = String(текст || '').split(/[\n,;]+/).map((с) => с.trim()).filter(Boolean);
  const годные = [], негодные = [];
  for (const с of строки) (годенАдрес(с) ? годные : негодные).push(с);
  return { годные: [...new Set(годные)], негодные };
}

/** Проверка пары «старый путь -> новый адрес» для своих перенаправлений. */
export function проверитьПеренос(откуда, куда) {
  const о = String(откуда || '').trim();
  const к = String(куда || '').trim();
  if (!о && !к) return { пусто: true };
  if (!о) return { беда: 'НЕТ_СТАРОГО' };
  if (!к) return { беда: 'НЕТ_НОВОГО' };
  if (!о.startsWith('/')) return { беда: 'СТАРЫЙ_БЕЗ_КОСОЙ' };
  // Управляющие знаки и пробелы в правиле рвут строку настроек, и Apache отвечает 500.
  if (/[\s\x00-\x1f]/.test(о) || /[\s\x00-\x1f]/.test(к)) return { беда: 'ПРОБЕЛ_ИЛИ_УПРАВЛЯЮЩИЙ' };
  if (!/^(https?:\/\/\S+|\/\S*)$/i.test(к)) return { беда: 'НОВЫЙ_НЕ_АДРЕС' };
  return { годно: true, откуда: о, куда: к };
}

// Шапка нарочно короткая: длинная занимала всё окно вывода, и сами правила приходилось
// искать прокруткой -- а смотрят люди именно на них.
const ЗАГОЛОВОК = (когда) => [
  '# Настройки Apache (.htaccess), собраны на opitro.com' + (когда ? ', ' + когда : '') + '.',
  '# Класть в КОРЕНЬ сайта -- туда же, где index.php или index.html',
  '# (public_html, www или httpdocs). Действует на эту папку и все вложенные.',
  '# ПЕРЕД ЗАМЕНОЙ СОХРАНИТЕ ПРЕЖНИЙ ФАЙЛ: откатиться потом будет нечем.',
];

/**
 * Собрать текст файла.
 * @param {object} н наладки
 * @returns {{код: string, беды: string[], заметки: string[]}}
 */
export function собрать(н = {}) {
  const {
    домен = '', https = false, зеркала = 'нет', заПосредником = false,
    листинг = false, адреса = '', хотлинк = false,
    сжатие = false, кэш = false, переносы = [], дата = '',
  } = н;

  const беды = [];
  const заметки = [];
  const части = [];

  const д = String(домен || '').trim().toLowerCase().replace(/^https?:\/\//, '').replace(/\/.*$/, '');
  const нуженДомен = зеркала !== 'нет' || хотлинк;
  if (нуженДомен && !д) беды.push('НЕТ_ДОМЕНА');
  else if (д && !ХОСТ.test(д)) беды.push('ПЛОХОЙ_ДОМЕН');

  // Приводим домен к виду без www: направление задаётся отдельно.
  const голый = д.replace(/^www\./, '');
  const канон = зеркала === 'с-www' ? 'www.' + голый : голый;

  const { годные: адресаГодные, негодные: адресаПлохие } = разобратьАдреса(адреса);
  if (адресаПлохие.length) беды.push('ПЛОХОЙ_АДРЕС:' + адресаПлохие.slice(0, 3).join(', '));

  const переносыГодные = [];
  for (const п of переносы || []) {
    const р = проверитьПеренос(п.откуда, п.куда);
    if (р.пусто) continue;
    if (р.беда) { беды.push(р.беда + ':' + (п.откуда || п.куда)); continue; }
    переносыГодные.push(р);
  }

  if (беды.length) return { код: '', беды, заметки };

  // ---- Переписывание адресов -----------------------------------------------------------
  const переписи = [];

  if (переносыГодные.length) {
    переписи.push('  # Свои перенаправления. Стоят ПЕРВЫМИ нарочно: если новый адрес указан');
    переписи.push('  # полностью, человек попадает на место за один прыжок, а не за два.');
    for (const п of переносыГодные) {
      const путь = защитить(п.откуда.replace(/^\//, '').replace(/\/$/, ''));
      // Хвостовая косая необязательна: /о и /о/ должны вести в одно место.
      переписи.push(`  RewriteRule ^${путь}/?$ ${п.куда} [R=301,L]`);
    }
    переписи.push('');
  }

  const правимСхему = https;
  const правимХост = зеркала !== 'нет';

  if (правимСхему || правимХост) {
    const цель = правимСхему ? 'https' : '%{REQUEST_SCHEME}';
    const кудаХост = правимХост ? канон : '%{HTTP_HOST}';

    if (правимСхему && заПосредником) {
      // Отдельная пометка нужна потому, что «защищено» здесь складывается из двух условий,
      // а у Apache условия с [OR] группируются попарно: третье условие пришлось бы писать
      // так, что смысл менялся бы на обратный. Пометка разрывает этот узел.
      переписи.push('  # Сайт стоит за посредником (Cloudflare и подобные): до Apache запрос');
      переписи.push('  # доходит обычным, даже когда человек пришёл по https. Без этой проверки');
      переписи.push('  # правило ниже срабатывало бы всегда и увело сайт в вечный круг.');
      переписи.push('  RewriteCond %{HTTPS} =on [OR]');
      переписи.push('  RewriteCond %{HTTP:X-Forwarded-Proto} =https');
      переписи.push('  RewriteRule ^ - [E=OPITRO_SSL:1]');
      переписи.push('');
    }

    переписи.push('  # Схема и хост правятся ОДНИМ правилом: два отдельных дали бы два');
    переписи.push('  # перенаправления подряд.');
    // Условия копим парами «текст, свои пометки», чтобы [OR] дописывался к пометкам, а не
    // приклеивался к строке как придётся.
    const условия = [];
    if (правимХост) условия.push([`%{HTTP_HOST} !^${защитить(канон)}$`, ['NC']]);
    if (правимСхему) {
      условия.push(заПосредником
        ? ['%{ENV:OPITRO_SSL} !=1', []]
        : ['%{HTTPS} !=on', []]);
    }
    // Перенаправлять надо, если ЛИБО хост чужой, ЛИБО схема не та. У Apache [OR] связывает
    // условие со следующим; при двух условиях это ровно «или», без ловушек со скобками.
    for (let и = 0; и < условия.length; и++) {
      const [текст, пометки] = условия[и];
      const все = и < условия.length - 1 ? [...пометки, 'OR'] : пометки;
      переписи.push(`  RewriteCond ${текст}${все.length ? ` [${все.join(',')}]` : ''}`);
    }
    переписи.push(`  RewriteRule ^ ${цель}://${кудаХост}%{REQUEST_URI} [R=301,L]`);
    переписи.push('');
  }

  if (хотлинк) {
    переписи.push('  # Защита от хотлинка -- запрет чужим сайтам показывать ваши картинки у себя.');
    переписи.push('  # Пустой источник перехода РАЗРЕШЁН: это прямое открытие картинки, сохранение');
    переписи.push('  # её на диск и те люди, у кого передача источника отключена. Запрет по пустому');
    переписи.push('  # источнику -- самая частая ошибка в таких правилах.');
    переписи.push('  RewriteCond %{HTTP_REFERER} !^$');
    переписи.push(`  RewriteCond %{HTTP_REFERER} !^https?://([^/]+\\.)?${защитить(голый)}(/|$) [NC]`);
    переписи.push('  # Поиск по картинкам не трогаем: закрыться от него значит потерять переходы.');
    переписи.push('  RewriteCond %{HTTP_REFERER} !^https?://([^/]+\\.)?(google|bing|yandex|duckduckgo|yahoo)\\. [NC]');
    переписи.push('  RewriteRule \\.(jpe?g|png|gif|webp|avif|svg|bmp|ico)$ - [F,NC]');
    переписи.push('');
  }

  if (переписи.length) {
    части.push([
      '<IfModule mod_rewrite.c>',
      '  RewriteEngine On',
      '',
      ...переписи,
    ].join('\n').replace(/\n+$/, '') + '\n</IfModule>');
  }

  // ---- Запрет по адресу ------------------------------------------------------------------
  if (адресаГодные.length) {
    const блок = [];
    блок.push('# Запрет доступа с указанных адресов.');
    блок.push('# Наречий два: у Apache 2.4 это Require, у 2.2 -- Order/Deny. Написан каждый');
    блок.push('# под своей проверкой, поэтому файл годится и там и там.');
    блок.push('<IfModule mod_authz_core.c>');
    блок.push('  <RequireAll>');
    блок.push('    Require all granted');
    for (const а of адресаГодные) блок.push(`    Require not ip ${а}`);
    блок.push('  </RequireAll>');
    блок.push('</IfModule>');
    блок.push('<IfModule !mod_authz_core.c>');
    блок.push('  Order allow,deny');
    блок.push('  Allow from all');
    for (const а of адресаГодные) блок.push(`  Deny from ${а}`);
    блок.push('</IfModule>');
    части.push(блок.join('\n'));
    заметки.push('АДРЕС_НЕ_ЗАЩИТА');
  }

  // ---- Список файлов в папке -------------------------------------------------------------
  if (листинг) {
    части.push([
      '# Запрет показывать содержимое папки, в которой нет index-файла.',
      '# Если хозяин площадки не разрешил менять Options, эта строка даёт 500 -- тогда',
      '# уберите её и попросите поддержку включить AllowOverride Options.',
      'Options -Indexes',
    ].join('\n'));
    заметки.push('ОПЦИИ_МОГУТ_ДАТЬ_500');
  }

  // ---- Сжатие ------------------------------------------------------------------------------
  if (сжатие) {
    части.push([
      '# Сжатие ответа. Картинки, видео и звук сюда не входят: они уже сжаты,',
      '# и повторное сжатие только тратит время сервера.',
      '<IfModule mod_deflate.c>',
      '  AddOutputFilterByType DEFLATE text/html text/plain text/xml text/css',
      '  AddOutputFilterByType DEFLATE application/javascript application/x-javascript text/javascript',
      '  AddOutputFilterByType DEFLATE application/json application/xml application/rss+xml',
      '  AddOutputFilterByType DEFLATE image/svg+xml application/x-font-ttf font/otf font/ttf',
      '</IfModule>',
    ].join('\n'));
  }

  // ---- Хранение в браузере ------------------------------------------------------------------
  if (кэш) {
    части.push([
      '# Сроки хранения в браузере.',
      '# У самих страниц срок НУЛЕВОЙ, и это важно: страница с долгим сроком не обновится',
      '# у вернувшегося человека, сколько бы вы её ни правили. Долгий срок -- только для',
      '# картинок, стилей и шрифтов, имя которых меняется при каждой сборке.',
      '<IfModule mod_expires.c>',
      '  ExpiresActive On',
      '  ExpiresDefault "access plus 1 week"',
      '  ExpiresByType text/html "access plus 0 seconds"',
      '  ExpiresByType image/jpeg "access plus 1 year"',
      '  ExpiresByType image/png "access plus 1 year"',
      '  ExpiresByType image/gif "access plus 1 year"',
      '  ExpiresByType image/webp "access plus 1 year"',
      '  ExpiresByType image/avif "access plus 1 year"',
      '  ExpiresByType image/svg+xml "access plus 1 year"',
      '  ExpiresByType image/x-icon "access plus 1 year"',
      '  ExpiresByType text/css "access plus 1 month"',
      '  ExpiresByType application/javascript "access plus 1 month"',
      '  ExpiresByType text/javascript "access plus 1 month"',
      '  ExpiresByType font/woff2 "access plus 1 year"',
      '  ExpiresByType font/woff "access plus 1 year"',
      '</IfModule>',
    ].join('\n'));
  }

  if (!части.length) return { код: '', беды: ['НИЧЕГО_НЕ_ВЫБРАНО'], заметки };

  const код = [ЗАГОЛОВОК(дата).join('\n'), '', ...части].join('\n\n').replace(/\n{3,}/g, '\n\n') + '\n';
  return { код, беды: [], заметки };
}
