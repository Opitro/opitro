// ЭКРАНИРОВАНИЕ И РАЗЭКРАНИРОВАНИЕ HTML.
//
// ДВЕ ЛОВУШКИ, НА КОТОРЫХ ЛОМАЮТСЯ ТАКИЕ ИНСТРУМЕНТЫ:
//
// 1. ПОРЯДОК ЗАМЕН. Амперсанд надо заменять ПЕРВЫМ. Если сперва превратить «<» в «&lt;», а
//    потом взяться за амперсанды, то только что поставленный амперсанд превратится в «&amp;»,
//    и выйдет «&amp;lt;» -- на странице человек увидит «&lt;» вместо «<». Здесь замена идёт
//    одним проходом по знакам, и такой беды не бывает вовсе.
//
// 2. ЧЕМ РАЗЭКРАНИРОВАТЬ. Ходовой приём -- положить строку в innerHTML обычного узла и взять
//    textContent. Так делать нельзя: разметка при этом РАЗБИРАЕТСЯ, из строки рождаются
//    настоящие узлы, и картинка с onerror уже пытается загрузиться. Здесь строка кладётся в
//    <textarea>: внутри него содержимое читается как чистый текст, теги узлами не становятся,
//    а мнемоники раскрываются -- все две с лишним тысячи, как их знает сам браузер.
//
// И ЕЩЁ ОДНО, ПРО АПОСТРОФ. Мнемоники &apos; в HTML 4 не существовало -- её ввели только в
// XML и в HTML5. Старые браузеры показывали её как есть, буквами. Поэтому апостроф здесь
// кодируется числом: &#39; понимают все и всегда.

const ОПАСНЫЕ = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
};

/**
 * Экранировать. По умолчанию трогаются только те пять знаков, что несут разметку.
 * @param {string} текст
 * @param {{всеНеASCII?: boolean}} наладки
 */
export function закодировать(текст, наладки = {}) {
  const { всеНеASCII = false } = наладки;
  let итог = '';
  // Идём по знакам, а не набором замен друг за другом: один проход не может испортить то,
  // что сам же поставил.
  for (const знак of String(текст ?? '')) {
    if (ОПАСНЫЕ[знак]) { итог += ОПАСНЫЕ[знак]; continue; }
    const код = знак.codePointAt(0);
    if (всеНеASCII && код > 127) { итог += `&#${код};`; continue; }
    итог += знак;
  }
  return итог;
}

/**
 * Разэкранировать. Разбор ведёт сам браузер, но в безопасном месте -- внутри <textarea>.
 * @param {string} текст
 */
export function раскодировать(текст) {
  const с = String(текст ?? '');
  if (!с) return '';
  if (typeof document === 'undefined') throw new Error('НУЖЕН_БРАУЗЕР');
  // Узел не добавляется в страницу и живёт ровно один вызов.
  const поле = document.createElement('textarea');
  поле.innerHTML = с;
  return поле.value;
}

/** Пересчёт: сколько знаков изменилось. Нужно строке отчёта, а не самому преобразованию. */
export function сколькоТронуто(было, стало) {
  if (было === стало) return 0;
  let счёт = 0;
  for (const знак of было) if (ОПАСНЫЕ[знак]) счёт++;
  return счёт;
}

/** Есть ли в строке хоть одна мнемоника -- по этому решаем, что человек хочет раскодировать. */
export function естьМнемоники(текст) {
  return /&(#\d+|#x[0-9a-f]+|[a-z][a-z0-9]{1,31});/i.test(String(текст ?? ''));
}
