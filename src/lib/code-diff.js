/* ТО, ЧТО НУЖНО ТОЛЬКО ПРИ СРАВНЕНИИ КОДА.
 *
 * Сам поиск различий лежит в diff.js и общий с страницей сравнения текстов. Здесь -- две
 * вещи, которых у прозы быть не должно.
 *
 * 1. ПОИСК НЕВИДИМЫХ ЗНАКОВ. Строки на вид одинаковые, а сравнение говорит «разные» --
 *    почти всегда виноват знак, которого не видно: отступ табом вместо пробелов, пробел в
 *    конце строки, метка порядка байтов в начале файла, неразрывный пробел из редактора.
 *
 *    ПРО КОНЦЫ СТРОК ОТДЕЛЬНО, И ЭТО ВАЖНО. Поле ввода в браузере САМО приводит CRLF к LF --
 *    измерено: textarea.value отдаёт LF, как бы текст туда ни попал. Значит, две вещи:
 *      -- из содержимого поля концы строк узнать НЕЛЬЗЯ, только из сырого текста вставки
 *         (clipboardData не выравнивается);
 *      -- разные концы строк НЕ МОГУТ быть причиной отличий на этой странице: поле их
 *         сравняло. Писать «вот почему у вас разное» было бы неправдой. Мы сообщаем это как
 *         факт о самих файлах: здесь не мешает, а в git и в редакторе покажет весь файл
 *         изменённым.
 *
 * 2. СБОРКА ПАТЧА в обычном виде unified diff -- того самого, который понимают patch и git.
 *    Прозе он не нужен, коду нужен постоянно.
 */

/** Знак неразрывного пробела: на вид пробел, для сравнения -- другой знак. */
const НЕРАЗРЫВНЫЙ = ' ';
const МЕТКА_ПОРЯДКА = '﻿';

/**
 * Что невидимого есть в тексте.
 * Возвращает только факты, без советов: советы складывает страница.
 */
export function невидимое(текст) {
  const с = String(текст ?? '');
  const строки = с.split(/\r\n|\r|\n/);
  return {
    crlf: /\r\n/.test(с),
    cr: /\r(?!\n)/.test(с),
    lf: /(?<!\r)\n/.test(с),
    табы: строки.some((с2) => /^\s*\t/.test(с2)),
    пробелыОтступ: строки.some((с2) => /^ +\S/.test(с2)),
    хвосты: строки.filter((с2) => /[ \t]+$/.test(с2)).length,
    метка: с.startsWith(МЕТКА_ПОРЯДКА),
    неразрывные: (с.match(new RegExp(НЕРАЗРЫВНЫЙ, 'g')) || []).length,
  };
}

/** Каким знаком заканчиваются строки в СЫРОМ тексте (до того, как поле его выровняло). */
export function видКонцов(сырое) {
  const н = невидимое(сырое);
  if (!н.crlf && !н.cr && !н.lf) return null;   // одна строка -- судить не о чем
  const части = [н.crlf && 'CRLF', н.cr && 'CR', н.lf && 'LF'].filter(Boolean);
  return части.join('+');
}

/**
 * Чем два текста отличаются НЕВИДИМО. Каждая находка -- пара [ключ, подробность],
 * подпись к ключу подставляет страница на своём языке.
 *
 * @param концы  {а, б} -- концы строк из СЫРОГО текста вставки. Из содержимого поля их
 *               не узнать: браузер выравнивает CRLF к LF. Если человек набирал руками,
 *               а не вставлял, тут будет null -- и мы про концы строк молчим, а не выдумываем.
 */
export function невидимыеРазличия(а, б, концы = {}) {
  const на = невидимое(а);
  const нб = невидимое(б);
  const находки = [];

  if (концы.а && концы.б && концы.а !== концы.б) {
    находки.push(['концы', `${концы.а} / ${концы.б}`]);
  } else if ((концы.а && концы.а.includes('+')) || (концы.б && концы.б.includes('+'))) {
    находки.push(['концыСмешаны', концы.а && концы.а.includes('+') ? концы.а : концы.б]);
  }

  // Таб против пробелов -- только если один текст отступает так, а другой иначе.
  if (на.табы !== нб.табы && (на.табы || нб.табы)) {
    находки.push(['отступы', на.табы ? 'таб / пробелы' : 'пробелы / таб']);
  }

  const хвосты = на.хвосты + нб.хвосты;
  if (хвосты) находки.push(['хвосты', String(хвосты)]);

  if (на.метка !== нб.метка) находки.push(['метка', на.метка ? '1' : '2']);

  const неразрывные = на.неразрывные + нб.неразрывные;
  if (неразрывные) находки.push(['неразрывные', String(неразрывные)]);

  return находки;
}

/**
 * Собрать патч в виде unified diff.
 * @param куски  результат сравнения по строкам
 * @param имена  {а, б} -- как назвать стороны в шапке
 * @param рядом  сколько неизменных строк оставлять вокруг правки
 */
export function патч(куски, имена = { а: 'a', б: 'b' }, рядом = 3) {
  // Расставляем номера строк: они нужны в заголовке каждого куска.
  let на = 0; let нб = 0;
  const ряд = куски.map((к) => {
    if (к.вид === 'равно') return { ...к, на: ++на, нб: ++нб };
    if (к.вид === 'удалено') return { ...к, на: ++на, нб: null };
    return { ...к, на: null, нб: ++нб };
  });

  const правки = ряд.map((к, и) => (к.вид === 'равно' ? -1 : и)).filter((и) => и >= 0);
  if (!правки.length) return '';

  // Собираем участки: правка плюс несколько строк вокруг. Соседние участки сливаем.
  const участки = [];
  for (const и of правки) {
    const от = Math.max(0, и - рядом);
    const до = Math.min(ряд.length - 1, и + рядом);
    const последний = участки[участки.length - 1];
    if (последний && от <= последний.до + 1) последний.до = Math.max(последний.до, до);
    else участки.push({ от, до });
  }

  const строки = [`--- ${имена.а}`, `+++ ${имена.б}`];
  for (const { от, до } of участки) {
    const кусок = ряд.slice(от, до + 1);
    const первыйА = кусок.find((к) => к.на !== null);
    const первыйБ = кусок.find((к) => к.нб !== null);
    const сколькоА = кусок.filter((к) => к.на !== null).length;
    const сколькоБ = кусок.filter((к) => к.нб !== null).length;
    строки.push(`@@ -${первыйА ? первыйА.на : 0},${сколькоА}`
      + ` +${первыйБ ? первыйБ.нб : 0},${сколькоБ} @@`);
    for (const к of кусок) {
      if (к.вид === 'равно') строки.push(' ' + к.а);
      else if (к.вид === 'удалено') строки.push('-' + к.а);
      else строки.push('+' + к.б);
    }
  }
  return строки.join('\n');
}

/**
 * Разложить куски на участки для показа: правки с несколькими строками вокруг, а длинные
 * одинаковые промежутки -- в свёрнутый вид. На файле в тысячу строк с одной правкой человеку
 * незачем листать девятьсот девяносто девять одинаковых.
 */
export function участки(куски, рядом = 3) {
  let на = 0; let нб = 0;
  const ряд = куски.map((к) => {
    if (к.вид === 'равно') return { ...к, на: ++на, нб: ++нб };
    if (к.вид === 'удалено') return { ...к, на: ++на, нб: null };
    return { ...к, на: null, нб: ++нб };
  });

  const нужна = new Array(ряд.length).fill(false);
  ряд.forEach((к, и) => {
    if (к.вид === 'равно') return;
    for (let j = Math.max(0, и - рядом); j <= Math.min(ряд.length - 1, и + рядом); j++) нужна[j] = true;
  });
  if (!нужна.some(Boolean)) return [{ вид: 'строки', строки: ряд }];

  const итог = [];
  let и = 0;
  while (и < ряд.length) {
    if (нужна[и]) {
      const от = и;
      while (и < ряд.length && нужна[и]) и++;
      итог.push({ вид: 'строки', строки: ряд.slice(от, и) });
    } else {
      const от = и;
      while (и < ряд.length && !нужна[и]) и++;
      итог.push({ вид: 'свёрнуто', строки: ряд.slice(от, и) });
    }
  }
  return итог;
}
