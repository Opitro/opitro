// РАЗБОР И ПОКАЗ ВРЕМЕНИ ЭПОХИ UNIX.
//
// КАК ОТЛИЧИТЬ СЕКУНДЫ ОТ МИЛЛИСЕКУНД. Ходовое правило -- «десять знаков это секунды,
// тринадцать это миллисекунды» -- верно для нашего времени и только для него. Оно молчит
// про 999999999 (девять знаков, а это 2001 год), про 0, про отрицательные метки до 1970
// года и про микросекунды, которыми меряет время добрая половина баз данных.
//
// Поэтому здесь число читают всеми четырьмя способами и берут САМУЮ КРУПНУЮ единицу, чей
// ответ попадает в разумный промежуток -- с тысячного года по трёхтысячный. На десяти и
// тринадцати знаках это даёт ровно то же, что правило из задания, но не ломается по краям.
//
// Первой мыслью было брать прочтение, ближайшее к сегодняшнему дню. Ревизия это опровергла:
// метка 4107542400 -- это 2100 год, до которого семьдесят четыре года, а прочтение тех же
// цифр как миллисекунд даёт 1970 год, до которого пятьдесят шесть. «Ближе» побеждало, и
// будущее превращалось в прошлое. То же случалось с 1900 годом. Промежуток такой беды не
// знает: 2100 год в нём, а 58680-й -- нет.
//
// И выбор ВСЕГДА ПИШЕТСЯ ЧЕЛОВЕКУ. Догадка о единицах меняет ответ в тысячу раз; молча
// принимать её за него нельзя, поэтому рядом стоит переключатель на другое прочтение.

const ЕДИНИЦЫ = [
  { имя: 'с', вМс: (н) => н * 1000, изМс: (мс) => Math.floor(мс / 1000) },
  { имя: 'мс', вМс: (н) => н, изМс: (мс) => Math.round(мс) },
  { имя: 'мкс', вМс: (н) => н / 1e3, изМс: (мс) => Math.round(мс * 1e3) },
  { имя: 'нс', вМс: (н) => н / 1e6, изМс: (мс) => Math.round(мс * 1e6) },
];

// Date держит примерно ±273 000 лет от 1970 года; за этой чертой он отдаёт Invalid Date.
const ПРЕДЕЛ = 8.64e15;

// Промежуток, внутри которого прочтение считается осмысленным. Верхний край можно было бы
// поднять и выше: ближайшее ложное совпадение -- 33658 год, куда попадают миллисекунды,
// прочитанные как секунды. Трёх тысяч хватает с большим запасом.
const ОКНО_ОТ = Date.UTC(1000, 0, 1);
const ОКНО_ДО = Date.UTC(3000, 0, 1);

/**
 * Разбор введённого числа.
 * @returns {годно, мс, единицы, варианты} -- мс годятся для Date,
 *          варианты: все четыре прочтения, чтобы человек мог выбрать другое.
 */
export function разобрать(ввод, сейчас = Date.now()) {
  // Пробелы и подчёркивания внутри числа встречаются в вставках из кода -- это не ошибка.
  const с = String(ввод ?? '').trim().replace(/[\s_ ]/g, '');
  if (!с || !/^[+-]?\d+$/.test(с)) return { годно: false, пусто: !с };

  const н = Number(с);
  if (!Number.isFinite(н)) return { годно: false, велико: true };

  const варианты = ЕДИНИЦЫ.map((е) => {
    const мс = е.вМс(н);
    return { единицы: е.имя, мс, годен: Math.abs(мс) <= ПРЕДЕЛ, далеко: Math.abs(мс - сейчас) };
  });

  const подходящие = варианты.filter((в) => в.годен);
  if (!подходящие.length) return { годно: false, велико: true, варианты };

  // Порядок в списке -- от крупной единицы к мелкой, поэтому первое попадание в промежуток
  // и есть самое крупное прочтение. Крупное вперёд не случайно: у любого числа около нуля
  // все четыре прочтения падают в 1970 год, и без этого правила побеждали бы наносекунды,
  // а -86400 -- это «вчера по меркам 1970-го», то есть секунды.
  let лучший = подходящие.find((в) => в.мс >= ОКНО_ОТ && в.мс <= ОКНО_ДО);
  // Ни одно прочтение не похоже на дату -- берём ближайшее к сегодня, чтобы хоть что-то
  // показать; человек всё равно видит выбранные единицы и может их сменить.
  if (!лучший) {
    лучший = подходящие[0];
    for (const в of подходящие) if (в.далеко < лучший.далеко) лучший = в;
  }

  return { годно: true, мс: лучший.мс, единицы: лучший.единицы, число: н, варианты };
}

/** Перечесть миллисекунды обратно в метку выбранных единиц. */
export function собрать(мс, единицы = 'с') {
  const е = ЕДИНИЦЫ.find((к) => к.имя === единицы) || ЕДИНИЦЫ[0];
  return е.изМс(мс);
}

const дв = (н) => String(н).padStart(2, '0');
// Годы до нашей эры и после десятитысячного пишутся со знаком -- иначе запись неоднозначна.
const год = (г) => (г >= 0 && г <= 9999 ? String(г).padStart(4, '0') : (г < 0 ? '-' : '+') + String(Math.abs(г)).padStart(6, '0'));

/** Всемирное время в виде, который читается одинаково в любой стране. */
export function вUTC(мс) {
  const д = new Date(мс);
  if (Number.isNaN(д.getTime())) return '';
  return `${год(д.getUTCFullYear())}-${дв(д.getUTCMonth() + 1)}-${дв(д.getUTCDate())} `
    + `${дв(д.getUTCHours())}:${дв(д.getUTCMinutes())}:${дв(д.getUTCSeconds())}`;
}

/** Запись по стандарту ISO 8601 -- та, что уходит в файлы и в чужие программы. */
export function вISO(мс) {
  const д = new Date(мс);
  return Number.isNaN(д.getTime()) ? '' : д.toISOString();
}

/** Местное время этого компьютера вместе со сдвигом от всемирного. */
export function вМестное(мс, язык = 'ru') {
  const д = new Date(мс);
  if (Number.isNaN(д.getTime())) return { строка: '', сдвиг: '', пояс: '' };
  const строка = `${год(д.getFullYear())}-${дв(д.getMonth() + 1)}-${дв(д.getDate())} `
    + `${дв(д.getHours())}:${дв(д.getMinutes())}:${дв(д.getSeconds())}`;
  // Знак у getTimezoneOffset обратный привычному: для Киева он вернёт -180, а пишут +03:00.
  const смещение = -д.getTimezoneOffset();
  const знак = смещение < 0 ? '-' : '+';
  const сдвиг = `UTC${знак}${дв(Math.floor(Math.abs(смещение) / 60))}:${дв(Math.abs(смещение) % 60)}`;
  let пояс = '';
  try {
    пояс = new Intl.DateTimeFormat(язык, { timeZoneName: 'long' })
      .formatToParts(д).find((ч) => ч.type === 'timeZoneName')?.value || '';
  } catch (е) { пояс = ''; }
  return { строка, сдвиг, пояс };
}

/**
 * Сколько прошло или осталось, словами. Склонения отдаём браузеру: он знает правила всех
 * четырёх языков, а свой список окончаний пришлось бы держать для каждого и всё равно
 * ошибаться -- «2 года» против «5 лет» против «22 года».
 */
export function насколькоДавно(мс, язык = 'ru', сейчас = Date.now()) {
  const секунд = (мс - сейчас) / 1000;
  const мерки = [
    ['year', 31556952], ['month', 2629746], ['week', 604800],
    ['day', 86400], ['hour', 3600], ['minute', 60], ['second', 1],
  ];
  try {
    const запись = new Intl.RelativeTimeFormat(язык, { numeric: 'auto' });
    for (const [мера, вСекундах] of мерки) {
      if (Math.abs(секунд) >= вСекундах || мера === 'second') {
        return запись.format(Math.round(секунд / вСекундах), мера);
      }
    }
  } catch (е) { /* без этого обойдёмся */ }
  return '';
}

/** Собрать метку из разложенной даты. Часовой пояс задаётся явно, а не угадывается. */
export function изЧастей({ год: г, месяц, день, час = 0, минута = 0, секунда = 0 }, поясUTC = false) {
  // И Date.UTC, и new Date(...) отображают годы 0..99 в 1900..1999 -- это правило языка,
  // а не опечатка. Год ставится отдельно, иначе 0050 год молча стал бы 1950-м.
  const д = new Date(поясUTC
    ? Date.UTC(2000, месяц - 1, день, час, минута, секунда)
    : new Date(2000, месяц - 1, день, час, минута, секунда).getTime());
  if (поясUTC) д.setUTCFullYear(г); else д.setFullYear(г);
  return д.getTime();
}

/** Не выходит ли метка за предел старых 32-битных систем -- 19 января 2038 года. */
export const ПРЕДЕЛ32 = 2147483647;
export function за2038(мс) {
  return Math.floor(мс / 1000) > ПРЕДЕЛ32;
}
