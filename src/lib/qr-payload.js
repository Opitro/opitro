// ЧТО ИМЕННО КЛАДЁТСЯ В QR-КОД.
//
// Сам код рисует библиотека -- Рид-Соломон, восемь масок с подсчётом штрафов и подбор версии
// руками не пишут: почти правильный код читается одним телефоном и не читается другим.
// А вот СТРОКА, которую туда кладут, -- наша забота, и именно в ней прячутся тихие поломки.
//
// ГЛАВНАЯ: ЭКРАНИРОВАНИЕ В СТРОКЕ WI-FI. Формат WIFI:S:имя;T:WPA;P:пароль;; разделяет поля
// точкой с запятой, поэтому в самих именах и паролях знаки \ ; , : " обязаны быть
// экранированы обратной косой. Пароль вида «Pa;ss» без экранирования обрывает строку: телефон
// увидит пароль «Pa», молча не подключится, и человек будет думать, что дело в роутере.
// В задании об этом не сказано ни слова.
//
// Вторая: в визитке (vCard) по тем же причинам экранируются \ ; , и переносы строк.

/** Экранирование для строки Wi-Fi: пять знаков по стандарту. */
export function экранироватьWifi(с) {
  return String(с ?? '').replace(/([\\;,:"])/g, '\\$1');
}

/** Экранирование для vCard: обратная косая, точка с запятой, запятая и переносы. */
export function экранироватьВизитку(с) {
  return String(с ?? '')
    .replace(/\\/g, '\\\\')
    .replace(/;/g, '\\;')
    .replace(/,/g, '\\,')
    .replace(/\r?\n/g, '\\n');
}

/** Ссылка: дописываем протокол, если его забыли, но не трогаем то, что уже с протоколом. */
export function ссылка(с) {
  const т = String(с ?? '').trim();
  if (!т) return '';
  // Свои схемы (mailto:, tel:, ftp:, market: и прочее) не трогаем -- человек знает, что делает.
  if (/^[a-z][a-z0-9+.-]*:/i.test(т)) return т;
  // «//example.com» -- тоже уже адрес, просто без схемы.
  if (т.startsWith('//')) return 'https:' + т;
  return 'https://' + т;
}

/**
 * Строка сети Wi-Fi. Тип защиты: WPA (подходит и для WPA2/WPA3), WEP или nopass.
 * Скрытая сеть помечается H:true -- без этого телефон её не найдёт.
 */
export function сетьWifi({ имя, пароль, защита = 'WPA', скрытая = false }) {
  const и = экранироватьWifi(имя);
  if (!и) return '';
  const части = [`S:${и}`];
  if (защита === 'nopass') {
    части.unshift('T:nopass');
  } else {
    части.unshift(`T:${защита}`);
    части.push(`P:${экранироватьWifi(пароль)}`);
  }
  if (скрытая) части.push('H:true');
  return `WIFI:${части.join(';')};;`;
}

/** Визитка. Пустые поля не пишем: телефон покажет пустые строки, если их оставить. */
export function визитка({ имя = '', фамилия = '', организация = '', должность = '',
                          телефон = '', почта = '', сайт = '' }) {
  const и = экранироватьВизитку(имя.trim());
  const ф = экранироватьВизитку(фамилия.trim());
  if (!и && !ф && !организация.trim() && !телефон.trim() && !почта.trim()) return '';
  const строки = ['BEGIN:VCARD', 'VERSION:3.0'];
  строки.push(`N:${ф};${и};;;`);
  const полное = [имя.trim(), фамилия.trim()].filter(Boolean).join(' ');
  if (полное) строки.push(`FN:${экранироватьВизитку(полное)}`);
  if (организация.trim()) строки.push(`ORG:${экранироватьВизитку(организация.trim())}`);
  if (должность.trim()) строки.push(`TITLE:${экранироватьВизитку(должность.trim())}`);
  if (телефон.trim()) строки.push(`TEL;TYPE=CELL:${экранироватьВизитку(телефон.trim())}`);
  if (почта.trim()) строки.push(`EMAIL:${экранироватьВизитку(почта.trim())}`);
  if (сайт.trim()) строки.push(`URL:${экранироватьВизитку(ссылка(сайт))}`);
  строки.push('END:VCARD');
  return строки.join('\n');
}

/**
 * SVG из матрицы. Один путь на все чёрные клетки -- так файл в разы меньше, чем набор
 * прямоугольников, и открывается любым редактором.
 *
 * ПОЛЕ ВОКРУГ КОДА обязательно и равно ЧЕТЫРЁМ КЛЕТКАМ: так требует стандарт. Без него
 * многие сканеры не находят код на пёстром фоне -- это не украшение, а часть кода.
 */
export function вSVG(тёмная, размерМодулей, { поле = 4, пиксель = 8 } = {}) {
  const всего = размерМодулей + поле * 2;
  const куски = [];
  for (let р = 0; р < размерМодулей; р++) {
    for (let к = 0; к < размерМодулей; к++) {
      if (тёмная(р, к)) куски.push(`M${к + поле} ${р + поле}h1v1h-1z`);
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${всего * пиксель}" height="${всего * пиксель}" viewBox="0 0 ${всего} ${всего}" shape-rendering="crispEdges">`
    + `<rect width="${всего}" height="${всего}" fill="#ffffff"/>`
    + `<path fill="#000000" d="${куски.join('')}"/></svg>`;
}

/**
 * ОБЯЗАТЕЛЬНОЕ ЛЕЧЕНИЕ КИРИЛЛИЦЫ. Библиотека по умолчанию переводит строку в байты по-своему
 * и берёт от каждого знака младший байт: «Привет» превращается в [31,64,56,50,53,66]. Код при
 * этом собирается и сканируется -- но телефон показывает кракозябры. Проверено запуском на той
 * самой сборке, которую берёт сайт.
 *
 * Лечение -- обычный TextEncoder: он даёт настоящий UTF-8, который и ждут все сканеры.
 * Вызывать ОДИН раз перед первым построением кода.
 */
export function настроитьUTF8(qrcode) {
  qrcode.stringToBytes = (с) => Array.from(new TextEncoder().encode(с));
  return qrcode;
}
