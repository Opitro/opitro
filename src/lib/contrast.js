// КОНТРАСТ ПО ПРАВИЛАМ ДОСТУПНОСТИ (WCAG).
//
// Нужен в двух местах: подписать плашку в палитре чёрным или белым так, чтобы её было
// видно, и позже -- на отдельной странице проверки контраста. Поэтому счёт живёт здесь, а
// не внутри одной страницы.
//
// ПОЧЕМУ НЕ «ПО ЯРКОСТИ НА ГЛАЗ». Ходовой приём -- сложить R, G и B, поделить и сравнить со
// 128. Он ошибается на насыщенных цветах: чистый синий #0000ff по такой мерке «светлый»
// (сумма 255), хотя белые буквы на нём читаются, а чёрные почти нет. В правилах доступности
// считается ОТНОСИТЕЛЬНАЯ ЯРКОСТЬ: каждая доля сначала распрямляется (экран показывает не
// линейно), потом складывается с весами -- зелёный вносит почти три четверти, синий около
// семи сотых, потому что глаз так устроен.

/** Распрямление одной доли: обратная поправка того сжатия, с которым цвет хранится. */
function распрямить(значение) {
  const д = Math.min(1, Math.max(0, значение / 255));
  return д <= 0.04045 ? д / 12.92 : ((д + 0.055) / 1.055) ** 2.4;
}

/** Относительная яркость от 0 (чёрный) до 1 (белый). */
export function яркость({ r, g, b }) {
  return 0.2126 * распрямить(r) + 0.7152 * распрямить(g) + 0.0722 * распрямить(b);
}

/**
 * Отношение контраста между двумя цветами: от 1 (одинаковые) до 21 (чёрный и белый).
 * Порядок цветов значения не имеет.
 */
export function контраст(первый, второй) {
  const а = яркость(первый);
  const б = яркость(второй);
  const светлее = Math.max(а, б);
  const темнее = Math.min(а, б);
  return (светлее + 0.05) / (темнее + 0.05);
}

const ЧЁРНЫЙ = { r: 0, g: 0, b: 0 };
const БЕЛЫЙ = { r: 255, g: 255, b: 255 };

/**
 * Каким цветом подписать плашку -- чёрным или белым. Берём тот, что даёт больше контраста,
 * а не тот, что «кажется» подходящим.
 */
export function буквыНа(цвет) {
  return контраст(цвет, ЧЁРНЫЙ) >= контраст(цвет, БЕЛЫЙ) ? '#000000' : '#ffffff';
}

/**
 * Оценка по правилам доступности. Порог 4.5 -- для обычного текста, 3 -- для крупного
 * (от 24 пикселей, или от 18.66 если жирный) и для очертаний управляющих элементов.
 */
export function оценка(отношение) {
  return {
    обычный: отношение >= 4.5,
    крупный: отношение >= 3,
    строгий: отношение >= 7,        // повышенный уровень для обычного текста
  };
}
