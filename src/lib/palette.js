// ПРАВИЛА СОЧЕТАНИЯ ЦВЕТОВ.
//
// Все четыре правила -- это сдвиги по цветовому кругу в пространстве HSL, и считаются они
// арифметикой, а не вкусом. Гармония тут не обещание красоты, а описанное правило: столько-то
// градусов в сторону.
//
// ЧЕСТНАЯ ОГОВОРКА ПРО ПЯТЬ ПЛАШЕК. Правил, дающих ровно пять цветов, среди этих четырёх нет:
// у комплиментарного их два, у триады три. Пять плашек набираются добавлением светлого и
// тёмного оттенка того же тона -- и в описании каждой плашки прямо сказано, что она такое,
// чтобы никто не думал, будто «третий цвет триады» это самостоятельное правило.
//
// ПРО КРУГ HSL. Он не совпадает с тем, как цвета видит глаз: жёлтый в нём заметно светлее
// синего при одной и той же светлоте. Сдвиг на 180° даёт формально противоположный цвет, а
// не обязательно «тот самый» из книжки по цветоведению. Правила эти живут в вебе именно в
// таком, арифметическом виде -- так их и считаем.

import { вHsl, изHsl } from './color-convert.js';

const покругу = (градус) => ((градус % 360) + 360) % 360;
const вграницах = (з, наим = 0, наиб = 100) => Math.min(наиб, Math.max(наим, з));

/** Тот же тон, но светлее или темнее на сколько-то процентов светлоты. */
function сдвинутьСветлоту(hsl, насколько, наим = 0, наиб = 100) {
  return изHsl({ ...hsl, l: вграницах(hsl.l + насколько, наим, наиб) });
}

/**
 * Палитра из пяти цветов по выбранному правилу.
 * @param основа -- {r,g,b}
 * @param правило -- 'комплиментарная' | 'аналоговая' | 'триада' | 'монохромная'
 * @returns [{цвет, роль, сдвиг}] -- роль это ключ для перевода, сдвиг в градусах или null.
 */
export function палитра(основа, правило) {
  const h = вHsl(основа);
  const тон = (насколько) => изHsl({ ...h, h: покругу(h.h + насколько) });

  if (правило === 'аналоговая') {
    // Соседи по кругу: два слева, два справа. Мягкий ряд без резких переходов.
    return [-60, -30, 0, 30, 60].map((г) => ({
      цвет: тон(г), роль: г === 0 ? 'основа' : 'сосед', сдвиг: г,
    }));
  }

  if (правило === 'триада') {
    // Три равноудалённых цвета -- и к ним светлый с тёмным оттенком основы, чтобы вышло пять.
    return [
      { цвет: сдвинутьСветлоту(h, -22), роль: 'темнее', сдвиг: 0 },
      { цвет: изHsl(h), роль: 'основа', сдвиг: 0 },
      { цвет: сдвинутьСветлоту(h, 22), роль: 'светлее', сдвиг: 0 },
      { цвет: тон(120), роль: 'второй', сдвиг: 120 },
      { цвет: тон(240), роль: 'третий', сдвиг: 240 },
    ];
  }

  if (правило === 'монохромная') {
    // Один тон, лесенка светлоты. Шаг считается от самой основы, чтобы её оттенок остался
    // в ряду, а не потерялся между придуманными ступенями.
    //
    // Крайние ступени прижимаем к 12 и 88 процентам, и вот почему. Ниже двенадцати цвет уже
    // почти чёрный: на весь цветовой круг там остаётся десяток значений RGB, и тон, который
    // должен быть общим для всей палитры, начинает гулять -- замерено, до шести градусов.
    // Пользы от такой плашки нет никакой: это просто тёмный квадрат.
    const ступени = [-32, -16, 0, 16, 32];
    return ступени.map((ш) => ({
      цвет: сдвинутьСветлоту(h, ш, 12, 88),
      роль: ш === 0 ? 'основа' : (ш < 0 ? 'темнее' : 'светлее'),
      сдвиг: 0,
    }));
  }

  // Комплиментарная -- по умолчанию. Основа с двумя оттенками и противоположный цвет с одним.
  const против = вHsl(тон(180));
  return [
    { цвет: сдвинутьСветлоту(h, -20), роль: 'темнее', сдвиг: 0 },
    { цвет: изHsl(h), роль: 'основа', сдвиг: 0 },
    { цвет: сдвинутьСветлоту(h, 20), роль: 'светлее', сдвиг: 0 },
    { цвет: изHsl(против), роль: 'против', сдвиг: 180 },
    { цвет: сдвинутьСветлоту(против, -20), роль: 'противТемнее', сдвиг: 180 },
  ];
}

/**
 * Случайный цвет, годный как основа палитры.
 * Ограничения не для красоты, а по делу: у почти серого цвета сдвиг тона ничего не меняет,
 * и все пять плашек выходят одинаковыми; у совсем тёмного и совсем светлого пропадает
 * лесенка светлоты -- она упирается в край.
 */
export function случайнаяОснова(случай = Math.random) {
  return изHsl({
    h: случай() * 360,
    s: 45 + случай() * 50,     // 45..95 %
    l: 35 + случай() * 30,     // 35..65 %
    a: 1,
  });
}
