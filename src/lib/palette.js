
import { вHsl, изHsl } from './color-convert.js';

const покругу = (градус) => ((градус % 360) + 360) % 360;
const вграницах = (з, наим = 0, наиб = 100) => Math.min(наиб, Math.max(наим, з));

function сдвинутьСветлоту(hsl, насколько, наим = 0, наиб = 100) {
  return изHsl({ ...hsl, l: вграницах(hsl.l + насколько, наим, наиб) });
}

export function палитра(основа, правило) {
  const h = вHsl(основа);
  const тон = (насколько) => изHsl({ ...h, h: покругу(h.h + насколько) });

  if (правило === 'аналоговая') {

    return [-60, -30, 0, 30, 60].map((г) => ({
      цвет: тон(г), роль: г === 0 ? 'основа' : 'сосед', сдвиг: г,
    }));
  }

  if (правило === 'триада') {

    return [
      { цвет: сдвинутьСветлоту(h, -22), роль: 'темнее', сдвиг: 0 },
      { цвет: изHsl(h), роль: 'основа', сдвиг: 0 },
      { цвет: сдвинутьСветлоту(h, 22), роль: 'светлее', сдвиг: 0 },
      { цвет: тон(120), роль: 'второй', сдвиг: 120 },
      { цвет: тон(240), роль: 'третий', сдвиг: 240 },
    ];
  }

  if (правило === 'монохромная') {

    const ступени = [-32, -16, 0, 16, 32];
    return ступени.map((ш) => ({
      цвет: сдвинутьСветлоту(h, ш, 12, 88),
      роль: ш === 0 ? 'основа' : (ш < 0 ? 'темнее' : 'светлее'),
      сдвиг: 0,
    }));
  }

  const против = вHsl(тон(180));
  return [
    { цвет: сдвинутьСветлоту(h, -20), роль: 'темнее', сдвиг: 0 },
    { цвет: изHsl(h), роль: 'основа', сдвиг: 0 },
    { цвет: сдвинутьСветлоту(h, 20), роль: 'светлее', сдвиг: 0 },
    { цвет: изHsl(против), роль: 'против', сдвиг: 180 },
    { цвет: сдвинутьСветлоту(против, -20), роль: 'противТемнее', сдвиг: 180 },
  ];
}

export function случайнаяОснова(случай = Math.random) {
  return изHsl({
    h: случай() * 360,
    s: 45 + случай() * 50,
    l: 35 + случай() * 30,
    a: 1,
  });
}
