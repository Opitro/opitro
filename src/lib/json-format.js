
const ПРОБЕЛЫ = new Set([' ', '\t', '\n', '\r']);

function место(текст, позиция) {
  let строка = 1;
  let началоСтроки = 0;
  for (let и = 0; и < позиция && и < текст.length; и++) {
    if (текст[и] === '\n') { строка++; началоСтроки = и + 1; }
  }
  return { строка, столбец: позиция - началоСтроки + 1 };
}

class Беда extends Error {
  constructor(что, позиция) { super(что); this.позиция = позиция; }
}

function разобрать(текст) {
  let и = 0;
  const повторы = [];

  const пропустить = () => { while (и < текст.length && ПРОБЕЛЫ.has(текст[и])) и++; };
  const беда = (что, где = и) => { throw new Беда(что, где); };

  function строкаJSON() {
    const начало = и;
    и++;
    while (и < текст.length) {
      const з = текст[и];
      if (з === '"') { и++; return текст.slice(начало, и); }
      if (з === '\\') {
        const с = текст[и + 1];
        if (с === undefined) беда('Строка оборвалась внутри экранирования', и);
        if (!'"\\/bfnrtu'.includes(с)) беда(`Недопустимое экранирование \\${с}`, и);
        if (с === 'u') {
          const шестнадцать = текст.slice(и + 2, и + 6);
          if (!/^[0-9a-fA-F]{4}$/.test(шестнадцать)) {
            беда('После \\u должно быть четыре шестнадцатеричных знака', и);
          }
          и += 6;
        } else и += 2;
        continue;
      }

      if (з < ' ') беда('Управляющий знак внутри строки: его нужно экранировать', и);
      и++;
    }
    беда('Строка не закрыта кавычкой', начало);
  }

  function числоJSON() {
    const начало = и;
    if (текст[и] === '-') и++;
    if (текст[и] === '0') и++;
    else if (текст[и] >= '1' && текст[и] <= '9') { while (текст[и] >= '0' && текст[и] <= '9') и++; }
    else беда('Здесь ожидалось число', начало);
    if (текст[и] === '.') {
      и++;
      if (!(текст[и] >= '0' && текст[и] <= '9')) беда('После точки нужна хотя бы одна цифра', и);
      while (текст[и] >= '0' && текст[и] <= '9') и++;
    }
    if (текст[и] === 'e' || текст[и] === 'E') {
      и++;
      if (текст[и] === '+' || текст[и] === '-') и++;
      if (!(текст[и] >= '0' && текст[и] <= '9')) беда('После знака степени нужна цифра', и);
      while (текст[и] >= '0' && текст[и] <= '9') и++;
    }
    return текст.slice(начало, и);
  }

  function значение(глубина) {
    if (глубина > 500) беда('Слишком глубокая вложенность', и);
    пропустить();
    if (и >= текст.length) беда('Текст кончился там, где ожидалось значение');
    const з = текст[и];

    if (з === '{') {
      и++;
      const пары = [];
      const виденные = new Set();
      пропустить();
      if (текст[и] === '}') { и++; return { т: 'об', пары }; }
      for (;;) {
        пропустить();
        if (текст[и] !== '"') {

          беда(текст[и] === "'"
            ? 'Одинарные кавычки в JSON запрещены: ключ нужно взять в двойные'
            : 'Ключ должен быть строкой в двойных кавычках');
        }
        const ключ = строкаJSON();
        if (виденные.has(ключ)) повторы.push({ ключ, ...место(текст, и - ключ.length) });
        виденные.add(ключ);
        пропустить();
        if (текст[и] !== ':') беда('После ключа ожидалось двоеточие');
        и++;
        пары.push([ключ, значение(глубина + 1)]);
        пропустить();
        if (текст[и] === ',') {
          и++;
          пропустить();
          if (текст[и] === '}') беда('Лишняя запятая перед закрывающей скобкой', и - 1);
          continue;
        }
        if (текст[и] === '}') { и++; return { т: 'об', пары }; }
        беда('Ожидалась запятая или закрывающая фигурная скобка');
      }
    }

    if (з === '[') {
      и++;
      const эл = [];
      пропустить();
      if (текст[и] === ']') { и++; return { т: 'мас', эл }; }
      for (;;) {
        эл.push(значение(глубина + 1));
        пропустить();
        if (текст[и] === ',') {
          и++;
          пропустить();
          if (текст[и] === ']') беда('Лишняя запятая перед закрывающей скобкой', и - 1);
          continue;
        }
        if (текст[и] === ']') { и++; return { т: 'мас', эл }; }
        беда('Ожидалась запятая или закрывающая квадратная скобка');
      }
    }

    if (з === '"') return { т: 'лит', сырое: строкаJSON() };
    if (з === '-' || (з >= '0' && з <= '9')) return { т: 'лит', сырое: числоJSON() };
    for (const слово of ['true', 'false', 'null']) {
      if (текст.startsWith(слово, и)) { и += слово.length; return { т: 'лит', сырое: слово }; }
    }
    if (з === "'") беда('Одинарные кавычки в JSON запрещены, нужны двойные');
    беда(`Неожиданный знак «${з}»`);
  }

  const дерево = значение(0);
  пропустить();
  if (и < текст.length) беда(`Лишнее после конца данных: «${текст[и]}»`);
  return { дерево, повторы };
}

function напечатать(узел, отступ, уровень = 0) {
  const перенос = отступ ? '\n' : '';
  const поле = отступ ? отступ.repeat(уровень + 1) : '';
  const закрытие = отступ ? отступ.repeat(уровень) : '';
  const двоеточие = отступ ? ': ' : ':';

  if (узел.т === 'лит') return узел.сырое;
  if (узел.т === 'об') {
    if (!узел.пары.length) return '{}';
    const тело = узел.пары
      .map(([к, з]) => `${поле}${к}${двоеточие}${напечатать(з, отступ, уровень + 1)}`)
      .join(',' + перенос);
    return `{${перенос}${тело}${перенос}${закрытие}}`;
  }
  if (!узел.эл.length) return '[]';
  const тело = узел.эл
    .map((з) => `${поле}${напечатать(з, отступ, уровень + 1)}`)
    .join(',' + перенос);
  return `[${перенос}${тело}${перенос}${закрытие}]`;
}

function сосчитать(узел, уровень = 1) {
  if (узел.т === 'лит') return { ключей: 0, глубина: уровень };
  const дети = узел.т === 'об' ? узел.пары.map((п) => п[1]) : узел.эл;
  let ключей = узел.т === 'об' ? узел.пары.length : 0;
  let глубина = уровень;
  for (const д of дети) {
    const с = сосчитать(д, уровень + 1);
    ключей += с.ключей;
    глубина = Math.max(глубина, с.глубина);
  }
  return { ключей, глубина };
}

export function обработатьJSON(исходный, отступ = 2) {
  const текст = String(исходный ?? '');
  if (!текст.trim()) return { пусто: true };
  let разбор;
  try {
    разбор = разобрать(текст);
  } catch (е) {
    const где = место(текст, Math.min(е.позиция ?? 0, текст.length));
    return { ошибка: { текст: е.message, строка: где.строка, столбец: где.столбец } };
  }
  const шаг = отступ === 'tab' ? '\t' : ' '.repeat(Number(отступ) || 0);
  const счёт = сосчитать(разбор.дерево);
  return {
    готово: напечатать(разбор.дерево, шаг),
    ключей: счёт.ключей,
    глубина: счёт.глубина,
    повторы: разбор.повторы,
  };
}
