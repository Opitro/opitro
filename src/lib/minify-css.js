// СЖАТИЕ CSS.
//
// ПОЧЕМУ НЕ НАБОР ЗАМЕН ПО ОБРАЗЦУ. Соблазн велик: выкинуть комментарии одним правилом,
// пробелы вторым, и готово. Так делают почти все самодельные минификаторы, и все они портят
// чужие стили одинаково. Разбор здесь идёт по одному знаку, с памятью о том, где мы стоим,
// потому что каждая из ловушек ниже уже ломала настоящие таблицы стилей:
//
//   1. content: "/* не комментарий */" -- внутри строки комментариев не бывает.
//   2. calc(100% - 10px) -- уберёшь пробелы вокруг минуса, и правило перестанет работать.
//      В CSS это не арифметика, а грамматика: calc(100%-10px) недействительно.
//   3. @media screen and (min-width:600px) -- уберёшь пробел перед скобкой, и запрос умрёт.
//   4. #aabbcc { } -- это НЕ цвет, а селектор по имени. Сократишь до #abc -- правило
//      перестанет находить свой элемент.
//   5. 0px -> 0 годится для длины, но НЕ для времени (transition: 0s нельзя писать как 0),
//      не для чисел внутри calc и не для 0% в @keyframes, где это номер шага.
//   6. url(data:...) без кавычек -- внутри бывает что угодно, вплоть до скобок в base64.
//
// Что НЕ делаем нарочно: не снимаем кавычки со значений, не выбрасываем пустые правила и не
// переставляем свойства местами. Выигрыш в байтах там крошечный, а способов сломать чужое
// -- много.

// Единицы длины, у которых ноль можно писать без единицы. Времени (s, ms), углов и
// процентов здесь нет намеренно: transition:0 без единицы недействительно, а 0% в
// @keyframes -- это номер шага, а не размер.
const ДЛИНЫ = /^(px|em|rem|ex|ch|vw|vh|vmin|vmax|cm|mm|in|pt|pc|q|cap|ic|lh|rlh|vb|vi)$/i;

// Правила, внутри которых лежат другие правила, а не объявления свойств.
const СОДЕРЖАТ_ПРАВИЛА =
  /^@(media|supports|document|container|layer|scope|keyframes|-\w+-keyframes)\b/i;

// Функции, чьё содержимое браузер держит дословно и разбирает только при подстановке.
// Внутри них нельзя ни жать пробелы, ни сокращать цвета: var(--нет, #ffffff) -- это запасное
// значение в виде набора знаков, а не разобранный цвет.
const СЫРЫЕ_ФУНКЦИИ = /^(var|color-mix|env|image-set|-webkit-image-set)$/i;
const ОСОБЫЕ_СПАНЫ = /\b(calc|min|max|clamp|var|color-mix|env|image-set|-webkit-image-set)\(/gi;

const ЗНАКИ = new Set(['{', '}', ';', ':', ',', '>', '~', '+']);
// Место, куда вернётся спрятанная строка или url. Знак нарочно такой, какого в CSS
// не бывает, -- иначе метка столкнулась бы с настоящим содержимым файла.
const МЕТКА = '\u0000';

/** Короткая запись цвета -- без оглядки на окружение; наружу идёт обёртка ниже. */
function цветаСырьём(значение) {
  return значение
    .replace(/#([0-9a-fA-F]{3,8})\b/g, (всё, знаки) => {
      const з = знаки.toLowerCase();
      if (з.length === 6 && з[0] === з[1] && з[2] === з[3] && з[4] === з[5]) {
        return '#' + з[0] + з[2] + з[4];
      }
      if (з.length === 8 && з[0] === з[1] && з[2] === з[3] && з[4] === з[5] && з[6] === з[7]) {
        return '#' + з[0] + з[2] + з[4] + з[6];
      }
      return '#' + з;
    })
    .replace(/\brgba?\(\s*([\d.]+)\s*[,\s]\s*([\d.]+)\s*[,\s]\s*([\d.]+)\s*(?:[,/]\s*([\d.%]+)\s*)?\)/gi,
      (всё, к, з, с, п) => {
        // Прозрачность, отличную от полной, в шестнадцатеричный вид не переводим:
        // на глаз она разошлась бы из-за округления.
        if (п !== undefined && п !== '1' && п !== '100%') return всё;
        const ч = [к, з, с].map(Number);
        if (ч.some((н) => !Number.isInteger(н) || н < 0 || н > 255)) return всё;
        return цветаСырьём('#' + ч.map((н) => н.toString(16).padStart(2, '0')).join(''));
      });
}

/**
 * Найти куски значения, лежащие внутри особых функций, и применить преобразование только к
 * остальному. Скобки считаем: calc(min(1px, 2px) + 3px) -- обычное дело.
 *
 * Особых два рода, и оба трогать нельзя:
 *   -- calc, min, max, clamp: там значим каждый пробел, а голый ноль недействителен;
 *   -- var, color-mix, env: их содержимое браузер держит дословно и разбирает лишь при
 *      подстановке. Внутри var(--нет, #ffffff) стоит не цвет, а набор знаков про запас.
 */
function внеОсобых(значение, преобразовать) {
  const особые = new RegExp(ОСОБЫЕ_СПАНЫ.source, 'gi');
  let итог = '', место = 0, м;
  while ((м = особые.exec(значение))) {
    if (м.index < место) continue;
    итог += преобразовать(значение.slice(место, м.index));
    let к = м.index + м[0].length, глубина = 1;
    while (к < значение.length && глубина > 0) {
      if (значение[к] === '(') глубина++;
      else if (значение[к] === ')') глубина--;
      к++;
    }
    итог += значение.slice(м.index, к);      // саму особую функцию оставляем как есть
    место = к;
    особые.lastIndex = к;
  }
  return итог + преобразовать(значение.slice(место));
}

/** Цвета -- только вне особых функций. */
const короткийЦвет = (значение) => внеОсобых(значение, цветаСырьём);

/** Лишние нули: 0.5 -> .5, 1.50 -> 1.5, 0px -> 0 -- тоже только вне особых функций. */
function лишниеНули(значение) {
  return внеОсобых(значение, (кусок) => кусок
    // ХВОСТОВОЙ НОЛЬ СНИМАЕМ ПЕРВЫМ. В обратном порядке 0.50rem превращается в .50rem, и
    // второе правило его уже не узнаёт: перед точкой не остаётся цифры, за которую оно
    // цепляется.
    .replace(/(\d)\.(\d*?)0+(?!\d)/g, (всё, ц, д) => (д ? `${ц}.${д}` : ц))
    // Знак перед точкой смотрим, чтобы не тронуть 1.5 и что-нибудь вроде v0.5.
    .replace(/(^|[\s,(:+\-*/])0+\.(\d)/g, '$1.$2')
    .replace(/(^|[\s,(:])0+([a-z]+)\b/gi, (всё, до, ед) => (ДЛИНЫ.test(ед) ? до + '0' : всё)));
}

/**
 * @param {string} текст исходный CSS
 * @param {object} наладки {комментарии, цвета, нули}
 * @returns {{код: string, беда: string|null}}
 */
export function сжатьCSS(текст, наладки = {}) {
  const { комментарии = true, цвета = true, нули = true } = наладки;
  const с = String(текст ?? '');
  let итог = '';
  let буфер = '';            // значение свойства -- копится целиком, чтобы преобразовать разом
  let вЗначении = false;
  // Собственные свойства (--имя) браузер НЕ разбирает: их значение хранится дословно, как
  // набор знаков, и разбирается только там, где его подставят через var(). Поэтому трогать
  // его нельзя вовсе. Пример беды: «--отступ: 0px» -> «0», и стоящее в другом месте
  // «calc(100% - var(--отступ))» становится недействительным. Такое сжатие ломает страницу
  // далеко от того места, где сжимало.
  let дословно = false;
  const защита = [];         // строки и url: в буфер идут метками, обратно -- нетронутыми
  let и = 0;

  // Стопка блоков: 'правила' -- внутри лежат другие правила (@media, @keyframes),
  // 'объявления' -- внутри лежат свойства. От этого зависит, цвет перед нами или селектор.
  const стопка = [];
  let преамбула = '';
  let счёт = 0;              // глубина calc() / min() / max() / clamp()
  let сырьё = 0;             // глубина var() / color-mix() / env() -- там пробелы дословны
  let скобки = 0;

  const вОбъявлениях = () => стопка[стопка.length - 1] === 'объявления';
  const куда = () => (вЗначении ? буфер : итог);
  const последний = () => { const т = куда(); return т[т.length - 1] || ''; };
  const выдать = (кусок) => { if (вЗначении) буфер += кусок; else итог += кусок; };

  /** Значение дописано до конца: преобразовать целиком и вернуть спрятанное. */
  const слить = () => {
    if (!вЗначении) return;
    let з = буфер;
    if (!дословно) {
      if (цвета) з = короткийЦвет(з);
      if (нули) з = лишниеНули(з);
    }
    з = з.replace(new RegExp(МЕТКА + '(\\d+)' + МЕТКА, 'g'), (всё, н) => защита[Number(н)]);
    итог += з.trimEnd();
    буфер = '';
    вЗначении = false;
    дословно = false;
  };
  const спрятать = (кусок) => {
    if (!вЗначении) { итог += кусок; return; }
    if (дословно) { буфер += кусок; return; }
    защита.push(кусок);
    буфер += МЕТКА + (защита.length - 1) + МЕТКА;
  };

  while (и < с.length) {
    const з = с[и];

    // --- Комментарии -------------------------------------------------------------------
    if (з === '/' && с[и + 1] === '*') {
      const конец = с.indexOf('*/', и + 2);
      if (конец === -1) return { код: '', беда: 'НЕЗАКРЫТЫЙ_КОММЕНТАРИЙ' };
      const целиком = с.slice(и, конец + 2);
      // Комментарий с восклицательным знаком по общему уговору несёт лицензию. Такие
      // оставляем даже когда просили убрать все: выкинуть чужую лицензию -- не оптимизация.
      if (!комментарии || целиком.startsWith('/*!')) спрятать(целиком);
      else if (/[\w-]$/.test(куда()) && /^[\w-]/.test(с.slice(конец + 2))) {
        // Комментарий стоял между двумя словами и склеил бы их.
        выдать(' ');
      }
      и = конец + 2;
      преамбула += ' ';
      continue;
    }

    // --- Строки ------------------------------------------------------------------------
    if (з === '"' || з === "'") {
      let к = и + 1;
      while (к < с.length) {
        if (с[к] === '\\') { к += 2; continue; }
        if (с[к] === з) break;
        к++;
      }
      if (к >= с.length) return { код: '', беда: 'НЕЗАКРЫТАЯ_СТРОКА' };
      const кусок = с.slice(и, к + 1);
      спрятать(кусок);
      преамбула += кусок;
      и = к + 1;
      continue;
    }

    // --- url(...) без кавычек ----------------------------------------------------------
    if ((з === 'u' || з === 'U') && /^url\(/i.test(с.slice(и, и + 4))) {
      const хвост = с.slice(и + 4);
      const пробел = хвост.match(/^\s*/)[0];
      const первый = хвост[пробел.length];
      if (первый !== '"' && первый !== "'") {
        const конец = с.indexOf(')', и + 4);
        if (конец === -1) return { код: '', беда: 'НЕЗАКРЫТЫЙ_URL' };
        спрятать('url(' + с.slice(и + 4, конец).trim() + ')');
        преамбула += 'url()';
        и = конец + 1;
        continue;
      }
    }

    // --- Пробелы -----------------------------------------------------------------------
    if (/\s/.test(з)) {
      let к = и;
      while (к < с.length && /\s/.test(с[к])) к++;
      // В значении собственного свойства пробелы -- часть содержимого, а не оформление.
      if (дословно) { буфер += с.slice(и, к); и = к; continue; }
      const до = последний();
      const после = с[к] || '';
      // Вокруг + и - внутри calc пробел ЗНАЧИМ: без него выражение недействительно.
      const счётный = счёт > 0 && (до === '+' || до === '-' || после === '+' || после === '-');
      // Перед открывающей скобкой пробел тоже значим: «and (min-width:0)» без него умрёт.
      const передСкобкой = после === '(';
      // Условие @supports браузеры хранят дословно, не приводя к общему виду, -- в отличие
      // от @media. Сжатие внутри него законно, но проверить его нечем, поэтому не трогаем.
      const вПоддержке = скобки > 0 && /^@supports\b/i.test(преамбула.trim());
      const лишний = !счётный && !передСкобкой && !вПоддержке && сырьё === 0
        && (до === '' || до === '(' || ЗНАКИ.has(до)
            || после === '' || после === ')' || после === '!' || ЗНАКИ.has(после));
      if (!лишний) выдать(' ');
      преамбула += ' ';
      и = к;
      continue;
    }

    // --- Скобки ------------------------------------------------------------------------
    if (з === '(') {
      const имя = куда().match(/([\w-]+)$/);
      if (имя && /^(calc|min|max|clamp)$/i.test(имя[1])) счёт++;
      else if (счёт > 0) счёт++;      // вложенная скобка внутри счёта тоже счётная
      if (имя && СЫРЫЕ_ФУНКЦИИ.test(имя[1])) сырьё++;
      else if (сырьё > 0) сырьё++;
      скобки++;
      выдать(з); преамбула += з; и++;
      continue;
    }
    if (з === ')') {
      if (счёт > 0) счёт--;
      if (сырьё > 0) сырьё--;
      if (скобки > 0) скобки--;
      выдать(з); преамбула += з; и++;
      continue;
    }

    // --- Границы -----------------------------------------------------------------------
    if (з === '{') {
      слить();
      стопка.push(СОДЕРЖАТ_ПРАВИЛА.test(преамбула.trim()) ? 'правила' : 'объявления');
      преамбула = '';
      итог += '{';
      и++;
      continue;
    }
    if (з === '}') {
      слить();
      if (итог[итог.length - 1] === ';') итог = итог.slice(0, -1);
      стопка.pop();
      преамбула = '';
      итог += '}';
      и++;
      continue;
    }
    if (з === ';') {
      слить();
      // Пустое объявление писать некуда и незачем.
      if (итог[итог.length - 1] === ';' || итог[итог.length - 1] === '{') { и++; преамбула = ''; continue; }
      итог += ';';
      преамбула = '';
      и++;
      continue;
    }
    if (з === ':' && вОбъявлениях() && скобки === 0 && !вЗначении) {
      // Имя свойства уже лежит в итоге -- по нему и узнаём собственное свойство. Через
      // [^...] нарочно: имена бывают не только латиницей, и \w кириллицу не знает, отчего
      // «--цифры» проскакивало как обычное свойство и его значение всё-таки правилось.
      дословно = /(^|[{;])--[^\s:;{},()]+$/.test(итог);
      итог += ':';
      преамбула += ':';
      вЗначении = true;
      и++;
      continue;
    }

    выдать(з);
    преамбула += з;
    и++;
  }

  слить();
  if (стопка.length) return { код: '', беда: 'НЕЗАКРЫТАЯ_СКОБКА' };
  return { код: итог.trim(), беда: null };
}
