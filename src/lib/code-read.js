// РАЗБОР СНИМКА -- В НЕСКОЛЬКО ЗАХОДОВ.
//
// Живой кадр приходит четыре раза в секунду, и позволить себе там можно только самое быстрое.
// Снимок -- другое дело: он один, человек ждёт ответа, и можно потратить секунду-другую.
//
// ЗАЧЕМ ПОВОРОТЫ. Полосы читаются построчно: распознаватель ведёт по кадру горизонтальные
// линии и смотрит, где чёрное сменяется белым. Код, снятый под углом, такими линиями не
// пересекается как надо, и не находится вовсе -- замерено: ровный снимок читается, тот же
// снимок с наклоном в тридцать градусов уже нет. Поэтому пробуем несколько поворотов.
//
// ЗАЧЕМ УМЕНЬШЕНИЕ. Снимок с телефона -- двенадцать мегапикселей. Разбирать их целиком долго,
// а полосам такая подробность не нужна: полторы тысячи точек по длинной стороне хватает с
// запасом. Заодно это обходит предел площади холста, который есть на iPhone.
const ПОВОРОТЫ = [0, 90, 25, -25, 50, -50];
const ДЛИННАЯ = 1500;

/** Кадр, повёрнутый на угол и уменьшенный до разумного. Возвращает ImageData. */
function перерисовать(картинка, угол, длинная) {
  const ш = картинка.naturalWidth || картинка.width;
  const в = картинка.naturalHeight || картинка.height;
  const к = Math.min(1, длинная / Math.max(ш, в));
  const нш = Math.max(1, Math.round(ш * к));
  const нв = Math.max(1, Math.round(в * к));
  const рад = (угол * Math.PI) / 180;
  // Повёрнутая картинка не помещается в прежнюю рамку -- считаем новую по описанному
  // прямоугольнику, иначе углы кода срезало бы, а в них половина ответа.
  const кш = Math.abs(Math.cos(рад)) * нш + Math.abs(Math.sin(рад)) * нв;
  const кв = Math.abs(Math.sin(рад)) * нш + Math.abs(Math.cos(рад)) * нв;
  const х = document.createElement('canvas');
  х.width = Math.round(кш);
  х.height = Math.round(кв);
  const р = х.getContext('2d', { willReadFrequently: true });
  // Пустые углы после поворота заливаем белым: чёрный распознаватель принимает за полосу.
  р.fillStyle = '#fff';
  р.fillRect(0, 0, х.width, х.height);
  р.translate(х.width / 2, х.height / 2);
  р.rotate(рад);
  р.imageSmoothingQuality = 'high';
  р.drawImage(картинка, -нш / 2, -нв / 2, нш, нв);
  return р.getImageData(0, 0, х.width, х.height);
}

/**
 * Разбор снимка. Заходы идут от самого дешёвого к самому дорогому и обрываются на первой
 * находке. Между заходами отдаём управление браузеру, иначе страница замирает.
 *
 * @param картинка -- img или canvas со снимком.
 * @param нужно    -- 'qr' | 'штрих' | 'оба'.
 */
export async function прочитатьСнимок({ картинка, нужно = 'оба' }) {
  const выдохнуть = () => new Promise((г) => setTimeout(г, 0));

  // 1. Родной распознаватель браузера: он полнее и быстрее всего, что мы можем предложить.
  const свои = await взятьСвой(нужно);
  if (свои) {
    try {
      const всё = await свои.детектор.detect(картинка);
      const найдено = (всё || []).filter((л) => свои.форматы.includes(л.format) && л.rawValue);
      if (найдено.length) {
        const л = найдено[0];
        return { текст: л.rawValue, формат: л.format, вид: л.format === 'qr_code' ? 'qr' : 'штрих' };
      }
      // Код виден, а содержимое пустое -- так бывает на macOS с PDF417: распознаватель
      // находит код и не отдаёт запись. Не сдаёмся и идём на запаску ниже: она читает
      // медленнее, зато отвечает.
    } catch (е) { /* провалился -- идём на запаски */ }
  }

  const прямо = перерисовать(картинка, 0, ДЛИННАЯ);

  // 2. QR: он не зависит от поворота, поэтому хватает одного захода.
  if (нужно !== 'штрих') {
    if (!jsQR) { const м = await import('jsqr'); jsQR = м.default || м; }
    const код = jsQR(прямо.data, прямо.width, прямо.height, { inversionAttempts: 'attemptBoth' });
    if (код && код.data) return { текст: код.data, формат: 'qr_code', вид: 'qr' };
  }

  // 3. Полосы: по одному заходу на поворот.
  if (нужно === 'qr') return null;
  const zx = await взятьZxing();
  for (const угол of ПОВОРОТЫ) {
    await выдохнуть();
    const точки = угол === 0 ? прямо : перерисовать(картинка, угол, ДЛИННАЯ);
    const сер = всерое(точки);
    const итог = однаПопытка(zx, сер, точки.width, точки.height);
    if (итог && годится(итог.формат, нужно)) {
      return { ...итог, вид: итог.формат === 'QR_CODE' ? 'qr' : 'штрих' };
    }
  }
  return null;
}
