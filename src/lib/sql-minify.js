// СЖАТИЕ SQL В ОДНУ СТРОКУ.
//
// Библиотека форматирования этого не умеет, а сделать «в лоб» нельзя: обычная замена всех
// пробелов на один ЛОМАЕТ ЗАПРОС в трёх местах сразу.
//
//   1. Строковые значения. В 'Москва,  Тверская' два пробела -- это данные, а не отступ.
//      Сжатие пробелов внутри кавычек молча меняет то, что попадёт в базу.
//   2. Однострочные комментарии. Если склеить строки, всё после «--» окажется закомментировано
//      до конца запроса, и он либо не выполнится, либо выполнится не тот.
//   3. Подсказки оптимизатору. /*+ INDEX(t idx) */ выглядит как комментарий, но им не является:
//      это указание, по какому плану выполнять запрос. Выбросив его, мы молча меняем скорость
//      работы, а иногда и нагрузку на базу.
//
// Поэтому здесь свой проход со знанием того, где заканчивается литерал: одинарные и двойные
// кавычки, обратные апострофы MySQL, квадратные скобки T-SQL и долларовые кавычки PostgreSQL.

/** Диалекты, где обратная косая внутри строки экранирует следующий знак. */
const СО_СЛЕШЕМ = new Set(['mysql', 'mariadb', 'tidb', 'hive', 'spark']);

export function сжатьSQL(исходный, диалект = 'sql') {
  const текст = String(исходный ?? '');
  if (!текст.trim()) return '';
  const слеш = СО_СЛЕШЕМ.has(диалект);
  // Куски копим списком и ПОМЕЧАЕМ ЛИТЕРАЛЫ. Заключительная уборка пробелов обязана обходить
  // их стороной: первая версия чистила строку целиком и этим отменяла всё сохранение --
  // два пробела внутри 'Москва,  Тверская' снова схлопывались в один.
  const из = [];
  const литералы = new Set();
  let и = 0;

  /** Добавить кусок как есть, не трогая внутренности. */
  const как_есть = (кусок) => { литералы.add(из.length); из.push(кусок); };

  while (и < текст.length) {
    const з = текст[и];

    // --- комментарии ---
    if (з === '-' && текст[и + 1] === '-') {
      // До конца строки. Сам комментарий выбрасываем: склеив строки, мы бы закомментировали
      // всё, что идёт следом.
      while (и < текст.length && текст[и] !== '\n') и++;
      из.push(' ');
      continue;
    }
    if (з === '/' && текст[и + 1] === '*') {
      const подсказка = текст[и + 2] === '+';   // /*+ ... */ -- это не комментарий, а указание
      const конец = текст.indexOf('*/', и + 2);
      const кусок = конец === -1 ? текст.slice(и) : текст.slice(и, конец + 2);
      и = конец === -1 ? текст.length : конец + 2;
      if (подсказка) как_есть(кусок.replace(/\s+/g, ' '));
      else из.push(' ');
      continue;
    }

    // --- строки и имена в кавычках ---
    if (з === "'" || з === '"' || з === '`') {
      const закрывающая = з;
      // E'...' в PostgreSQL: там обратная косая экранирует, даже если в диалекте обычно нет.
      const сЭкраном = слеш || (з === "'" && /[eE]$/.test(из[из.length - 1] || ''));
      let к = и + 1;
      while (к < текст.length) {
        if (сЭкраном && текст[к] === '\\') { к += 2; continue; }
        if (текст[к] === закрывающая) {
          if (текст[к + 1] === закрывающая) { к += 2; continue; }   // удвоенная -- часть строки
          к++;
          break;
        }
        к++;
      }
      как_есть(текст.slice(и, к));
      и = к;
      continue;
    }
    if (з === '[') {
      // Имя в квадратных скобках -- T-SQL. Внутри может быть что угодно, включая пробелы.
      const конец = текст.indexOf(']', и + 1);
      const к = конец === -1 ? текст.length : конец + 1;
      как_есть(текст.slice(и, к));
      и = к;
      continue;
    }
    if (з === '$') {
      // Долларовые кавычки PostgreSQL: $$...$$ или $имя$...$имя$. Внутри -- тело функции,
      // где пробелы и переносы значимы.
      const метка = /^\$[A-Za-z_][A-Za-z_0-9]*\$|^\$\$/.exec(текст.slice(и));
      if (метка) {
        const конец = текст.indexOf(метка[0], и + метка[0].length);
        const к = конец === -1 ? текст.length : конец + метка[0].length;
        как_есть(текст.slice(и, к));
        и = к;
        continue;
      }
    }

    // --- пробелы ---
    if (/\s/.test(з)) {
      while (и < текст.length && /\s/.test(текст[и])) и++;
      из.push(' ');
      continue;
    }

    из.push(з);
    и++;
  }

  // Прибираем то, что осталось от выброшенных комментариев и переносов: лишний пробел перед
  // запятой, точкой с запятой и закрывающей скобкой смотрится неряшливо. Литералы при этом
  // не трогаем -- внутри них пробелы это данные.
  const готово = [];
  for (let к = 0; к < из.length; к++) {
    const кусок = из[к];
    if (литералы.has(к)) { готово.push(кусок); continue; }
    if (кусок === ' ') {
      // Пробелы подряд (например от двух выброшенных комментариев) сводим к одному.
      if (готово.length && готово[готово.length - 1] === ' ') continue;
      // Перед запятой, точкой с запятой и закрывающей скобкой пробел не нужен.
      let след = к + 1;
      while (след < из.length && !литералы.has(след) && из[след] === ' ') след++;
      if (след < из.length && !литералы.has(след) && ',;)'.includes(из[след])) continue;
      // После открывающей скобки -- тоже.
      const пред = готово[готово.length - 1];
      if (пред === '(' && !литералы.has(к - 1)) continue;
      готово.push(' ');
      continue;
    }
    готово.push(кусок);
  }
  return готово.join('').trim();
}
