// ПОИСК ПО ВЫРАЖЕНИЮ — В ОТДЕЛЬНОМ ПОТОКЕ.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ПОТОК. Регулярное выражение может считаться вечно. Классический пример --
// (a+)+$ на строке из тридцати букв «a» и одной «b»: движок перебирает разбиения, и их
// столько, что счёт идёт годами. Это не выдуманная беда, а обычное дело на странице, куда
// приходят пробовать выражения: человек ошибся во вложенном повторе -- и вкладка мертва,
// потому что остановить свой же счёт из того же потока нельзя.
//
// Поток же можно ПРЕРВАТЬ снаружи. Поэтому весь поиск живёт здесь, а страница ждёт ответа с
// часами в руках и, не дождавшись, убивает поток и честно говорит, что выражение зациклилось.
//
// ЕЩЁ ДВЕ ЛОВУШКИ, ОБЕ ЗАКРЫТЫ НИЖЕ:
//   -- пустое совпадение при флаге g. Выражение вроде a* находит пустоту в каждой позиции, и
//      наивный цикл никогда не сдвинется с места. Двигаем сами.
//   -- слишком много совпадений. На большом тексте их бывают сотни тысяч, и попытка отдать их
//      все убивает память. Ставим потолок и говорим, что показали не всё.

const ПОТОЛОК = 5000;

self.onmessage = (е) => {
  const { шаблон, флаги, текст } = е.data || {};

  let выражение;
  try {
    выражение = new RegExp(шаблон, флаги);
  } catch (о) {
    // Сообщение движка отдаём как есть: оно точнее любого нашего пересказа и говорит,
    // на каком именно месте выражение сломалось.
    self.postMessage({ беда: String(о.message || о) });
    return;
  }

  const совпадения = [];
  let оборвано = false;

  try {
    if (!флаги.includes('g')) {
      const м = выражение.exec(текст);
      if (м) совпадения.push(разобрать(м));
    } else {
      выражение.lastIndex = 0;
      let м;
      while ((м = выражение.exec(текст)) !== null) {
        совпадения.push(разобрать(м));
        // Пустое совпадение не двигает указатель -- сдвигаем сами, иначе цикл вечный.
        if (м[0] === '') выражение.lastIndex += 1;
        if (совпадения.length >= ПОТОЛОК) { оборвано = true; break; }
      }
    }
  } catch (о) {
    self.postMessage({ беда: String(о.message || о) });
    return;
  }

  self.postMessage({ совпадения, оборвано, потолок: ПОТОЛОК });

  function разобрать(м) {
    const группы = [];
    for (let и = 1; и < м.length; и++) {
      группы.push({ номер: и, имя: имяГруппы(м, и), текст: м[и] === undefined ? null : м[и] });
    }
    return { начало: м.index, конец: м.index + м[0].length, текст: м[0], группы };
  }

  /** Имя именованной группы, если совпадает по значению. Точнее сопоставить нечем. */
  function имяГруппы(м, номер) {
    if (!м.groups) return null;
    for (const [имя, значение] of Object.entries(м.groups)) {
      if (значение === м[номер]) return имя;
    }
    return null;
  }
};
