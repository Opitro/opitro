// СБОРКА СТРОКИ ГРАДИЕНТА ДЛЯ CSS.
//
// Здесь только правила записи и подсчёт запасного цвета. Разбор и показ -- дело браузера, и
// это удобно: правильность строки можно проверить не своим же кодом, а тем самым браузером,
// который её потом и покажет.
//
// ПРО СМЕШИВАНИЕ С ПРОЗРАЧНОСТЬЮ. Между двумя точками цвет считается не «в лоб», а с
// предварительным умножением на плотность. Разница видна на переходе из цветного в
// прозрачное: если смешивать в лоб, к прозрачному краю подмешивается чёрный и получается
// грязная серая полоса. Браузеры давно считают правильно, и запасной цвет мы считаем так же,
// иначе он не совпал бы с тем, что видно на экране.

import { вHex, вСтрокуRgb } from './color-convert.js';

const вграницах = (з, наим, наиб) => Math.min(наиб, Math.max(наим, з));

/** Точки по порядку, доли внутри 0..100. Порядок важен: CSS читает их слева направо. */
export function поПорядку(точки) {
  return [...точки]
    .map((т) => ({ ...т, доля: вграницах(Number(т.доля) || 0, 0, 100) }))
    .sort((а, б) => а.доля - б.доля);
}

/** Цвет одной точки в записи CSS: без прозрачности -- коротким HEX, с ней -- через rgba. */
function записьЦвета(точка) {
  const a = точка.цвет.a ?? 1;
  return a >= 1 ? вHex({ ...точка.цвет, a: 1 }) : вСтрокуRgb(точка.цвет);
}

/**
 * Строка градиента.
 * @param вид   -- 'linear' | 'radial'
 * @param угол  -- градусы для линейного
 * @param точки -- [{цвет: {r,g,b,a}, доля: 0..100}]
 */
export function вСтроку({ вид, угол, точки }) {
  const ряд = поПорядку(точки)
    .map((т) => `${записьЦвета(т)} ${Math.round(т.доля)}%`)
    .join(', ');
  if (вид === 'radial') {
    // circle at center -- чтобы круг оставался кругом на вытянутом блоке. Без этого браузер
    // берёт эллипс по размеру блока, и на широкой полосе получается не то, что в предпросмотре
    // квадратной формы.
    return `radial-gradient(circle at center, ${ряд})`;
  }
  return `linear-gradient(${Math.round(((угол % 360) + 360) % 360)}deg, ${ряд})`;
}

/**
 * Цвет в заданной доле пути. Смешивание -- с предварительным умножением на плотность, как
 * это делает сам браузер.
 */
export function цветНа(точки, доля) {
  const ряд = поПорядку(точки);
  if (!ряд.length) return { r: 0, g: 0, b: 0, a: 1 };
  if (доля <= ряд[0].доля) return { ...ряд[0].цвет };
  const последняя = ряд[ряд.length - 1];
  if (доля >= последняя.доля) return { ...последняя.цвет };

  let левая = ряд[0];
  let правая = последняя;
  for (let и = 0; и < ряд.length - 1; и++) {
    if (доля >= ряд[и].доля && доля <= ряд[и + 1].доля) {
      левая = ряд[и];
      правая = ряд[и + 1];
      break;
    }
  }
  const шаг = правая.доля - левая.доля;
  const к = шаг === 0 ? 0 : (доля - левая.доля) / шаг;

  const aЛ = левая.цвет.a ?? 1;
  const aП = правая.цвет.a ?? 1;
  const a = aЛ + (aП - aЛ) * к;
  if (a === 0) return { r: 0, g: 0, b: 0, a: 0 };
  // Умножаем на плотность, смешиваем, делим обратно -- так прозрачный край не тянет за собой
  // чёрный.
  const смесь = (кл) => {
    const л = левая.цвет[кл] * aЛ;
    const п = правая.цвет[кл] * aП;
    return Math.round((л + (п - л) * к) / a);
  };
  return { r: смесь('r'), g: смесь('g'), b: смесь('b'), a };
}

/**
 * Запасной сплошной цвет -- на случай, если градиент не поддержан. Берём цвет ровно в
 * середине перехода и убираем прозрачность: запасной цвет обязан быть плотным, иначе он не
 * спасёт читаемость текста, ради которой и ставится.
 */
export function запаснойЦвет(точки) {
  const ц = цветНа(точки, 50);
  return вHex({ r: ц.r, g: ц.g, b: ц.b, a: 1 });
}

/** Готовые строки для вставки в стили: сначала запасной цвет, потом сам градиент. */
export function кодCSS(состояние) {
  return `background-color: ${запаснойЦвет(состояние.точки)};\n`
    + `background-image: ${вСтроку(состояние)};`;
}
