
const УГЛЫ = ['лв', 'пв', 'пн', 'лн'];

const вграницах = (з, наим, наиб) => Math.min(наиб, Math.max(наим, з));

function четвёрка(значения, единица) {
  return УГЛЫ.map((у) => `${Math.round(значения[у])}${единица}`).join(' ');
}

export function вСтроку({ поперёк, вдоль, единица = 'px' }) {
  const первая = четвёрка(поперёк, единица);
  if (!вдоль) return первая;
  const вторая = четвёрка(вдоль, единица);

  return первая === вторая ? первая : `${первая} / ${вторая}`;
}

export function кодCSS(состояние) {
  return `border-radius: ${вСтроку(состояние)};`;
}

export function множительСжатия({ поперёк, вдоль, единица }, ширина, высота) {
  const в = вдоль || поперёк;

  const п = (з) => (единица === '%' ? (з / 100) * ширина : з);
  const пв = (з) => (единица === '%' ? (з / 100) * высота : з);

  const стороны = [
    (п(поперёк.лв) + п(поперёк.пв)) / ширина,
    (пв(в.пв) + пв(в.пн)) / высота,
    (п(поперёк.лн) + п(поперёк.пн)) / ширина,
    (пв(в.лв) + пв(в.лн)) / высота,
  ];
  const наибольшая = Math.max(...стороны, 0);
  return наибольшая > 1 ? 1 / наибольшая : 1;
}

export function ровно(значение, единица = 'px') {
  const з = вграницах(значение, 0, единица === '%' ? 100 : 200);
  const все = Object.fromEntries(УГЛЫ.map((у) => [у, з]));
  return { поперёк: все, вдоль: null, единица };
}

export function случайнаяКлякса(случай = Math.random) {
  const з = () => Math.round(25 + случай() * 50);
  return {
    поперёк: { лв: з(), пв: з(), пн: з(), лн: з() },
    вдоль: { лв: з(), пв: з(), пн: з(), лн: з() },
    единица: '%',
  };
}

export { УГЛЫ };
