// СБОРКА СТРОКИ border-radius.
//
// Свойство хитрее, чем кажется. У каждого из четырёх углов на самом деле ДВА радиуса --
// поперечный и продольный, -- и полная запись выглядит так:
//
//     border-radius: 30% 70% 70% 30% / 30% 30% 70% 70%;
//                    └── поперёк ──┘   └── вдоль ────┘
//
// До косой черты стоят радиусы по горизонтали, после -- по вертикали. Когда они совпадают,
// косую черту и вторую четвёрку опускают, и получается привычная короткая запись. Порядок
// углов всегда один: слева сверху, справа сверху, справа снизу, слева снизу -- по часовой
// стрелке от левого верхнего.
//
// ЗДЕСЬ ТОЛЬКО ПРАВИЛА ЗАПИСИ. Рисует браузер, и проверять правильность строки удобнее всего
// им же.

const УГЛЫ = ['лв', 'пв', 'пн', 'лн'];   // левый верхний, правый верхний, правый нижний, левый нижний

const вграницах = (з, наим, наиб) => Math.min(наиб, Math.max(наим, з));

/** Четвёрка значений с единицей измерения. */
function четвёрка(значения, единица) {
  return УГЛЫ.map((у) => `${Math.round(значения[у])}${единица}`).join(' ');
}

/**
 * Строка border-radius.
 * @param поперёк -- {лв, пв, пн, лн} радиусы по горизонтали
 * @param вдоль   -- то же по вертикали; если не задано или совпадает, косой черты не будет
 * @param единица -- 'px' | '%'
 */
export function вСтроку({ поперёк, вдоль, единица = 'px' }) {
  const первая = четвёрка(поперёк, единица);
  if (!вдоль) return первая;
  const вторая = четвёрка(вдоль, единица);
  // Одинаковые четвёрки писать дважды незачем: короткая запись читается легче, а значит
  // и правится потом легче.
  return первая === вторая ? первая : `${первая} / ${вторая}`;
}

export function кодCSS(состояние) {
  return `border-radius: ${вСтроку(состояние)};`;
}

/**
 * Уменьшатся ли скругления сами. Правило CSS: если на какой-то стороне сумма двух радиусов
 * больше длины стороны, БРАУЗЕР УМЕНЬШАЕТ ВСЕ радиусы разом -- на один и тот же множитель.
 * Об этом мало кто знает, а следствие заметное: поставив 100% всем углам, вы получите не
 * «очень круглые углы», а ровный овал, и дальше значения перестают что-либо менять.
 *
 * @returns множитель от 0 до 1; единица означает, что всё помещается как есть.
 */
export function множительСжатия({ поперёк, вдоль, единица }, ширина, высота) {
  const в = вдоль || поперёк;
  // В процентах радиус считается от своей стороны: поперечные -- от ширины, продольные -- от
  // высоты. В пикселях -- как есть.
  const п = (з) => (единица === '%' ? (з / 100) * ширина : з);
  const пв = (з) => (единица === '%' ? (з / 100) * высота : з);

  const стороны = [
    (п(поперёк.лв) + п(поперёк.пв)) / ширина,       // верх
    (пв(в.пв) + пв(в.пн)) / высота,                 // право
    (п(поперёк.лн) + п(поперёк.пн)) / ширина,       // низ
    (пв(в.лв) + пв(в.лн)) / высота,                 // лево
  ];
  const наибольшая = Math.max(...стороны, 0);
  return наибольшая > 1 ? 1 / наибольшая : 1;
}

/** Одно значение на все восемь -- для простого режима со связанными углами. */
export function ровно(значение, единица = 'px') {
  const з = вграницах(значение, 0, единица === '%' ? 100 : 200);
  const все = Object.fromEntries(УГЛЫ.map((у) => [у, з]));
  return { поперёк: все, вдоль: null, единица };
}

/**
 * Случайная «жидкая» фигура. Значения нарочно держатся подальше от краёв: при радиусах,
 * близких к нулю или к сотне, фигура вырождается в прямоугольник или в овал, и вся затея
 * с неровными углами пропадает.
 */
export function случайнаяКлякса(случай = Math.random) {
  const з = () => Math.round(25 + случай() * 50);      // 25..75 %
  return {
    поперёк: { лв: з(), пв: з(), пн: з(), лн: з() },
    вдоль: { лв: з(), пв: з(), пн: з(), лн: з() },
    единица: '%',
  };
}

export { УГЛЫ };
