let карта = null;

/** Загрузить карту границ. Грузится только тогда, когда в снимке есть координаты. */
async function взятьКарту() {
  if (карта) return карта;
  const [топо, { feature }] = await Promise.all([
    import('world-atlas/countries-110m.json'),
    import('topojson-client'),
  ]);
  const данные = топо.default || топо;
  карта = feature(данные, данные.objects.countries).features;
  return карта;
}

/** Точка внутри кольца? Считаем по лучу: сколько раз он пересёк границу -- чётно или нет. */
function вКольце(точка, кольцо) {
  const [x, y] = точка;
  let внутри = false;
  for (let i = 0, j = кольцо.length - 1; i < кольцо.length; j = i++) {
    const [xi, yi] = кольцо[i];
    const [xj, yj] = кольцо[j];
    const пересекает = (yi > y) !== (yj > y)
      && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi;
    if (пересекает) внутри = !внутри;
  }
  return внутри;
}

/** Точка в многоугольнике: внутри внешнего кольца и не в дырке. */
function вМногоугольнике(точка, кольца) {
  if (!кольца.length || !вКольце(точка, кольца[0])) return false;
  for (let i = 1; i < кольца.length; i++) if (вКольце(точка, кольца[i])) return false;
  return true;
}

/**
 * Страна по координатам.
 *
 * @returns {{код: string, имя: string}|null} двухбуквенный код и название на языке страницы
 */
export async function странаПоКоординатам(широта, долгота, язык = 'ru') {
  if (!isFinite(широта) || !isFinite(долгота)) return null;
  const страны = await взятьКарту();
  const точка = [долгота, широта];
  for (const страна of страны) {
    const г = страна.geometry;
    if (!г) continue;
    const куски = г.type === 'Polygon' ? [г.coordinates] : г.coordinates;
    for (const кусок of куски) {
      if (вМногоугольнике(точка, кусок)) {
        const код = КОДЫ[String(Number(страна.id))];
        if (!код) return { код: '', имя: страна.properties.name };
        let имя = страна.properties.name;
        try {
          имя = new Intl.DisplayNames([язык], { type: 'region' }).of(код) || имя;
        } catch (е) { /* браузер не умеет -- оставим английское название */ }
        return { код, имя };
      }
    }
  }
  return null;       // море, Антарктида или дырка в грубой карте
}

// ---- БЛИЖАЙШИЙ ГОРОД ---------------------------------------------------------------------------
//
// Точный адрес (улица, дом) в браузере получить нельзя: база адресов весит гигабайты, и
// спросить её можно только у чужой службы -- то есть отправить наружу координаты человека.
// Ради этого страница и существует, поэтому наружу мы не ходим.
//
// Зато ближайший город считается на устройстве: список городов от пятнадцати тысяч жителей
// весит 650 КБ и грузится только тогда, когда в снимке есть координаты.
//
// Если ближайший город дальше шестидесяти километров -- молчим. Назвать город, до которого час
// езды, значит соврать: снимок сделан не там.

let города = null;

async function взятьГорода() {
  if (города) return города;
  const { ГОРОДА } = await import('./cities.js');
  города = ГОРОДА.split('\n').map((строка) => {
    const [имя, страна, ш, д] = строка.split('\t');
    return { имя, страна, ш: +ш, д: +д };
  });
  return города;
}

/** Расстояние между точками по земле, в километрах (формула гаверсинуса). */
function вёрсты(ш1, д1, ш2, д2) {
  const рад = Math.PI / 180;
  const дш = (ш2 - ш1) * рад, дд = (д2 - д1) * рад;
  const а = Math.sin(дш / 2) ** 2
    + Math.cos(ш1 * рад) * Math.cos(ш2 * рад) * Math.sin(дд / 2) ** 2;
  return 6371 * 2 * Math.atan2(Math.sqrt(а), Math.sqrt(1 - а));
}

/**
 * Ближайший город к точке.
 *
 * @returns {{имя: string, страна: string, вёрст: number}|null} null -- если вокруг ничего нет
 */
export async function ближайшийГород(широта, долгота, потолок = 60) {
  if (!isFinite(широта) || !isFinite(долгота)) return null;
  const список = await взятьГорода();
  // Грубо отсекаем по клетке в один градус: перебирать двадцать четыре тысячи городов с
  // тригонометрией незачем, когда девяносто девять из ста отпадают вычитанием.
  let лучший = null, ближе = Infinity;
  for (const г of список) {
    if (Math.abs(г.ш - широта) > 1.2) continue;
    const поправка = Math.max(0.2, Math.cos(широта * Math.PI / 180));
    if (Math.abs(г.д - долгота) > 1.2 / поправка) continue;
    const в = вёрсты(широта, долгота, г.ш, г.д);
    if (в < ближе) { ближе = в; лучший = г; }
  }
  if (!лучший || ближе > потолок) return null;
  return { имя: лучший.имя, страна: лучший.страна, вёрст: Math.round(ближе) };
}
