// ХЭШИ: MD5, SHA-1, SHA-256, SHA-512.
//
// ТРИ СЕМЕЙСТВА SHA СЧИТАЕТ САМ БРАУЗЕР -- через crypto.subtle, тот же узел, на котором
// держится шифрование соединений. Своего кода там нет и быть не должно: чужая реализация
// хэша, написанная на коленке, ошибается редко и незаметно, а цена ошибки -- неверная
// контрольная сумма, по которой человек примет решение.
//
// MD5 ПРИХОДИТСЯ ПИСАТЬ САМОМУ. Браузеры его не дают нарочно: он давно сломан и выкинут из
// crypto.subtle, чтобы им не пользовались для защиты. Но проверять по нему целостность
// файлов не перестали, и на страницу его просят. Поэтому он здесь свой -- и сверен с
// системной командой md5 на тысяче случайных строк.
//
// КОДИРОВКА -- UTF-8, И ЭТО НЕ МЕЛОЧЬ. Хэш считается от БАЙТОВ, а не от букв. «привет» в
// UTF-8 и в windows-1251 -- разные наборы байтов и разные хэши. Инструменты, которые об этом
// молчат, дают человеку два разных ответа на одну строку, и он не понимает, кто прав.

/** Байты строки в UTF-8. Один и тот же способ для всех алгоритмов -- иначе они разойдутся. */
export const вБайты = (текст) => new TextEncoder().encode(String(текст ?? ''));

const шестнадцать = (байты) => {
  let с = '';
  for (const б of байты) с += б.toString(16).padStart(2, '0');
  return с;
};

// ---- MD5 ---------------------------------------------------------------------------------

const СДВИГИ = [
  7, 12, 17, 22, 7, 12, 17, 22, 7, 12, 17, 22, 7, 12, 17, 22,
  5, 9, 14, 20, 5, 9, 14, 20, 5, 9, 14, 20, 5, 9, 14, 20,
  4, 11, 16, 23, 4, 11, 16, 23, 4, 11, 16, 23, 4, 11, 16, 23,
  6, 10, 15, 21, 6, 10, 15, 21, 6, 10, 15, 21, 6, 10, 15, 21,
];

// Постоянные MD5 -- целые части от |sin(i+1)| * 2^32. Считаем, а не переписываем таблицу:
// в переписанной от руки таблице из 64 чисел опечатка почти неизбежна и незаметна.
const ПОСТОЯННЫЕ = (() => {
  const к = new Uint32Array(64);
  for (let и = 0; и < 64; и++) к[и] = Math.floor(Math.abs(Math.sin(и + 1)) * 2 ** 32);
  return к;
})();

const влево = (х, н) => (х << н) | (х >>> (32 - н));

/** MD5 от набора байтов. Возвращает строку из тридцати двух шестнадцатеричных знаков. */
export function md5(байты) {
  const длина = байты.length;
  // Дополнение: единичный бит, нули, и восемь байтов длины В БИТАХ, младшим концом вперёд.
  const сколько = (((длина + 8) >> 6) + 1) * 64;
  const х = new Uint8Array(сколько);
  х.set(байты);
  х[длина] = 0x80;
  const битов = длина * 8;
  // Длина кладётся как 64-битное число. Старшие четыре байта считаем отдельно: в JS сдвиг
  // работает на 32 битах, и «битов >>> 32» дал бы не ноль, а само число.
  const вид = new DataView(х.buffer);
  вид.setUint32(сколько - 8, битов >>> 0, true);
  вид.setUint32(сколько - 4, Math.floor(битов / 2 ** 32), true);

  let а = 0x67452301, б = 0xefcdab89, в = 0x98badcfe, г = 0x10325476;

  for (let место = 0; место < сколько; место += 64) {
    const м = new Uint32Array(16);
    for (let и = 0; и < 16; и++) м[и] = вид.getUint32(место + и * 4, true);

    let [аа, бб, вв, гг] = [а, б, в, г];
    for (let и = 0; и < 64; и++) {
      let ф, к;
      if (и < 16) { ф = (бб & вв) | (~бб & гг); к = и; }
      else if (и < 32) { ф = (гг & бб) | (~гг & вв); к = (5 * и + 1) % 16; }
      else if (и < 48) { ф = бб ^ вв ^ гг; к = (3 * и + 5) % 16; }
      else { ф = вв ^ (бб | ~гг); к = (7 * и) % 16; }
      const врем = гг;
      гг = вв;
      вв = бб;
      бб = (бб + влево((аа + ф + ПОСТОЯННЫЕ[и] + м[к]) | 0, СДВИГИ[и])) | 0;
      аа = врем;
    }
    а = (а + аа) | 0; б = (б + бб) | 0; в = (в + вв) | 0; г = (г + гг) | 0;
  }

  const итог = new Uint8Array(16);
  const вывод = new DataView(итог.buffer);
  вывод.setUint32(0, а >>> 0, true);
  вывод.setUint32(4, б >>> 0, true);
  вывод.setUint32(8, в >>> 0, true);
  вывод.setUint32(12, г >>> 0, true);
  return шестнадцать(итог);
}

// ---- SHA ---------------------------------------------------------------------------------

const ИМЕНА = { 'sha-1': 'SHA-1', 'sha-256': 'SHA-256', 'sha-512': 'SHA-512' };

/** SHA силами самого браузера. Требует защищённого соединения -- на http его попросту нет. */
export async function sha(имя, байты) {
  const родное = ИМЕНА[String(имя).toLowerCase()];
  if (!родное) throw new Error('НЕИЗВЕСТНЫЙ_АЛГОРИТМ');
  const узел = (typeof crypto !== 'undefined' && crypto.subtle) ? crypto.subtle : null;
  if (!узел) throw new Error('НЕТ_CRYPTO_SUBTLE');
  return шестнадцать(new Uint8Array(await узел.digest(родное, байты)));
}

/** Все четыре хэша разом. Порядок постоянный -- строки на странице не должны прыгать. */
export async function всеХэши(текст) {
  const байты = вБайты(текст);
  const [единица, двести, пятьсот] = await Promise.all([
    sha('sha-1', байты), sha('sha-256', байты), sha('sha-512', байты),
  ]);
  return [
    ['MD5', md5(байты)],
    ['SHA-1', единица],
    ['SHA-256', двести],
    ['SHA-512', пятьсот],
  ];
}
