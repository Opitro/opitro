// Синтез речи своим голосом -- в стороне от страницы.
//
// Piper считает арифметику: на нашей проверке 0.98 секунды на семь секунд звука. На своём
// потоке страницы это значило бы, что при длинном тексте всё замирает на десятки секунд, и
// Chrome показал бы «Страница не отвечает» с предложением её закрыть. Ничего плохого при
// этом не происходит -- браузер просто не умеет отличить занятый поток от повисшего.
// У работника поток свой: страница продолжает рисоваться, шкала едет, отклик не страдает.
//
// Разговор идёт простыми сообщениями: {тип} туда, {тип} обратно. Страница никогда не трогает
// модель напрямую.
//
// Модель приезжает с Hugging Face один раз и остаётся в хранилище браузера (OPFS). Текст
// никуда не отправляется: его вообще некуда отправлять, весь расчёт здесь.

import { TtsSession, stored, remove } from './piper/piper-tts-web.js';

const шли = (весть) => self.postMessage(весть);

let занятие = null;
let ключЗанятия = '';

// Скорость у человека и «длина» у Piper -- обратные величины: чем больше lengthScale, тем
// медленнее речь. Проверено замером: 1.6 / из модели / 0.7 дают 3.44 / 2.08 / 1.82 секунды
// на одной и той же фразе.
const вДлину = (скорость) => (скорость && скорость > 0 ? 1 / скорость : undefined);

async function готовое(голос, приЗагрузке) {
  if (занятие && ключЗанятия === голос) return занятие;
  занятие = await TtsSession.create({
    voiceId: голос,
    progress: (п) => {
      if (!п || !п.total) return;
      // Сюда же прилетают вести о ходе САМОГО СИНТЕЗА (кусок из скольких), а не только о
      // скачивании. Отличаем по адресу: у синтеза он служебный, не сетевой.
      const это_синтез = typeof п.url === 'string' && !/^https?:/.test(п.url);
      приЗагрузке(Math.min(100, (п.loaded / п.total) * 100), это_синтез);
    },
    logger: () => {},
  });
  ключЗанятия = голос;
  return занятие;
}

self.onmessage = async (е) => {
  const д = е.data || {};
  try {
    if (д.тип === 'что-скачано') {
      шли({ тип: 'что-скачано', список: await stored() });
      return;
    }

    if (д.тип === 'забыть') {
      await remove(д.голос);
      if (ключЗанятия === д.голос) { занятие = null; ключЗанятия = ''; }
      шли({ тип: 'забыто', голос: д.голос, список: await stored() });
      return;
    }

    if (д.тип === 'скачать') {
      шли({ тип: 'ход', этап: 'скачивание', доля: 0 });
      await готовое(д.голос, (доля, синтез) => {
        if (!синтез) шли({ тип: 'ход', этап: 'скачивание', доля });
      });
      шли({ тип: 'готов', голос: д.голос, список: await stored() });
      return;
    }

    if (д.тип === 'синтез') {
      шли({ тип: 'ход', этап: 'подготовка', доля: 0 });
      const с = await готовое(д.голос, (доля, синтез) => {
        шли({ тип: 'ход', этап: синтез ? 'синтез' : 'скачивание', доля });
      });
      с.speakerId = д.номер || 0;
      с.lengthScale = вДлину(д.скорость);
      шли({ тип: 'ход', этап: 'синтез', доля: 0 });
      const начало = performance.now();
      const wav = await с.predict(д.текст);
      const байты = await wav.arrayBuffer();
      шли({
        тип: 'готово',
        байты,
        секунд: (performance.now() - начало) / 1000,
        список: await stored(),
      }, [байты]);
      return;
    }
  } catch (ошибка) {
    // Занятие могло остаться недоделанным -- следующая попытка должна начинать заново, иначе
    // человек будет упираться в одну и ту же беду до перезагрузки страницы.
    занятие = null;
    ключЗанятия = '';
    шли({ тип: 'беда', текст: String((ошибка && (ошибка.message || ошибка)) || 'ошибка') });
  }
};
