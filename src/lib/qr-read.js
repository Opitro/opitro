// ГЛАВНОЕ ЗДЕСЬ -- НЕ РАСПОЗНАВАНИЕ, А БЕЗОПАСНОСТЬ ССЫЛКИ.
//
// В задании сказано «абсолютно безопасно» -- но про доступ к камере. А настоящая опасность
// QR-кода в другом: код нельзя прочитать глазами, и человек узнаёт, куда его ведут, только
// после перехода. На этом и построено целое семейство обманов -- наклейку с чужим кодом
// лепят поверх настоящей на парковочном автомате, в кафе, на счёте за коммуналку.
//
// Поэтому сканер обязан: НИКОГДА ничего не открывать сам, показывать ПОЛНЫЙ адрес текстом
// до всякого перехода и вслух называть подозрительное. Проверяем четыре вещи, каждая из
// которых встречается в живых обманах:
//   1. Собачка в адресе: https://sberbank.ru@evil.example -- браузер пойдёт на evil.example,
//      а человек читает начало и видит знакомое имя.
//   2. Punycode (xn--): имя из букв, неотличимых на вид от латинских -- «аpple.com», где «а»
//      кириллическая. В адресной строке выглядит как настоящее.
//   3. Чужая схема: javascript:, data:, file: -- по такой ссылке переходить нельзя вовсе.
//   4. Тот же обман через двоеточие с паролем: https://a:b@evil.example.

/** Снимаем экранирование строки Wi-Fi: без этого пароль показывается неверным. */
export function снятьЭкранWifi(с) {
  return String(с ?? '').replace(/\\(.)/g, '$1');
}

/** Снимаем экранирование vCard: обратный ход к \\ \; \, и \n. */
export function снятьЭкранВизитки(с) {
  return String(с ?? '')
    .replace(/\\n/gi, '\n')
    .replace(/\\([\\;,])/g, '$1');
}

/** Разбор строки Wi-Fi. Поля идут в любом порядке, поэтому читаем по меткам. */
function разобратьWifi(текст) {
  const тело = текст.slice(5).replace(/;;\s*$/, '');
  const поля = {};
  // Делим по неэкранированным точкам с запятой: иначе пароль «Pa\;ss» развалится надвое.
  const части = [];
  let кусок = '';
  for (let и = 0; и < тело.length; и++) {
    if (тело[и] === '\\') { кусок += тело[и] + (тело[и + 1] ?? ''); и++; continue; }
    if (тело[и] === ';') { части.push(кусок); кусок = ''; continue; }
    кусок += тело[и];
  }
  if (кусок) части.push(кусок);
  for (const ч of части) {
    const н = ч.indexOf(':');
    if (н === -1) continue;
    поля[ч.slice(0, н).toUpperCase()] = снятьЭкранWifi(ч.slice(н + 1));
  }
  return {
    имя: поля.S || '',
    пароль: поля.P || '',
    защита: поля.T || 'nopass',
    скрытая: String(поля.H || '').toLowerCase() === 'true',
  };
}

/** Разбор визитки: берём поля, которые человеку интересны. */
function разобратьВизитку(текст) {
  const из = {};
  for (const строка of текст.split(/\r?\n/)) {
    const н = строка.indexOf(':');
    if (н === -1) continue;
    const метка = строка.slice(0, н).toUpperCase().split(';')[0];
    const значение = снятьЭкранВизитки(строка.slice(н + 1));
    if (метка === 'FN') из.имя = значение;
    else if (метка === 'N' && !из.имя) из.имя = значение.split(';').filter(Boolean).reverse().join(' ');
    else if (метка === 'ORG') из.организация = значение;
    else if (метка === 'TITLE') из.должность = значение;
    else if (метка === 'TEL') из.телефон = значение;
    else if (метка === 'EMAIL') из.почта = значение;
    else if (метка === 'URL') из.сайт = значение;
  }
  return из;
}

const БЕЗОПАСНЫЕ_СХЕМЫ = new Set(['http:', 'https:', 'mailto:', 'tel:', 'sms:', 'geo:']);

/**
 * Разбор ссылки с проверкой на обман. Возвращает {адрес, узел, схема, переходить, тревоги[]}.
 * «переходить» -- можно ли вообще предлагать переход (только http и https).
 */
export function разобратьСсылку(текст) {
  let у;
  try { у = new URL(текст); } catch (е) { return null; }
  const тревоги = [];
  const схема = у.protocol;

  if (!БЕЗОПАСНЫЕ_СХЕМЫ.has(схема)) тревоги.push({ вид: 'схема', что: схема });
  // Собачка в адресе: всё до неё -- это имя пользователя, а не сайт.
  if (у.username || у.password) тревоги.push({ вид: 'собачка', что: у.hostname });
  // Punycode: имя записано знаками, неотличимыми на вид от латинских.
  if (/(^|\.)xn--/i.test(у.hostname)) тревоги.push({ вид: 'punycode', что: у.hostname });
  // Тот же обман, но записанный так, что URL-разбор не выделил имя пользователя.
  // Только для http и https: в mailto: собачка -- это и есть суть адреса, и тревожиться там
  // не о чем (первая проверка поднимала ложную тревогу на каждом mailto:).
  const сетевая = схема === 'http:' || схема === 'https:';
  if (сетевая && !у.username && /@/.test(у.pathname + у.search)) {
    тревоги.push({ вид: 'собачка-в-пути', что: у.hostname });
  }

  return {
    адрес: у.href,
    узел: у.hostname,
    схема,
    переходить: схема === 'http:' || схема === 'https:',
    тревоги,
  };
}

/** Что это вообще такое. Возвращает {вид, поля} -- вид: url | wifi | card | tel | mail | text. */
export function разобратьСодержимое(текст) {
  const т = String(текст ?? '');
  if (!т) return { вид: 'text', текст: '' };

  if (/^WIFI:/i.test(т)) return { вид: 'wifi', сеть: разобратьWifi(т), текст: т };
  if (/^BEGIN:VCARD/i.test(т)) return { вид: 'card', визитка: разобратьВизитку(т), текст: т };
  if (/^tel:/i.test(т)) return { вид: 'tel', номер: т.slice(4), текст: т };
  if (/^(mailto|smsto|sms):/i.test(т)) return { вид: 'mail', адрес: т.replace(/^[a-z]+:/i, ''), текст: т };

  const ссылка = разобратьСсылку(т);
  if (ссылка) return { вид: 'url', ссылка, текст: т };
  // Голое имя сайта без схемы -- частый случай. Ссылкой не называем, но узнаём.
  if (/^[a-z0-9-]+(\.[a-z0-9-]+)+(\/\S*)?$/i.test(т) && т.length < 300) {
    const п = разобратьСсылку('https://' + т);
    if (п) return { вид: 'url', ссылка: п, безСхемы: true, текст: т };
  }
  return { вид: 'text', текст: т };
}
