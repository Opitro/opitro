/**
 * PP-OCR В БРАУЗЕРЕ: НЕЙРОСЕТЬ ВМЕСТО РАЗБОРА СТРОК.
 *
 * Зачем это понадобилось. Tesseract ищет на снимке ровные строки тёмных букв на светлом --
 * он придуман для документов. Фотография товара ему не по зубам: владелец снял пакет молока
 * с французской этикеткой, и мы вернули кашу из обрывков. Ни точная модель, ни выравнивание,
 * ни подбор цветового канала это до конца не вылечили.
 *
 * Здесь работа поделена надвое, и каждую половину делает своя обученная сеть:
 *   1. ДЕТЕКТОР находит на снимке куски текста -- любые, хоть под углом, хоть на коробке;
 *   2. РАСПОЗНАВАТЕЛЬ читает каждый кусок отдельно, уже выпрямленным.
 *
 * Так устроены все нынешние сильные сканеры. Веса -- официальные, PP-OCRv5 mobile: детектор
 * 4,6 МБ, распознаватель латиницы 7,7 МБ, кириллицы 7,7 МБ. Считается всё на устройстве
 * человека: onnxruntime возьмёт видеокарту, если она есть, и процессор, если нет.
 */
import { СЛОВАРИ } from './ocr-dicts.js';

const ПУТЬ = '/ocr/';
let ортОбещание = null;
const сети = new Map();

/** Сам движок вычислений. Берём его один раз и настраиваем на наши файлы. */
async function орт() {
  if (ортОбещание) return ортОбещание;
  ортОбещание = (async () => {
    const ort = await import('onnxruntime-web');
    // Файлы движка лежат у нас: ничего не тянем с чужих сайтов, как и всё остальное на сайте.
    // Указываем их ПОИМЁННО: по одному пути движок просит сборку с поддержкой видеокарты
    // (jsep), а она весит 21 МБ. Нам хватает обычной на 11 МБ -- считаем на процессоре.
    ort.env.wasm.wasmPaths = {
      mjs: ПУТЬ + 'ort-wasm-simd-threaded.mjs',
      wasm: ПУТЬ + 'ort-wasm-simd-threaded.wasm',
    };
    // Потоки не включаем: они требуют особых заголовков (cross-origin isolation), которых на
    // обычной странице нет, и без них движок молча падает на старте.
    ort.env.wasm.numThreads = 1;
    ort.env.wasm.simd = true;
    return ort;
  })();
  return ортОбещание;
}

/** Загрузить сеть по имени файла. Каждая приезжает один раз и остаётся в памяти вкладки. */
async function сеть(имя, ход) {
  if (сети.has(имя)) return сети.get(имя);
  const обещание = (async () => {
    const ort = await орт();
    if (ход) ход({ качаем: имя });
    const ответ = await fetch(ПУТЬ + имя);
    if (!ответ.ok) throw new Error('не скачалась сеть ' + имя);
    const байты = new Uint8Array(await ответ.arrayBuffer());
    return ort.InferenceSession.create(байты, { executionProviders: ['wasm'] });
  })();
  сети.set(имя, обещание);
  try { return await обещание; } catch (е) { сети.delete(имя); throw е; }
}

/* ---- Детектор -------------------------------------------------------------------------- */

/**
 * Подготовить снимок для детектора: стороны кратны 32, значения нормированы так же, как при
 * обучении. Длинную сторону держим в пределах 960 точек -- этого хватает, чтобы найти даже
 * мелкие подписи, а считается быстро.
 */
function кадрДляДетектора(картинка, предел = 960) {
  const ш0 = картинка.width, в0 = картинка.height;
  const к = Math.min(1, предел / Math.max(ш0, в0));
  const ш = Math.max(32, Math.round((ш0 * к) / 32) * 32);
  const в = Math.max(32, Math.round((в0 * к) / 32) * 32);
  const холст = document.createElement('canvas');
  холст.width = ш; холст.height = в;
  холст.getContext('2d', { willReadFrequently: true }).drawImage(картинка, 0, 0, ш, в);
  const точки = холст.getContext('2d').getImageData(0, 0, ш, в).data;
  const данные = new Float32Array(3 * ш * в);
  const средн = [0.485, 0.456, 0.406], разброс = [0.229, 0.224, 0.225];
  for (let i = 0, п = 0; i < точки.length; i += 4, п++) {
    данные[п] = (точки[i] / 255 - средн[0]) / разброс[0];
    данные[ш * в + п] = (точки[i + 1] / 255 - средн[1]) / разброс[1];
    данные[2 * ш * в + п] = (точки[i + 2] / 255 - средн[2]) / разброс[2];
  }
  return { данные, ш, в, кХ: ш0 / ш, кУ: в0 / в };
}

/**
 * Связные пятна на карте вероятностей -- это и есть куски текста. Обходим карту вширь
 * (очередью, а не рекурсией: рекурсия на большом снимке кладёт вкладку переполнением стека).
 */
function пятна(карта, ш, в, порог = 0.3, наименьшее = 12) {
  const видели = new Uint8Array(ш * в);
  const найденные = [];
  const очередь = new Int32Array(ш * в);
  for (let старт = 0; старт < ш * в; старт++) {
    if (видели[старт] || карта[старт] < порог) continue;
    let голова = 0, хвост = 0;
    очередь[хвост++] = старт;
    видели[старт] = 1;
    const точки = [];
    while (голова < хвост) {
      const п = очередь[голова++];
      const х = п % ш, у = (п / ш) | 0;
      точки.push(х, у);
      for (let ду = -1; ду <= 1; ду++) for (let дх = -1; дх <= 1; дх++) {
        if (!дх && !ду) continue;
        const х2 = х + дх, у2 = у + ду;
        if (х2 < 0 || у2 < 0 || х2 >= ш || у2 >= в) continue;
        const п2 = у2 * ш + х2;
        if (видели[п2] || карта[п2] < порог) continue;
        видели[п2] = 1;
        очередь[хвост++] = п2;
      }
    }
    if (точки.length / 2 >= наименьшее) найденные.push(точки);
  }
  return найденные;
}

/** Выпуклая оболочка (обход Эндрю): нужна, чтобы найти самый тесный повёрнутый прямоугольник. */
function оболочка(точки) {
  const пары = [];
  for (let i = 0; i < точки.length; i += 2) пары.push([точки[i], точки[i + 1]]);
  пары.sort((а, б) => (а[0] - б[0]) || (а[1] - б[1]));
  const крест = (о, а, б) => (а[0] - о[0]) * (б[1] - о[1]) - (а[1] - о[1]) * (б[0] - о[0]);
  const низ = [];
  for (const т of пары) {
    while (низ.length >= 2 && крест(низ[низ.length - 2], низ[низ.length - 1], т) <= 0) низ.pop();
    низ.push(т);
  }
  const верх = [];
  for (let i = пары.length - 1; i >= 0; i--) {
    const т = пары[i];
    while (верх.length >= 2 && крест(верх[верх.length - 2], верх[верх.length - 1], т) <= 0) верх.pop();
    верх.push(т);
  }
  низ.pop(); верх.pop();
  return низ.concat(верх);
}

/**
 * Самый тесный прямоугольник вокруг пятна -- с поворотом. Крутим «штангенциркулем»: по
 * каждой стороне оболочки примеряем прямоугольник и берём наименьший по площади. Именно он
 * даёт угол наклона строки, по которому её потом выпрямляют.
 */
function тесныйПрямоугольник(оболочкаТочек) {
  let лучший = null;
  const н = оболочкаТочек.length;
  for (let i = 0; i < н; i++) {
    const [х1, у1] = оболочкаТочек[i];
    const [х2, у2] = оболочкаТочек[(i + 1) % н];
    const угол = Math.atan2(у2 - у1, х2 - х1);
    const кос = Math.cos(-угол), син = Math.sin(-угол);
    let минХ = Infinity, махХ = -Infinity, минУ = Infinity, махУ = -Infinity;
    for (const [х, у] of оболочкаТочек) {
      const пх = х * кос - у * син, пу = х * син + у * кос;
      if (пх < минХ) минХ = пх; if (пх > махХ) махХ = пх;
      if (пу < минУ) минУ = пу; if (пу > махУ) махУ = пу;
    }
    const площадь = (махХ - минХ) * (махУ - минУ);
    if (!лучший || площадь < лучший.площадь) {
      лучший = { площадь, угол, минХ, махХ, минУ, махУ };
    }
  }
  if (!лучший) return null;
  const { угол, минХ, махХ, минУ, махУ } = лучший;
  const кос = Math.cos(угол), син = Math.sin(угол);
  const вернуть = (пх, пу) => [пх * кос - пу * син, пх * син + пу * кос];
  return {
    углы: [вернуть(минХ, минУ), вернуть(махХ, минУ), вернуть(махХ, махУ), вернуть(минХ, махУ)],
    ширина: махХ - минХ,
    высота: махУ - минУ,
    угол,
  };
}

/** Немного расширить рамку: сеть очерчивает буквы впритык, и края букв иначе срезаются. */
function расширить(углы, доля = 0.12) {
  const цх = (углы[0][0] + углы[2][0]) / 2, цу = (углы[0][1] + углы[2][1]) / 2;
  return углы.map(([х, у]) => [цх + (х - цх) * (1 + доля), цу + (у - цу) * (1 + доля)]);
}

/** Найти на снимке куски текста. Возвращает рамки в координатах ИСХОДНОГО снимка. */
export async function найтиСтроки(картинка, { ход, предел = 960, порог = 0.3 } = {}) {
  const ort = await орт();
  const сеточка = await сеть('det.onnx', ход);
  const { данные, ш, в, кХ, кУ } = кадрДляДетектора(картинка, предел);
  const вход = new ort.Tensor('float32', данные, [1, 3, в, ш]);
  const имяВхода = сеточка.inputNames[0];
  const ответ = await сеточка.run({ [имяВхода]: вход });
  const карта = ответ[сеточка.outputNames[0]].data;

  const рамки = [];
  for (const точки of пятна(карта, ш, в, порог)) {
    const охват = оболочка(точки);
    if (охват.length < 3) continue;
    const п = тесныйПрямоугольник(охват);
    if (!п) continue;
    // Совсем мелкие пятна -- это шум, а не буквы.
    if (Math.min(п.ширина, п.высота) < 3 || Math.max(п.ширина, п.высота) < 8) continue;
    рамки.push({
      углы: расширить(п.углы).map(([х, у]) => [х * кХ, у * кУ]),
      ширина: п.ширина * кХ,
      высота: п.высота * кУ,
    });
  }
  // Сверху вниз, слева направо -- как читает человек.
  рамки.sort((а, б) => {
    const ау = Math.min(...а.углы.map((т) => т[1])), бу = Math.min(...б.углы.map((т) => т[1]));
    if (Math.abs(ау - бу) > Math.min(а.высота, б.высота) * 0.6) return ау - бу;
    return Math.min(...а.углы.map((т) => т[0])) - Math.min(...б.углы.map((т) => т[0]));
  });
  return рамки;
}

/* ---- Распознаватель ---------------------------------------------------------------------- */

/**
 * Вырезать кусок по рамке и ВЫПРЯМИТЬ его. Строка на фотографии почти всегда лежит под углом;
 * распознаватель же ждёт ровную полоску высотой 48 точек. Поворачиваем холстом -- это тот же
 * поворот, что делает человек, разглядывая косо лежащий лист.
 */
function вырезать(картинка, рамка, высотаЦели = 48) {
  const [а, б, в, г] = рамка.углы;
  const верх = Math.hypot(б[0] - а[0], б[1] - а[1]);
  const низ = Math.hypot(в[0] - г[0], в[1] - г[1]);
  const лево = Math.hypot(г[0] - а[0], г[1] - а[1]);
  const право = Math.hypot(в[0] - б[0], в[1] - б[1]);
  const ширина = Math.max(верх, низ);
  const высота = Math.max(лево, право);
  const к = высотаЦели / Math.max(8, высота);
  const цельШ = Math.max(16, Math.round(ширина * к));
  const холст = document.createElement('canvas');
  холст.width = цельШ; холст.height = высотаЦели;
  const кон = холст.getContext('2d', { willReadFrequently: true });
  кон.imageSmoothingQuality = 'high';

  // РАЗГИБАЕМ КУСОК ПОЛОСКАМИ. Надпись на пакете или банке идёт по кривой: у такой рамки
  // верхняя и нижняя стороны не параллельны, и простым поворотом её не выпрямить -- буквы
  // остаются кривыми, а распознаватель выдаёт «MNAAAW» вместо «MILSANI».
  //
  // Поэтому режем кусок на узкие вертикальные полоски и каждую ставим на место отдельно:
  // левый край берём с одной стороны рамки, правый -- с другой. Много маленьких поворотов
  // складываются в разгибание кривой -- тот же приём, каким выпрямляют скан книги у корешка.
  const полосок = Math.max(1, Math.min(96, Math.round(цельШ / 8)));
  const вдоль = (т1, т2, доля) => [т1[0] + (т2[0] - т1[0]) * доля, т1[1] + (т2[1] - т1[1]) * доля];
  for (let i = 0; i < полосок; i++) {
    const д1 = i / полосок, д2 = (i + 1) / полосок;
    const вх1 = вдоль(а, б, д1), вх2 = вдоль(а, б, д2);
    const нх1 = вдоль(г, в, д1);
    // Полоска задаётся своим верхним левым углом и двумя направлениями: вдоль строки и вниз.
    const шагХ = (вх2[0] - вх1[0]) * (полосок / цельШ);
    const шагУ = (вх2[1] - вх1[1]) * (полосок / цельШ);
    const внизХ = (нх1[0] - вх1[0]) / высотаЦели;
    const внизУ = (нх1[1] - вх1[1]) / высотаЦели;
    кон.save();
    кон.beginPath();
    кон.rect(Math.floor(д1 * цельШ), 0, Math.ceil(цельШ / полосок) + 1, высотаЦели);
    кон.clip();
    // Преобразование: куда смещается точка холста при шаге вправо и вниз.
    кон.setTransform(1, 0, 0, 1, 0, 0);
    const обр = обратное(шагХ, шагУ, внизХ, внизУ, вх1[0] - (д1 * цельШ) * шагХ, вх1[1] - (д1 * цельШ) * шагУ);
    if (обр) {
      кон.setTransform(обр.a, обр.b, обр.c, обр.d, обр.e, обр.f);
      кон.drawImage(картинка, 0, 0);
    }
    кон.restore();
  }
  кон.setTransform(1, 0, 0, 1, 0, 0);
  return холст;
}

/**
 * Обратное преобразование: мы знаем, куда холст отображается на снимок, а рисовать надо
 * наоборот. Матрица два на два с переносом -- разворачиваем её по правилу обратной матрицы.
 */
function обратное(a, b, c, d, e, f) {
  const опр = a * d - b * c;
  if (!опр || !isFinite(опр)) return null;
  return {
    a: d / опр, b: -b / опр, c: -c / опр, d: a / опр,
    e: (c * f - d * e) / опр, f: (b * e - a * f) / опр,
  };
}

/** Тот же кусок в обращённых цветах: белое становится чёрным, и надпись читается как обычная. */
function обратитьЦвета(холст) {
  const копия = document.createElement('canvas');
  копия.width = холст.width; копия.height = холст.height;
  const кон = копия.getContext('2d', { willReadFrequently: true });
  кон.drawImage(холст, 0, 0);
  const д = кон.getImageData(0, 0, копия.width, копия.height);
  const п = д.data;
  for (let i = 0; i < п.length; i += 4) { п[i] = 255 - п[i]; п[i + 1] = 255 - п[i + 1]; п[i + 2] = 255 - п[i + 2]; }
  кон.putImageData(д, 0, 0);
  return копия;
}

/** Расшифровка CTC: сеть выдаёт по знаку на столбик, повторы и пустые столбцы выбрасываем. */
function расшифровать(данные, шагов, классов, словарь) {
  // В обученной модели нулевой класс -- «пусто», дальше идут знаки словаря, а последним
  // обычно стоит пробел. Подгоняем словарь под то, сколько классов у сети на самом деле:
  // разошлись бы на единицу -- и текст поехал бы на букву в сторону.
  const знаки = ['', ...словарь];
  while (знаки.length < классов) знаки.push(' ');
  let вышло = '';
  let прежний = -1;
  let сумма = 0, счёт = 0;
  for (let т = 0; т < шагов; т++) {
    let лучший = 0, лучшая = -Infinity;
    for (let к = 0; к < классов; к++) {
      const з = данные[т * классов + к];
      if (з > лучшая) { лучшая = з; лучший = к; }
    }
    if (лучший !== 0 && лучший !== прежний) {
      вышло += знаки[лучший] ?? '';
      сумма += лучшая; счёт++;
    }
    прежний = лучший;
  }
  return { текст: вышло, уверенность: счёт ? Math.round((сумма / счёт) * 100) : 0 };
}

/** Прочитать один кусок. Азбука -- 'latin' или 'cyrillic'. */
async function прочитатьКусок(холст, азбука, ход) {
  const ort = await орт();
  const имяФайла = азбука === 'cyrillic' ? 'rec-cyrillic.onnx' : 'rec-latin.onnx';
  const сеточка = await сеть(имяФайла, ход);
  const ш = холст.width, в = холст.height;
  const точки = холст.getContext('2d').getImageData(0, 0, ш, в).data;
  const данные = new Float32Array(3 * ш * в);
  // Нормировка обучения: значение из [0,1] сдвигается в [-1,1].
  for (let i = 0, п = 0; i < точки.length; i += 4, п++) {
    данные[п] = (точки[i] / 255 - 0.5) / 0.5;
    данные[ш * в + п] = (точки[i + 1] / 255 - 0.5) / 0.5;
    данные[2 * ш * в + п] = (точки[i + 2] / 255 - 0.5) / 0.5;
  }
  const вход = new ort.Tensor('float32', данные, [1, 3, в, ш]);
  const ответ = await сеточка.run({ [сеточка.inputNames[0]]: вход });
  const выход = ответ[сеточка.outputNames[0]];
  const [, шагов, классов] = выход.dims;
  return расшифровать(выход.data, шагов, классов, СЛОВАРИ[азбука] || СЛОВАРИ.latin);
}

/**
 * ПРОЧИТАТЬ СНИМОК ЦЕЛИКОМ: найти куски текста и прочитать каждый.
 *
 * Азбуку выбираем сами: читаем первые несколько кусков латиницей и кириллицей и смотрим, чей
 * ответ увереннее. Человеку выбирать нечего -- он принёс снимок, а не задачу по языкознанию.
 */
export async function прочитатьСнимок(картинка, { ход, азбука = 'авто' } = {}) {
  const рамки = await найтиСтроки(картинка, { ход });
  if (!рамки.length) return { строки: [], текст: '', азбука: null };

  const куски = рамки.map((р) => вырезать(картинка, р));
  let выбранная = азбука;
  if (азбука === 'авто') {
    const пробных = куски.slice(0, Math.min(4, куски.length));
    let лучшая = 'latin', лучшийСчёт = -1;
    for (const я of ['latin', 'cyrillic']) {
      let сумма = 0;
      for (const к of пробных) {
        const { текст, уверенность } = await прочитатьКусок(к, я, ход);
        сумма += уверенность * Math.min(1, текст.trim().length / 4);
      }
      if (сумма > лучшийСчёт) { лучшийСчёт = сумма; лучшая = я; }
    }
    выбранная = лучшая;
  }

  const строки = [];
  for (let i = 0; i < куски.length; i++) {
    if (ход) ход({ читаем: i + 1, всего: куски.length });
    let лучшее = await прочитатьКусок(куски[i], выбранная, ход);
    // СВЕТЛЫЕ БУКВЫ НА ТЁМНОМ читаются хуже: распознаватель приучен к тёмному по светлому.
    // Если кусок вышел неуверенным, пробуем его же в обращённых цветах -- на упаковках и
    // вывесках белая надпись по цветному полю встречается постоянно.
    if (лучшее.уверенность < 80) {
      const наоборот = обратитьЦвета(куски[i]);
      const второе = await прочитатьКусок(наоборот, выбранная, ход);
      if (второе.уверенность > лучшее.уверенность + 4) лучшее = второе;
    }
    if (!лучшее.текст.trim()) continue;
    строки.push({ текст: лучшее.текст.trim(), уверенность: лучшее.уверенность, рамка: рамки[i] });
  }
  return { строки, текст: строки.map((с) => с.текст).join('\n'), азбука: выбранная };
}
