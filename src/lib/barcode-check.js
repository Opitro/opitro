// ПРОВЕРКА ДАННЫХ ДЛЯ ШТРИХКОДА.
//
// Рисует библиотека JsBarcode, и рисует хорошо. Но на вопрос «почему не получилось» она
// отвечает одним словом: невалидно. Для человека это бесполезно, а случаи все разные:
//
//   -- CODE128 не принимает кириллицу. «Товар-1» отвергается молча, и владелец магазина
//      думает, что сломан сайт. На деле в штрихкод этого стандарта помещаются только знаки
//      таблицы ASCII: цифры, латиница и знаки препинания.
//   -- EAN-13 из тринадцати цифр отвергается, если последняя не сходится. Библиотека не
//      говорит, какой она должна быть, -- а это простой расчёт, и его можно показать.
//   -- CODE39 печатает строчные буквы ЗАГЛАВНЫМИ. Код при этом годный, но напечатано будет
//      не то, что ввели, и об этом надо предупредить заранее.
//
// Здесь считается контрольная цифра и составляются понятные сообщения. Сам рисунок -- за
// библиотекой.

/**
 * Контрольная цифра для семейства EAN (EAN-8, EAN-13, UPC-A). Считается по одному правилу:
 * цифры справа налево умножаются попеременно на 3 и 1, сумма дополняется до десятка.
 */
export function контрольнаяЦифра(цифры) {
  const с = String(цифры).replace(/\D/g, '');
  let сумма = 0;
  for (let и = 0; и < с.length; и++) {
    // Отсчёт справа: самая правая цифра данных всегда умножается на три.
    const вес = и % 2 === 0 ? 3 : 1;
    сумма += вес * Number(с[с.length - 1 - и]);
  }
  return (10 - (сумма % 10)) % 10;
}

const ДЛИНА = { EAN13: 13, EAN8: 8, UPC: 12 };

/** Знаки, которые понимает CODE39. Остальные он не умеет вовсе. */
const ЗНАКИ39 = new Set('0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ-. $/+%'.split(''));

/**
 * Разбор ввода. Возвращает {годно, значение, беда, подсказка, добавленаЦифра}.
 *   значение -- то, что надо отдать библиотеке (может отличаться от введённого);
 *   беда -- ключ ошибки для перевода на язык страницы, с полями;
 *   подсказка -- необязательное замечание, когда всё годно, но есть о чём сказать.
 */
export function проверить(формат, ввод) {
  const текст = String(ввод ?? '');
  if (!текст.trim()) return { годно: false, пусто: true };

  if (формат === 'EAN13' || формат === 'EAN8' || формат === 'UPC') {
    const надо = ДЛИНА[формат];
    const цифры = текст.replace(/\s/g, '');
    if (!/^\d+$/.test(цифры)) {
      const чужой = [...цифры].find((з) => !/\d/.test(з));
      return { годно: false, беда: { вид: 'толькоЦифры', знак: чужой } };
    }
    // На одну цифру короче -- значит человек ввёл данные без контрольной. Досчитаем сами
    // и скажем об этом: молча дописывать цифру нельзя, её потом печатать на упаковке.
    if (цифры.length === надо - 1) {
      const ц = контрольнаяЦифра(цифры);
      return { годно: true, значение: цифры + ц, добавленаЦифра: ц };
    }
    if (цифры.length !== надо) {
      return { годно: false, беда: { вид: 'длина', надо, есть: цифры.length } };
    }
    const должна = контрольнаяЦифра(цифры.slice(0, надо - 1));
    const стоит = Number(цифры[надо - 1]);
    if (должна !== стоит) {
      return { годно: false, беда: { вид: 'контроль', должна, стоит } };
    }
    return { годно: true, значение: цифры };
  }

  if (формат === 'CODE39') {
    const верх = текст.toUpperCase();
    const чужой = [...верх].find((з) => !ЗНАКИ39.has(з));
    if (чужой) return { годно: false, беда: { вид: 'знак39', знак: чужой } };
    return {
      годно: true,
      значение: верх,
      // Предупреждаем заранее: код будет годным, но напечатается не тем, что ввели.
      подсказка: верх !== текст ? { вид: 'заглавные' } : null,
    };
  }

  // CODE128 и родственники: только таблица ASCII. Кириллица сюда не помещается.
  const чужой = [...текст].find((з) => з.codePointAt(0) > 127);
  if (чужой) return { годно: false, беда: { вид: 'неASCII', знак: чужой } };
  return { годно: true, значение: текст };
}
