/**
 * ТЕКСТОВЫЙ PDF ИЗ ПРОЧИТАННОГО.
 *
 * Зачем свой сборщик. Раньше PDF отдавал Tesseract: снимок как картинка, а поверх него
 * невидимый слой букв. Во-первых, с переходом на официальный движок до Tesseract дело
 * больше не доходит, и значок PDF просто молчал. Во-вторых, человеку нужен не снимок в
 * оболочке PDF, а документ с текстом -- такой, где буквы выделяются, ищутся и копируются,
 * а файл весит килобайты, а не мегабайты фотографии.
 *
 * Поэтому здесь собирается обычный текстовый PDF. Никакой картинки внутри нет.
 *
 * ПОЧЕМУ НЕ ВСТРОЕННЫЕ ШРИФТЫ PDF. В PDF есть четырнадцать шрифтов, которые не надо никуда
 * класть (Helvetica и прочие), но они знают только западную кодировку: кириллица в них
 * превращается в мусор, а весь смысл страницы -- читать русские и украинские этикетки.
 * Поэтому шрифт мы кладём в файл сами, как CID-шрифт с двухбайтовыми номерами букв
 * (Identity-H). Ради веса в public/pdf/text.ttf лежит не весь Noto Sans, а подмножество:
 * латиница, кириллица, греческий и знаки препинания -- 82 КБ вместо 570 КБ.
 *
 * ПОИСК ПО ФАЙЛУ. Двухбайтовые номера -- это номера глифов внутри шрифта, а не буквы. Чтобы
 * Ctrl+F и копирование возвращали настоящие буквы, в файл кладётся таблица ToUnicode:
 * номер глифа -> буква. Без неё текст виден, но не находится и копируется кашей.
 */

const ПУТЬ_ШРИФТА = '/pdf/text.ttf';

// Лист A4 и поля в пунктах PDF (1 пункт = 1/72 дюйма). Поля 2 см.
const ЛИСТ = { ш: 595.28, в: 841.89, поле: 56.7 };
const КЕГЛЬ = 11;
const МЕЖСТРОЧНЫЙ = 15.5;
const МЕЖАБЗАЦНЫЙ = 7;

/* ---- Чтение шрифта ---------------------------------------------------------------------- */

/**
 * Разбор TTF: нам нужны всего четыре вещи -- номер глифа для буквы, его ширина, размер
 * клетки шрифта и габариты. Всё остальное в файле PDF просто передаётся как есть.
 */
function разобратьШрифт(байты) {
  const в = new DataView(байты.buffer, байты.byteOffset, байты.byteLength);
  const таблицы = new Map();
  const сколько = в.getUint16(4);
  for (let и = 0; и < сколько; и++) {
    const п = 12 + и * 16;
    const имя = String.fromCharCode(байты[п], байты[п + 1], байты[п + 2], байты[п + 3]);
    таблицы.set(имя, { нач: в.getUint32(п + 8), длина: в.getUint32(п + 12) });
  }
  const надо = (имя) => {
    const т = таблицы.get(имя);
    if (!т) throw new Error('в шрифте нет таблицы ' + имя);
    return т.нач;
  };

  const head = надо('head');
  const единиц = в.getUint16(head + 18);
  const габарит = [в.getInt16(head + 36), в.getInt16(head + 38), в.getInt16(head + 40), в.getInt16(head + 42)];

  const hhea = надо('hhea');
  const верх = в.getInt16(hhea + 4);
  const низ = в.getInt16(hhea + 6);
  const метрик = в.getUint16(hhea + 34);

  const hmtx = надо('hmtx');
  const всегоГлифов = в.getUint16(надо('maxp') + 4);
  const ширины = new Uint16Array(всегоГлифов);
  let последняя = 0;
  for (let г = 0; г < всегоГлифов; г++) {
    if (г < метрик) последняя = в.getUint16(hmtx + г * 4);
    ширины[г] = последняя;
  }

  // Высота заглавной буквы нужна описанию шрифта. В OS/2 она есть начиная со второй версии;
  // если версия старше -- берём разумную долю от верха, читалки этим полем почти не пользуются.
  let высотаЗаглавной = Math.round(верх * 0.7);
  const os2 = таблицы.get('OS/2');
  if (os2 && в.getUint16(os2.нач) >= 2 && os2.длина >= 90) высотаЗаглавной = в.getInt16(os2.нач + 88);

  return { глифы: читатьCmap(в, надо('cmap')), ширины, единиц, верх, низ, габарит, высотаЗаглавной };
}

/**
 * Таблица буква -> номер глифа. Формат 4 -- в каждом шрифте, формат 12 -- когда есть буквы
 * выше 0xFFFF. Берём лучшую из имеющихся; в нашем подмножестве это формат 4.
 */
function читатьCmap(в, нач) {
  const записей = в.getUint16(нач + 2);
  let лучшая = 0, лучшийВес = -1;
  for (let и = 0; и < записей; и++) {
    const п = нач + 4 + и * 8;
    const площадка = в.getUint16(п), кодировка = в.getUint16(п + 2);
    const смещение = нач + в.getUint32(п + 4);
    const формат = в.getUint16(смещение);
    if (формат !== 4 && формат !== 12) continue;
    // Чем больше вес, тем полнее таблица: (3,10) полнее (3,1), а та полнее прочих.
    const вес = (площадка === 3 && кодировка === 10) ? 3 : (площадка === 3 && кодировка === 1) ? 2 : 1;
    if (вес > лучшийВес) { лучшийВес = вес; лучшая = смещение; }
  }
  if (!лучшая) throw new Error('в шрифте нет понятной таблицы букв');

  const карта = new Map();
  if (в.getUint16(лучшая) === 12) {
    const групп = в.getUint32(лучшая + 12);
    for (let и = 0; и < групп; и++) {
      const п = лучшая + 16 + и * 12;
      const от = в.getUint32(п), до = в.getUint32(п + 4), первый = в.getUint32(п + 8);
      for (let к = от; к <= до; к++) карта.set(к, первый + (к - от));
    }
    return карта;
  }

  const сегментов = в.getUint16(лучшая + 6) / 2;
  const концы = лучшая + 14;
  const начала = концы + сегментов * 2 + 2;
  const дельты = начала + сегментов * 2;
  const сдвиги = дельты + сегментов * 2;
  for (let с = 0; с < сегментов; с++) {
    const до = в.getUint16(концы + с * 2);
    const от = в.getUint16(начала + с * 2);
    if (от > до || от === 0xFFFF) continue;
    const дельта = в.getInt16(дельты + с * 2);
    const сдвиг = в.getUint16(сдвиги + с * 2);
    for (let к = от; к <= до; к++) {
      let г;
      if (сдвиг === 0) г = (к + дельта) & 0xFFFF;
      else {
        const где = сдвиги + с * 2 + сдвиг + (к - от) * 2;
        if (где + 1 >= в.byteLength) continue;
        г = в.getUint16(где);
        if (г !== 0) г = (г + дельта) & 0xFFFF;
      }
      if (г) карта.set(к, г);
    }
  }
  return карта;
}

let шрифтГотов = null;

/** Шрифт едет один раз за посещение: второй PDF собирается уже без ожидания. */
function взятьШрифт() {
  if (!шрифтГотов) {
    шрифтГотов = fetch(ПУТЬ_ШРИФТА)
      .then((о) => {
        if (!о.ok) throw new Error('шрифт не отдался: ' + о.status);
        return о.arrayBuffer();
      })
      .then((б) => {
        const байты = new Uint8Array(б);
        return { байты, ...разобратьШрифт(байты) };
      })
      .catch((е) => { шрифтГотов = null; throw е; });
  }
  return шрифтГотов;
}

/* ---- Раскладка текста по листам --------------------------------------------------------- */

/** Ширина строки в пунктах при выбранном кегле. */
function ширинаСтроки(строка, шрифт, кегль) {
  let сумма = 0;
  for (const буква of строка) {
    const г = шрифт.глифы.get(буква.codePointAt(0));
    сумма += шрифт.ширины[г || 0] || 0;
  }
  return сумма * кегль / шрифт.единиц;
}

/**
 * Перенос по словам. Слово шире листа (длинная ссылка, склеенный штрихкод) рвём по буквам --
 * иначе оно ушло бы за край и пропало из виду.
 */
function разложить(текст, шрифт, кегль, предел) {
  const готовые = [];
  let текущая = '';
  const положить = () => { if (текущая) { готовые.push(текущая); текущая = ''; } };

  for (const слово of текст.split(/\s+/).filter(Boolean)) {
    const проба = текущая ? текущая + ' ' + слово : слово;
    if (ширинаСтроки(проба, шрифт, кегль) <= предел) { текущая = проба; continue; }
    положить();
    if (ширинаСтроки(слово, шрифт, кегль) <= предел) { текущая = слово; continue; }
    let кусок = '';
    for (const буква of слово) {
      if (кусок && ширинаСтроки(кусок + буква, шрифт, кегль) > предел) { готовые.push(кусок); кусок = ''; }
      кусок += буква;
    }
    текущая = кусок;
  }
  положить();
  return готовые;
}

/* ---- Сборка файла ----------------------------------------------------------------------- */

const вБайты = (строка) => Uint8Array.from(строка, (з) => з.charCodeAt(0) & 0xFF);

/** В строках PDF скобки и обратная косая -- служебные знаки, их экранируют. */
const экранировать = (строка) => String(строка).replace(/([\\()])/g, '\\$1');

/**
 * Сжатие потоков. CompressionStream('deflate') даёт ровно тот формат, который PDF называет
 * FlateDecode. Со шрифтом это 82 КБ против 45 КБ в готовом файле. Если браузер такого не
 * умеет -- кладём как есть: файл потяжелее, но рабочий.
 */
async function сжать(байты) {
  if (typeof CompressionStream !== 'function') return null;
  try {
    const поток = new Blob([байты]).stream().pipeThrough(new CompressionStream('deflate'));
    return new Uint8Array(await new Response(поток).arrayBuffer());
  } catch (е) {
    return null;
  }
}

/** Номер глифа в шестнадцатеричном виде -- так строки пишутся в содержимом листа. */
const вШестнадцать = (ч, знаков) => ч.toString(16).toUpperCase().padStart(знаков, '0');

/**
 * Таблица «номер глифа -> буква». Без неё поиск по файлу и копирование не работают: читалка
 * видит номера и не знает, какие это буквы.
 */
function собратьToUnicode(пары) {
  const строки = [];
  const все = [...пары.entries()].sort((а, б) => а[0] - б[0]);
  for (let и = 0; и < все.length; и += 100) {
    const кусок = все.slice(и, и + 100);
    строки.push(кусок.length + ' beginbfchar');
    for (const [глиф, код] of кусок) {
      // Буквы выше 0xFFFF пишутся суррогатной парой -- так требует UTF-16BE.
      const цель = код > 0xFFFF
        ? вШестнадцать(0xD800 + ((код - 0x10000) >> 10), 4) + вШестнадцать(0xDC00 + ((код - 0x10000) & 0x3FF), 4)
        : вШестнадцать(код, 4);
      строки.push('<' + вШестнадцать(глиф, 4) + '> <' + цель + '>');
    }
    строки.push('endbfchar');
  }
  return [
    '/CIDInit /ProcSet findresource begin',
    '12 dict begin', 'begincmap',
    '/CIDSystemInfo <</Registry (Adobe) /Ordering (UCS) /Supplement 0>> def',
    '/CMapName /Adobe-Identity-UCS def', '/CMapType 2 def',
    '1 begincodespacerange', '<0000> <FFFF>', 'endcodespacerange',
    ...строки,
    'endcmap', 'CMapName currentdict /CMap defineresource pop', 'end', 'end',
  ].join('\n');
}

/** Массив ширин: читалка берёт их отсюда, а не из вложенного шрифта. */
function собратьШирины(глифы, шрифт) {
  const все = [...глифы].sort((а, б) => а - б);
  const куски = [];
  let и = 0;
  while (и < все.length) {
    let к = и;
    while (к + 1 < все.length && все[к + 1] === все[к] + 1) к++;
    const ширины = все.slice(и, к + 1)
      .map((г) => Math.round(шрифт.ширины[г] * 1000 / шрифт.единиц));
    куски.push(все[и] + ' [' + ширины.join(' ') + ']');
    и = к + 1;
  }
  return '[' + куски.join(' ') + ']';
}

/**
 * Собрать PDF из абзацев прочитанного.
 *
 * @param {Array<{строки: Array<{текст: string}>}>} абзацы -- как их отдаёт разбор снимка.
 * @param {{заголовок?: string}} настройки
 * @returns {Promise<Uint8Array>} готовый файл.
 */
export async function собратьPdf(абзацы, { заголовок = 'Text' } = {}) {
  const шрифт = await взятьШрифт();
  const предел = ЛИСТ.ш - ЛИСТ.поле * 2;

  // 1. Раскладываем текст по строкам листа. Пустая строка между абзацами сохраняет деление,
  //    которое человек видел на снимке.
  const строкиЛиста = [];
  абзацы.forEach((абзац, номер) => {
    if (номер) строкиЛиста.push(null);       // null -- отступ между абзацами
    for (const строка of абзац.строки) {
      const текст = (строка.текст || '').trim();
      if (!текст) continue;
      for (const часть of разложить(текст, шрифт, КЕГЛЬ, предел)) строкиЛиста.push(часть);
    }
  });

  // 2. Режем на листы.
  const листы = [[]];
  let у = ЛИСТ.в - ЛИСТ.поле - КЕГЛЬ;
  for (const строка of строкиЛиста) {
    const шаг = строка === null ? МЕЖАБЗАЦНЫЙ : МЕЖСТРОЧНЫЙ;
    if (у - шаг < ЛИСТ.поле) { листы.push([]); у = ЛИСТ.в - ЛИСТ.поле - КЕГЛЬ; }
    if (строка !== null) листы[листы.length - 1].push({ текст: строка, у });
    у -= шаг;
  }
  if (!листы[листы.length - 1].length && листы.length > 1) листы.pop();

  // 3. Содержимое листов. Заодно копим, какие глифы вообще понадобились: ширины и таблицу
  //    поиска кладём только для них, а не для всей тысячи из шрифта.
  const нужныеГлифы = new Set();
  const обратно = new Map();
  const вГлифы = (строка) => {
    let вышло = '';
    for (const буква of строка) {
      const код = буква.codePointAt(0);
      const глиф = шрифт.глифы.get(код) || шрифт.глифы.get(63) || 0;   // нет буквы -- «?»
      нужныеГлифы.add(глиф);
      обратно.set(глиф, шрифт.глифы.has(код) ? код : 63);
      вышло += вШестнадцать(глиф, 4);
    }
    return вышло;
  };

  const содержимое = листы.map((лист) => {
    const куски = ['BT', '/F1 ' + КЕГЛЬ + ' Tf'];
    for (const { текст, у: верх } of лист) {
      куски.push('1 0 0 1 ' + ЛИСТ.поле.toFixed(2) + ' ' + верх.toFixed(2) + ' Tm');
      куски.push('<' + вГлифы(текст) + '> Tj');
    }
    куски.push('ET');
    return куски.join('\n');
  });

  // 4. Раскладываем объекты. Номера идут подряд: 1 -- корень, 2 -- список листов,
  //    дальше сами листы, их содержимое и четыре объекта шрифта.
  const оЛист = (и) => 3 + и;
  const оСодержимое = (и) => 3 + листы.length + и;
  const оШрифт = 3 + листы.length * 2;
  const оПотомок = оШрифт + 1;
  const оОписание = оШрифт + 2;
  const оФайлШрифта = оШрифт + 3;
  const оToUnicode = оШрифт + 4;
  const оСведения = оШрифт + 5;
  const всего = оСведения;

  const объекты = new Array(всего + 1).fill(null);
  const положить = (номер, тело) => { объекты[номер] = тело; };

  положить(1, вБайты('<</Type /Catalog /Pages 2 0 R>>'));
  положить(2, вБайты('<</Type /Pages /Kids [' + листы.map((_, и) => oref(оЛист(и))).join(' ')
    + '] /Count ' + листы.length + '>>'));
  листы.forEach((_, и) => положить(оЛист(и), вБайты(
    '<</Type /Page /Parent 2 0 R'
    + ' /MediaBox [0 0 ' + ЛИСТ.ш + ' ' + ЛИСТ.в + ']'
    + ' /Resources <</Font <</F1 ' + oref(оШрифт) + '>>>>'
    + ' /Contents ' + oref(оСодержимое(и)) + '>>')));

  for (let и = 0; и < листы.length; и++) {
    положить(оСодержимое(и), await поток(вБайты(содержимое[и])));
  }

  положить(оШрифт, вБайты('<</Type /Font /Subtype /Type0 /BaseFont /NotoSans'
    + ' /Encoding /Identity-H /DescendantFonts [' + oref(оПотомок) + ']'
    + ' /ToUnicode ' + oref(оToUnicode) + '>>'));
  положить(оПотомок, вБайты('<</Type /Font /Subtype /CIDFontType2 /BaseFont /NotoSans'
    + ' /CIDSystemInfo <</Registry (Adobe) /Ordering (Identity) /Supplement 0>>'
    + ' /FontDescriptor ' + oref(оОписание)
    + ' /DW ' + Math.round(шрифт.ширины[0] * 1000 / шрифт.единиц)
    + ' /W ' + собратьШирины(нужныеГлифы, шрифт)
    + ' /CIDToGIDMap /Identity>>'));
  const вТысячных = (ч) => Math.round(ч * 1000 / шрифт.единиц);
  положить(оОписание, вБайты('<</Type /FontDescriptor /FontName /NotoSans'
    + ' /Flags 32'                                   // 32 -- обычный наборный шрифт
    + ' /FontBBox [' + шрифт.габарит.map(вТысячных).join(' ') + ']'
    + ' /ItalicAngle 0'
    + ' /Ascent ' + вТысячных(шрифт.верх)
    + ' /Descent ' + вТысячных(шрифт.низ)
    + ' /CapHeight ' + вТысячных(шрифт.высотаЗаглавной)
    + ' /StemV 80'
    + ' /FontFile2 ' + oref(оФайлШрифта) + '>>'));
  положить(оФайлШрифта, await поток(шрифт.байты, { Length1: шрифт.байты.length }));
  положить(оToUnicode, await поток(вБайты(собратьToUnicode(обратно))));
  положить(оСведения, вБайты('<</Title (' + экранировать(заголовок) + ')'
    + ' /Producer (Opitro) /CreationDate (' + датаPdf(new Date()) + ')>>'));

  // 5. Склейка с таблицей смещений: в ней указано, на каком байте начинается каждый объект.
  const части = [];
  let длина = 0;
  const добавить = (байты) => { части.push(байты); длина += байты.length; };
  добавить(вБайты('%PDF-1.7\n%\xE2\xE3\xCF\xD3\n'));

  const места = new Array(всего + 1).fill(0);
  for (let н = 1; н <= всего; н++) {
    места[н] = длина;
    добавить(вБайты(н + ' 0 obj\n'));
    добавить(объекты[н]);
    добавить(вБайты('\nendobj\n'));
  }

  const таблица = длина;
  let ссылки = 'xref\n0 ' + (всего + 1) + '\n0000000000 65535 f \n';
  for (let н = 1; н <= всего; н++) ссылки += String(места[н]).padStart(10, '0') + ' 00000 n \n';
  ссылки += 'trailer\n<</Size ' + (всего + 1) + ' /Root 1 0 R /Info ' + oref(оСведения) + '>>\n'
    + 'startxref\n' + таблица + '\n%%EOF\n';
  добавить(вБайты(ссылки));

  const файл = new Uint8Array(длина);
  let куда = 0;
  for (const часть of части) { файл.set(часть, куда); куда += часть.length; }
  return файл;
}

const oref = (номер) => номер + ' 0 R';

/** Поток: словарь с длиной, потом сами байты. Сжимаем, если браузер умеет. */
async function поток(байты, ещё = {}) {
  const сжатые = await сжать(байты);
  const тело = сжатые && сжатые.length < байты.length ? сжатые : байты;
  const свойства = Object.entries(ещё).map(([к, з]) => ' /' + к + ' ' + з).join('');
  const шапка = вБайты('<</Length ' + тело.length + свойства
    + (тело === сжатые ? ' /Filter /FlateDecode' : '') + '>>\nstream\n');
  const хвост = вБайты('\nendstream');
  const всё = new Uint8Array(шапка.length + тело.length + хвост.length);
  всё.set(шапка, 0);
  всё.set(тело, шапка.length);
  всё.set(хвост, шапка.length + тело.length);
  return всё;
}

/** Дата в том виде, в каком её ждут читалки PDF. */
function датаPdf(д) {
  const дв = (ч) => String(ч).padStart(2, '0');
  return 'D:' + д.getFullYear() + дв(д.getMonth() + 1) + дв(д.getDate())
    + дв(д.getHours()) + дв(д.getMinutes()) + дв(д.getSeconds());
}

/**
 * Какая доля букв текста шрифту незнакома. Нужна, чтобы не отдавать человеку файл из одних
 * вопросительных знаков: арабского, иврита и иероглифов в подмножестве нет, а Tesseract их
 * читать умеет.
 */
export async function долянеЗнакомых(текст) {
  const шрифт = await взятьШрифт();
  const буквы = String(текст).match(/\p{L}/gu) || [];
  if (!буквы.length) return 0;
  const мимо = буквы.filter((б) => !шрифт.глифы.has(б.codePointAt(0))).length;
  return мимо / буквы.length;
}
