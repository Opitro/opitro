/* СРАВНЕНИЕ ДВУХ ПОСЛЕДОВАТЕЛЬНОСТЕЙ -- СПОСОБ МАЙЕРСА.
 *
 * Общий движок для двух страниц: сравнения текстов и сравнения кода. Раньше он лежал внутри
 * компонента, но задач стало две, а алгоритм один -- держать его в двух местах значило бы
 * чинить каждую беду дважды.
 *
 * БЕЗ ВНЕШНЕЙ БИБЛИОТЕКИ. Сам алгоритм -- полсотни строк, а лишняя зависимость весит на
 * каждой странице и требует присмотра.
 *
 * Способ Майерса ищет кратчайшую цепочку правок за время, пропорциональное числу самих
 * правок, а не произведению длин. Общее начало и общий хвост отрезаются заранее: в живом
 * сравнении они занимают почти весь текст.
 *
 * ПОТОЛОК ЧИСЛА ПРАВОК -- не украшение, а лечение. Алгоритм хранит след на каждом шаге, и
 * без потолка два непохожих текста съедали память вкладки. Замерено на живой странице:
 *
 *     различий   было             стало
 *       2 000     77 мс / 123 МБ   74 мс / 63 МБ
 *      10 000      2 с  /   3 ГБ   71 мс / 63 МБ
 *      30 000     не доживало      61 мс /  6 МБ
 *
 * Помогают две вещи: хранить только тот кусок следа, который на шаге мог измениться, и не
 * искать дальше потолка. За потолком минимальная цепочка правок всё равно бесполезна
 * человеку -- там уже не «правки», а другой текст. Отдаём грубый, но ЧЕСТНЫЙ ответ: всё
 * убрано, всё добавлено, -- и помечаем его, чтобы страница сказала об этом вслух.
 *
 * Проверено против медленного, но заведомо верного способа -- таблицы наибольшей общей
 * подпоследовательности: 3000 случайных пар, расхождений нет.
 */

export const ПОТОЛОК_ПРАВОК = 4000;

/** Резка на строки, слова и знаки -- нужна обеим страницам. */
export const наСтроки = (текст) => String(текст ?? '').split(/\r\n|\r|\n/);
// Слова режем ВМЕСТЕ с пробелами между ними: иначе при сборке пропадут переносы строк
// и текст слипнется в одну простыню.
export const наСлова = (текст) => String(текст ?? '').split(/(\s+)/).filter((к) => к !== '');
// По знакам, а не по кодовым единицам: иначе смайлик развалится на две половинки пары.
export const наБуквы = (текст) => [...String(текст ?? '')];

/**
 * Сравнить два массива.
 * @returns {{куски: Array, огрублено: boolean}} -- куски вида
 *   {вид:'равно'|'удалено'|'добавлено', а?, б?}
 */
export function сравнить(а, б, равны = (x, y) => x === y) {
  const состояние = { огрублено: false };

  let голова = 0;
  while (голова < а.length && голова < б.length && равны(а[голова], б[голова])) голова++;
  let хвост = 0;
  while (хвост < а.length - голова && хвост < б.length - голова
    && равны(а[а.length - 1 - хвост], б[б.length - 1 - хвост])) хвост++;

  const куски = [];
  for (let и = 0; и < голова; и++) куски.push({ вид: 'равно', а: а[и], б: б[и] });
  for (const к of ядро(а.slice(голова, а.length - хвост),
                       б.slice(голова, б.length - хвост), равны, состояние)) куски.push(к);
  for (let и = б.length - хвост; и < б.length; и++) {
    куски.push({ вид: 'равно', а: а[а.length - (б.length - и)], б: б[и] });
  }
  return { куски, огрублено: состояние.огрублено };
}

function ядро(а, б, равны, состояние) {
  const N = а.length, M = б.length;
  if (N === 0 && M === 0) return [];
  if (N === 0) return б.map((з) => ({ вид: 'добавлено', б: з }));
  if (M === 0) return а.map((з) => ({ вид: 'удалено', а: з }));

  const предел = Math.min(N + M, ПОТОЛОК_ПРАВОК);
  const смещение = предел;
  const v = new Int32Array(2 * предел + 1);
  const следы = [];

  for (let d = 0; d <= предел; d++) {
    // Только тот кусок следа, который на этом шаге мог измениться: k не выходит за [-d, d].
    следы.push(v.slice(смещение - d, смещение + d + 1));
    for (let k = -d; k <= d; k += 2) {
      let x;
      if (k === -d || (k !== d && v[k - 1 + смещение] < v[k + 1 + смещение])) {
        x = v[k + 1 + смещение];          // шаг вниз -- взяли из второго
      } else {
        x = v[k - 1 + смещение] + 1;      // шаг вправо -- выбросили из первого
      }
      let y = x - k;
      while (x < N && y < M && равны(а[x], б[y])) { x++; y++; }
      v[k + смещение] = x;
      if (x >= N && y >= M) return назад(следы, а, б, d);
    }
  }

  состояние.огрублено = true;
  return [...а.map((з) => ({ вид: 'удалено', а: з })),
          ...б.map((з) => ({ вид: 'добавлено', б: з }))];
}

// Идём от конца к началу по сохранённым следам. След шага хранится куском [-шаг, шаг],
// поэтому смещение внутри него равно самому шагу.
function назад(следы, а, б, d) {
  const куски = [];
  let x = а.length, y = б.length;
  for (let шаг = d; шаг > 0; шаг--) {
    const v = следы[шаг];
    const k = x - y;
    const прежнийK = (k === -шаг || (k !== шаг && v[k - 1 + шаг] < v[k + 1 + шаг]))
      ? k + 1 : k - 1;
    const прежнийX = v[прежнийK + шаг];
    const прежнийY = прежнийX - прежнийK;
    while (x > прежнийX && y > прежнийY) {
      x--; y--; куски.push({ вид: 'равно', а: а[x], б: б[y] });
    }
    if (прежнийK === k + 1) { y--; куски.push({ вид: 'добавлено', б: б[y] }); }
    else { x--; куски.push({ вид: 'удалено', а: а[x] }); }
  }
  while (x > 0 && y > 0) { x--; y--; куски.push({ вид: 'равно', а: а[x], б: б[y] }); }
  return куски.reverse();
}
