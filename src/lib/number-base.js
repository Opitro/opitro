/* ПЕРЕВОД ЧИСЕЛ МЕЖДУ СИСТЕМАМИ СЧИСЛЕНИЯ.
 *
 * ОТСТУПЛЕНИЕ ОТ ЗАДАНИЯ, И ОНО ГЛАВНОЕ. В задании предложены parseInt(строка, основание)
 * и Number.prototype.toString(основание). Так делать нельзя: обычное число в JavaScript
 * точно хранит целые только до 2^53. А шестнадцатеричные числа нужны ровно там, где эта
 * граница перейдена: адреса памяти, битовые маски, куски хэшей -- это 64 бита.
 *
 *   parseInt('FFFFFFFFFFFFFFFF', 16).toString(16)  ->  '10000000000000000'
 *
 * Вместо шестнадцати букв F выходит единица с нулями: число округлилось при чтении.
 * Поэтому считаем на BigInt -- у него точность не кончается. Проверено сверкой с python3,
 * где целые тоже без предела.
 *
 * Дробей нет намеренно. Дробная часть в двоичном виде почти всегда бесконечна (0.1 в
 * десятичной -- это 0.000110011... в двоичной), и любой ответ пришлось бы обрезать, то есть
 * соврать. Точка в поля просто не пропускается, а не отбрасывается молча.
 */

/** Основания, между которыми переводим. Порядок -- как на странице. */
export const ОСНОВАНИЯ = [2, 10, 16, 8];

const ЗНАКИ = '0123456789abcdefghijklmnopqrstuvwxyz';

/** Какие знаки годны для основания. Регистр не важен: 2a и 2A -- одно и то же. */
export function годные(основание) {
  return ЗНАКИ.slice(0, основание);
}

/**
 * Убрать из строки всё, чего в этой системе быть не может.
 * Минус оставляем, но только первым знаком: отрицательные адреса и маски встречаются.
 */
export function процедить(текст, основание) {
  const с = String(текст ?? '');
  const годен = new Set(годные(основание).split(''));
  let итог = '';
  for (let и = 0; и < с.length; и++) {
    const з = с[и];
    if (з === '-' && итог === '') { итог += '-'; continue; }
    if (годен.has(з.toLowerCase())) итог += з;
  }
  return итог;
}

/** Строка -> BigInt. Возвращает null, если числа в строке нет. */
export function вЧисло(текст, основание) {
  const с = процедить(текст, основание);
  const минус = с.startsWith('-');
  const цифры = минус ? с.slice(1) : с;
  if (!цифры) return null;

  const б = BigInt(основание);
  let итог = 0n;
  for (const з of цифры.toLowerCase()) {
    итог = итог * б + BigInt(ЗНАКИ.indexOf(з));
  }
  return минус ? -итог : итог;
}

/** BigInt -> строка. Шестнадцатеричные буквы заглавные: так их пишут в коде и в отладчиках. */
export function изЧисла(значение, основание) {
  if (значение === null || значение === undefined) return '';
  const с = значение.toString(основание);
  return основание > 10 ? с.toUpperCase() : с;
}

/**
 * Перевести написанное в одном поле во все четыре.
 * Поле, в котором набирают, не трогаем -- иначе курсор прыгает и ведущие нули пропадают
 * прямо под пальцами.
 */
export function перевести(текст, основание) {
  const значение = вЧисло(текст, основание);
  const итог = {};
  for (const о of ОСНОВАНИЯ) итог[о] = значение === null ? '' : изЧисла(значение, о);
  return { значение, поля: итог };
}

/**
 * Сколько двоичных разрядов занимает число. Считаем по модулю: у -5 столько же значащих
 * битов, сколько у 5. Ноль занимает один разряд.
 */
export function разрядов(значение) {
  if (значение === null || значение === undefined) return 0;
  const м = значение < 0n ? -значение : значение;
  return м === 0n ? 1 : м.toString(2).length;
}

/**
 * В какой обычный размер число уже не влезает без знака: 8, 16, 32 или 64 бита.
 * Нужно тем, кто пишет маски и разбирает протоколы: 256 в байт уже не помещается.
 */
export function размер(значение) {
  if (значение === null || значение === undefined || значение < 0n) return null;
  const б = разрядов(значение);
  for (const р of [8, 16, 32, 64]) if (б <= р) return р;
  return null;
}
