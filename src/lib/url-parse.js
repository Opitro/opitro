// РАЗБОР ССЫЛКИ.
//
// Разбирает сам браузер -- класс URL, тот же самый, которым он ходит по ссылкам. Своего
// разбора здесь нет намеренно: правила устройства адресов полны исключений (двоеточия в пути,
// скобки у адресов IPv6, точки-сегменты, повторные косые), и самодельный разбор расходится с
// настоящим ровно на тех ссылках, ради которых человек и пришёл разбираться.
//
// НАША РАБОТА -- ПОКАЗАТЬ ТО, О ЧЁМ ОБЫЧНЫЕ ПАРСЕРЫ МОЛЧАТ:
//
//   1. ПОВТОРЯЮЩИЕСЯ ПАРАМЕТРЫ. В ?a=1&a=2 обычный get('a') вернёт только «1», и второе
//      значение пропадёт молча. Здесь показаны оба -- именно на этом ломаются разборы
//      ссылок из рекламных систем, где повторы обычное дело.
//   2. ПЛЮС В ЗАПРОСЕ -- ЭТО ПРОБЕЛ, А В ПУТИ -- ПЛЮС. Одна и та же закорючка значит разное
//      по разные стороны знака вопроса, и это ходовая причина «параметр приходит не тот».
//   3. ИМЯ НА КИРИЛЛИЦЕ ПРЕВРАЩАЕТСЯ В punycode. Браузер отправит на сервер не «пример.рф»,
//      а «xn--e1afmkfd.xn--p1ai», и в журналах будет второе. Показываем оба.
//   4. ЛОГИН И ПАРОЛЬ В ССЫЛКЕ. Их можно вписать прямо в адрес, и они утекают в закладки, в
//      историю и в чужие журналы. Если они есть -- об этом надо сказать прямо.
//   5. ЯКОРЬ НА СЕРВЕР НЕ УХОДИТ. Всё после решётки остаётся в браузере.
//   6. ПУТЬ С КИРИЛЛИЦЕЙ БРАУЗЕР ПОКАЗЫВАЕТ В ПРОЦЕНТАХ. «/путь» превращается в
//      «/%D0%BF%D1%83%D1%82%D1%8C» -- и это правда, именно так он уйдёт на сервер. Но человек
//      набирал буквы, и узнать в процентах свою ссылку невозможно. Показываем обе записи.

/** Порядок частей постоянный: строки на странице не должны прыгать. */
const ЧАСТИ = [
  ['protocol', 'схема'], ['username', 'логин'], ['password', 'пароль'],
  ['hostname', 'хост'], ['port', 'порт'], ['pathname', 'путь'],
  ['search', 'запрос'], ['hash', 'якорь'], ['origin', 'источник'],
];

/**
 * @param {string} строка
 * @returns {{годна, адрес, части, параметры, заметки, беда, дописали}}
 */
export function разобрать(строка) {
  const с = String(строка ?? '').trim();
  if (!с) return { годен: false, беда: 'ПУСТО' };

  let адрес = null;
  let дописали = false;
  try { адрес = new URL(с); }
  catch (е) {
    // Ссылка без схемы -- обычное дело: её копируют из адресной строки уже без «https://».
    // Дописываем, но ГОВОРИМ об этом: молча менять разбираемое нельзя.
    // Догадываемся ТОЛЬКО когда догадка разумна: строка начинается с чего-то похожего на
    // имя узла. Иначе «!!!» разобралось бы как хост -- разбор URL в браузере на удивление
    // терпелив, и «https://!!!» он принимает.
    const похожеНаУзел = /^(localhost|\[[0-9a-f:]+\]|[a-z0-9\u00a1-\uffff]([a-z0-9\u00a1-\uffff-]*[a-z0-9\u00a1-\uffff])?(\.[a-z0-9\u00a1-\uffff]([a-z0-9\u00a1-\uffff-]*[a-z0-9\u00a1-\uffff])?)+)(:\d+)?([/?#]|$)/i;
    if (!/^[a-z][a-z0-9+.-]*:/i.test(с) && похожеНаУзел.test(с)) {
      try { адрес = new URL('https://' + с); дописали = true; }
      catch (е2) { адрес = null; }
    }
  }
  if (!адрес) return { годен: false, беда: 'НЕ_ССЫЛКА' };

  // Рядом с каждой частью -- её читаемый вид, если он отличается. Для хоста это имя до
  // перевода в punycode, для пути и запроса -- запись без процентов.
  const части = ЧАСТИ
    .map(([ключ, имя]) => {
      const значение = адрес[ключ] || '';
      let читаемое = '';
      if (ключ === 'hostname') читаемое = вЮникоде(значение);
      else читаемое = раскодировать(значение, ключ);
      return [имя, ключ, значение, читаемое === значение ? '' : читаемое];
    })
    .filter(([, ключ, значение]) => значение !== '' || ключ === 'pathname');

  // Параметры берём ПЕРЕЧИСЛЕНИЕМ, а не через get: get отдаёт только первое значение, и
  // повторы пропали бы молча.
  const параметры = [];
  for (const [имя, значение] of адрес.searchParams) параметры.push({ имя, значение });

  const счёт = new Map();
  for (const п of параметры) счёт.set(п.имя, (счёт.get(п.имя) || 0) + 1);
  for (const п of параметры) п.повтор = счёт.get(п.имя) > 1;

  const заметки = [];
  if (дописали) заметки.push('ДОПИСАЛИ_СХЕМУ');
  if (адрес.username || адрес.password) заметки.push('ЛОГИН_В_ССЫЛКЕ');
  if ([...счёт.values()].some((н) => н > 1)) заметки.push('ЕСТЬ_ПОВТОРЫ');
  if (адрес.hash) заметки.push('ЯКОРЬ_НЕ_УХОДИТ');
  // Имя на кириллице: браузер уже перевёл его в punycode, и в адресе стоит именно оно.
  if (/^xn--/i.test(адрес.hostname) || адрес.hostname.split('.').some((к) => /^xn--/i.test(к))) {
    заметки.push('PUNYCODE');
  }
  if (адрес.search.includes('+')) заметки.push('ПЛЮС_ЭТО_ПРОБЕЛ');
  // Закодированная косая внутри отрезка пути -- частая причина «сервер не находит страницу».
  if (/%2f/i.test(адрес.pathname)) заметки.push('КОСАЯ_В_ОТРЕЗКЕ');

  return {
    годен: true, адрес, части, параметры, заметки, дописали,
    хостВЮникоде: вЮникоде(адрес.hostname),
    беда: null,
  };
}

// Знаки, которые в каждой части несут СТРОЕНИЕ, а не содержание. Раскодировать их нельзя:
// «/a%2Fb/c» -- это ДВА отрезка пути, где во втором стоит косая; показать его как «/a/b/c»
// значит соврать про строение ссылки. То же с «&» внутри значения запроса.
const СТРОЕНИЕ = {
  pathname: ['2F', '5C', '3F', '23'],          // / \ ? #
  search: ['26', '3D', '3F', '23'],            // & = ? #
  hash: ['23'],                                // #
};

/**
 * Раскодировать проценты, не трогая те, что несут строение. Битую запись оставляем как
 * есть -- ломаться на ней незачем.
 */
function раскодировать(с, ключ) {
  if (!с || !с.includes('%')) return с;
  const беречь = СТРОЕНИЕ[ключ] || [];
  // Прячем бережёные последовательности за знаком, которого в ссылке быть не может.
  const спрятанные = [];
  const скрыто = с.replace(/%[0-9a-f]{2}/gi, (кусок) => {
    if (!беречь.includes(кусок.slice(1).toUpperCase())) return кусок;
    спрятанные.push(кусок);
    return `\u0001${спрятанные.length - 1}\u0001`;
  });
  let итог;
  try { итог = decodeURIComponent(скрыто); } catch (е) { return с; }
  return итог.replace(/\u0001(\d+)\u0001/g, (всё, н) => спрятанные[Number(н)]);
}

/** Обратный перевод из punycode -- чтобы показать рядом привычное имя. */
function вЮникоде(хост) {
  if (typeof URL !== 'function') return хост;
  try {
    // Штатного обратного перевода в браузере нет; берём то, что показывает сам браузер в
    // свойстве ссылки, если имя не переводилось.
    return хост.split('.').map(разкодировать).join('.');
  } catch (е) { return хост; }
}

/** Раскодировать одну часть punycode. Разбор короткий и целиком по описанию RFC 3492. */
function разкодировать(кусок) {
  if (!/^xn--/i.test(кусок)) return кусок;
  const тело = кусок.slice(4);
  const граница = тело.lastIndexOf('-');
  let вывод = граница > 0 ? [...тело.slice(0, граница)].map((з) => з.codePointAt(0)) : [];
  let место = граница > 0 ? граница + 1 : 0;
  let н = 128, смещение = 72, и = 0;
  const ЦИФРА = (з) => {
    const к = з.charCodeAt(0);
    if (к >= 48 && к <= 57) return к - 22;      // 0-9 -> 26..35
    if (к >= 97 && к <= 122) return к - 97;     // a-z -> 0..25
    if (к >= 65 && к <= 90) return к - 65;
    return -1;
  };
  while (место < тело.length) {
    const прежнее = и;
    for (let вес = 1, к = 36; ; к += 36) {
      if (место >= тело.length) return кусок;
      const цифра = ЦИФРА(тело[место++]);
      if (цифра < 0) return кусок;
      и += цифра * вес;
      const порог = к <= смещение ? 1 : (к >= смещение + 26 ? 26 : к - смещение);
      if (цифра < порог) break;
      вес *= 36 - порог;
    }
    const длина = вывод.length + 1;
    // Пересчёт смещения -- по описанию RFC 3492.
    let разница = прежнее === 0 ? Math.floor((и - прежнее) / 700) : Math.floor((и - прежнее) / 2);
    разница += Math.floor(разница / длина);
    let к = 0;
    while (разница > 455) { разница = Math.floor(разница / 35); к += 36; }
    смещение = к + Math.floor((36 * разница) / (разница + 38));
    н += Math.floor(и / длина);
    и %= длина;
    вывод.splice(и, 0, н);
    и++;
  }
  try { return String.fromCodePoint(...вывод); } catch (е) { return кусок; }
}
