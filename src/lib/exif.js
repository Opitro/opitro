// ЧТО ФОТОАППАРАТ ЗАПИСАЛ ВНУТРЬ СНИМКА (EXIF).
//
// Разбор целиком свой и целиком на устройстве: файл никуда не уходит, читается прямо из
// памяти браузера. Для этой страницы это не украшение, а главный довод -- она показывает
// человеку, что его снимок выдаёт место съёмки, и было бы странно при этом сам снимок
// куда-то отправлять.
//
// Читаем три вместилища, где EXIF действительно встречается:
//   JPEG -- отрезок APP1, начинающийся словом "Exif\0\0";
//   PNG  -- кусок eXIf (в новых снимках с телефонов бывает);
//   WebP -- кусок EXIF внутри RIFF.
// Внутри всех трёх лежит одно и то же -- маленький файл TIFF с описями (IFD).
//
// Чего НЕ умеем и о чём страница обязана сказать прямо: HEIC (снимки iPhone «по умолчанию»)
// браузер сам не разбирает, и притворяться нечем -- об этом пишем человеку, а не молчим.

/** Типы значений в описи TIFF и длина одной единицы в байтах. */
const ДЛИНА = { 1: 1, 2: 1, 3: 2, 4: 4, 5: 8, 6: 1, 7: 1, 8: 2, 9: 4, 10: 8, 11: 4, 12: 8 };

// Номера полей. Имена людям дают страницы -- здесь только то, что записано в снимке.
export const ПОЛЯ = {
  make: 0x010f, model: 0x0110, orientation: 0x0112, software: 0x0131, artist: 0x013b,
  datetime: 0x0132, copyright: 0x8298,
  exposure: 0x829a, fnumber: 0x829d, iso: 0x8827, isoNew: 0x8833,
  original: 0x9003, digitized: 0x9004, shutter: 0x9201, aperture: 0x9202,
  brightness: 0x9203, exposureBias: 0x9204, flash: 0x9209, focal: 0x920a,
  focal35: 0xa405, width: 0xa002, height: 0xa003, lens: 0xa434, lensMake: 0xa433,
  whiteBalance: 0xa403, exposureProgram: 0x8822, meteringMode: 0x9207,
  colorSpace: 0xa001, offsetTime: 0x9010, subject: 0x9286,
  exifIfd: 0x8769, gpsIfd: 0x8825,
};

const ПОЛЯ_GPS = {
  latRef: 1, lat: 2, lonRef: 3, lon: 4, altRef: 5, alt: 6, time: 7,
  speedRef: 12, speed: 13, imgDirRef: 16, imgDir: 17, date: 29,
};

/** Найти в JPEG отрезок APP1 с EXIF. Возвращает срез, начинающийся с заголовка TIFF. */
function изJpeg(байты) {
  let i = 2;                                   // FFD8 уже проверено
  while (i + 4 <= байты.length) {
    if (байты[i] !== 0xff) { i++; continue; }  // мусор между отрезками -- бывает
    const метка = байты[i + 1];
    if (метка === 0xd8 || метка === 0x01 || (метка >= 0xd0 && метка <= 0xd7)) { i += 2; continue; }
    if (метка === 0xda || метка === 0xd9) return null;   // пошли сами точки -- описей дальше нет
    const длина = (байты[i + 2] << 8) | байты[i + 3];
    if (метка === 0xe1 && длина > 8) {
      const голова = String.fromCharCode(...байты.slice(i + 4, i + 10));
      if (голова === 'Exif\0\0') return байты.slice(i + 10, i + 2 + длина);
    }
    i += 2 + длина;
  }
  return null;
}

/** PNG: ищем кусок eXIf. */
function изPng(байты) {
  let i = 8;                                   // подпись PNG
  while (i + 8 <= байты.length) {
    const длина = чтение32(байты, i, false);
    const имя = String.fromCharCode(байты[i + 4], байты[i + 5], байты[i + 6], байты[i + 7]);
    if (имя === 'eXIf') return байты.slice(i + 8, i + 8 + длина);
    if (имя === 'IEND') return null;
    i += 12 + длина;                           // длина + имя + данные + проверочная сумма
  }
  return null;
}

/** WebP: кусок EXIF внутри RIFF. */
function изWebp(байты) {
  let i = 12;                                  // RIFF + размер + WEBP
  while (i + 8 <= байты.length) {
    const имя = String.fromCharCode(байты[i], байты[i + 1], байты[i + 2], байты[i + 3]);
    const длина = чтение32(байты, i + 4, true);
    if (имя === 'EXIF') {
      let начало = i + 8;
      // Некоторые пишут перед заголовком TIFF ещё и слово "Exif\0\0" -- пропускаем.
      if (String.fromCharCode(...байты.slice(начало, начало + 6)) === 'Exif\0\0') начало += 6;
      return байты.slice(начало, i + 8 + длина);
    }
    i += 8 + длина + (длина % 2);              // куски выровнены по чётному байту
    if (имя === 'ANMF' && длина === 0) break;
  }
  return null;
}

function чтение16(б, i, мл) { return мл ? б[i] | (б[i + 1] << 8) : (б[i] << 8) | б[i + 1]; }
function чтение32(б, i, мл) {
  return мл
    ? (б[i] | (б[i + 1] << 8) | (б[i + 2] << 16) | (б[i + 3] << 24)) >>> 0
    : ((б[i] << 24) | (б[i + 1] << 16) | (б[i + 2] << 8) | б[i + 3]) >>> 0;
}

/** Прочитать одно значение описи. Возвращает число, строку или список чисел. */
function значение(тлф, вход) {
  const { байты, мл } = тлф;
  const { тип, счёт, место } = вход;
  const шаг = ДЛИНА[тип] || 1;
  if (место + счёт * шаг > байты.length) return null;
  if (тип === 2) {                              // строка
    let s = '';
    for (let k = 0; k < счёт; k++) {
      const c = байты[место + k];
      if (c === 0) break;
      s += String.fromCharCode(c);
    }
    return s.trim();
  }
  const список = [];
  for (let k = 0; k < счёт; k++) {
    const п = место + k * шаг;
    if (тип === 1 || тип === 6 || тип === 7) список.push(байты[п]);
    else if (тип === 3) список.push(чтение16(байты, п, мл));
    else if (тип === 8) { const ч = чтение16(байты, п, мл); список.push(ч > 32767 ? ч - 65536 : ч); }
    else if (тип === 4) список.push(чтение32(байты, п, мл));
    else if (тип === 9) { const ч = чтение32(байты, п, мл); список.push(ч > 2147483647 ? ч - 4294967296 : ч); }
    else if (тип === 5 || тип === 10) {
      let верх = чтение32(байты, п, мл), низ = чтение32(байты, п + 4, мл);
      if (тип === 10) {
        if (верх > 2147483647) верх -= 4294967296;
        if (низ > 2147483647) низ -= 4294967296;
      }
      список.push(низ === 0 ? 0 : верх / низ);
    } else if (тип === 11) список.push(новыйFloat(байты, п, мл, 4));
    else if (тип === 12) список.push(новыйFloat(байты, п, мл, 8));
    else список.push(байты[п]);
  }
  return счёт === 1 ? список[0] : список;
}

function новыйFloat(б, i, мл, размер) {
  const буфер = new ArrayBuffer(размер);
  const вид = new DataView(буфер);
  for (let k = 0; k < размер; k++) вид.setUint8(k, б[i + k]);
  return размер === 4 ? вид.getFloat32(0, мл) : вид.getFloat64(0, мл);
}

/**
 * Прочитать одну опись. Отдаёт карту «номер поля → значение» -- и рядом СЫРЫЕ записи: номер,
 * тип, количество и сами байты значения.
 *
 * Сырые нужны для обратной сборки. Разобранное значение для этого не годится: дробь 1/250
 * превращается в 0.004, и обратно ту же запись уже не сложить -- в файле появилось бы другое
 * число. Человеку, который убирает координаты и оставляет выдержку, мы обязаны вернуть
 * выдержку ровно ту, что была.
 */
function опись(тлф, смещение) {
  const { байты, мл } = тлф;
  const итог = new Map();
  итог.сырые = [];
  if (смещение + 2 > байты.length) return { поля: итог, следующая: 0 };
  const сколько = чтение16(байты, смещение, мл);
  // Опись с сотнями полей -- признак того, что мы читаем не то место, а мусор.
  if (сколько > 512) return { поля: итог, следующая: 0 };
  for (let k = 0; k < сколько; k++) {
    const п = смещение + 2 + k * 12;
    if (п + 12 > байты.length) break;
    const номер = чтение16(байты, п, мл);
    const тип = чтение16(байты, п + 2, мл);
    const счёт = чтение32(байты, п + 4, мл);
    const шаг = ДЛИНА[тип] || 1;
    const всего = счёт * шаг;
    // До четырёх байт значение лежит прямо здесь, дальше -- по смещению от начала TIFF.
    const место = всего <= 4 ? п + 8 : чтение32(байты, п + 8, мл);
    if (счёт > 65535 && тип !== 2 && тип !== 7) continue;    // явная порча
    итог.set(номер, значение(тлф, { тип, счёт, место }));
    if (место + всего <= байты.length) {
      итог.сырые.push({ номер, тип, счёт, байты: байты.slice(место, место + всего) });
    }
  }
  const хвост = смещение + 2 + сколько * 12;
  const следующая = хвост + 4 <= байты.length ? чтение32(байты, хвост, мл) : 0;
  return { поля: итог, следующая };
}

/**
 * Разобрать снимок. Отдаёт сырые поля по номерам -- называть их по-человечески будет
 * страница, у неё для этого есть язык.
 *
 * @returns {{есть: boolean, причина?: string, основные: Map, снимка: Map, gps: Map,
 *            порядок: 'мл'|'ст', вместилище: string}}
 */
export function разобратьExif(буфер) {
  const байты = new Uint8Array(буфер);
  let вместилище = '';
  let тифф = null;
  if (байты.length > 4 && байты[0] === 0xff && байты[1] === 0xd8) {
    вместилище = 'jpeg';
    тифф = изJpeg(байты);
  } else if (байты.length > 8 && байты[0] === 0x89 && байты[1] === 0x50) {
    вместилище = 'png';
    тифф = изPng(байты);
  } else if (байты.length > 12 && String.fromCharCode(байты[0], байты[1], байты[2], байты[3]) === 'RIFF'
    && String.fromCharCode(байты[8], байты[9], байты[10], байты[11]) === 'WEBP') {
    вместилище = 'webp';
    тифф = изWebp(байты);
  } else if (байты.length > 12 && String.fromCharCode(байты[4], байты[5], байты[6], байты[7]) === 'ftyp') {
    // HEIC/HEIF: EXIF лежит отдельным предметом в коробке meta. Разбираем коробки и достаём
    // его -- точки изображения при этом не трогаем вовсе.
    вместилище = 'heic';
    const где = найтиExifВHeic(буфер);
    if (где && где.длинаТифф > 8) тифф = байты.slice(где.тифф, где.тифф + где.длинаТифф);
    else return { есть: false, причина: 'нет', вместилище };
  } else {
    return { есть: false, причина: 'чужой', вместилище: '' };
  }

  if (!тифф || тифф.length < 8) return { есть: false, причина: 'нет', вместилище };

  const порядок = String.fromCharCode(тифф[0], тифф[1]);
  if (порядок !== 'II' && порядок !== 'MM') return { есть: false, причина: 'нет', вместилище };
  const мл = порядок === 'II';
  const тлф = { байты: тифф, мл };
  if (чтение16(тифф, 2, мл) !== 42) return { есть: false, причина: 'нет', вместилище };

  const первая = чтение32(тифф, 4, мл);
  const { поля: основные } = опись(тлф, первая);
  const снимка = основные.has(ПОЛЯ.exifIfd)
    ? опись(тлф, основные.get(ПОЛЯ.exifIfd)).поля : new Map();
  const gps = основные.has(ПОЛЯ.gpsIfd)
    ? опись(тлф, основные.get(ПОЛЯ.gpsIfd)).поля : new Map();

  // «Есть» -- значит есть ЧТО ПОКАЗАТЬ. Указатели на вложенные описи (0x8769, 0x8825) сами
  // по себе не значат ничего: PNG, пересохранённый на Маке, несёт пустую опись с одним таким
  // указателем -- и страница молчала бы, вместо того чтобы сказать «полей нет».
  const значимых = (карта) => [...карта.keys()]
    .filter((н) => н !== ПОЛЯ.exifIfd && н !== ПОЛЯ.gpsIfd).length;
  const всего = значимых(основные) + значимых(снимка) + значимых(gps);

  return {
    есть: всего > 0,
    причина: всего > 0 ? '' : 'нет',
    основные, снимка, gps,
    порядок: мл ? 'мл' : 'ст',
    вместилище,
  };
}

/**
 * СОБРАТЬ EXIF ЗАНОВО из сырых записей.
 *
 * ПОРЯДОК БАЙТОВ БЕРЁМ ИЗ ИСХОДНИКА. Сырые значения -- это куски файла как есть, и переложить
 * их в файл с другим порядком нельзя: короткое число уедет наизнанку, а у дроби числитель и
 * знаменатель станут миллионными. Поймано пробой: поворот 6 превращался в 1536. Дроби при
 * этом «сходились» -- числитель и знаменатель врут одинаково, и частное остаётся прежним, --
 * то есть беда была бы тихой и всплыла бы у того, кто открыл бы файл строгой программой.
 *
 * Правило размещения простое и заданное форматом: значение до четырёх байт лежит прямо в
 * записи, длиннее -- в общей куче после описей, а в записи стоит смещение от начала TIFF.
 *
 * @param {{основные: Array, снимка: Array, gps: Array}} части сырые записи по описям
 * @returns {Uint8Array|null} готовый кусок TIFF или null, если сохранять нечего
 */
export function собратьExif(части, какиеБайты = {}) {
  const мл = какиеБайты.мл !== false;
  const основные = [...(части.основные || [])].filter((з) => з.номер !== ПОЛЯ.exifIfd && з.номер !== ПОЛЯ.gpsIfd);
  const снимка = [...(части.снимка || [])];
  const gps = [...(части.gps || [])];
  if (!основные.length && !снимка.length && !gps.length) return null;

  const сорт = (а, б) => а.номер - б.номер;
  основные.sort(сорт); снимка.sort(сорт); gps.sort(сорт);

  // Место под указатели на вложенные описи -- они тоже записи в первой описи.
  const указатели = [];
  if (снимка.length) указатели.push({ номер: ПОЛЯ.exifIfd, тип: 4, счёт: 1, ссылка: 'снимка' });
  if (gps.length) указатели.push({ номер: ПОЛЯ.gpsIfd, тип: 4, счёт: 1, ссылка: 'gps' });
  const перваяОпись = [...основные, ...указатели].sort(сорт);

  const длинаОписи = (записи) => 2 + записи.length * 12 + 4;
  const началоПервой = 8;
  const началоСнимка = началоПервой + длинаОписи(перваяОпись);
  const началоGps = началоСнимка + (снимка.length ? длинаОписи(снимка) : 0);
  const началоКучи = началоGps + (gps.length ? длинаОписи(gps) : 0);

  let кучаДлина = 0;
  for (const з of [...перваяОпись, ...снимка, ...gps]) {
    if (з.байты && з.байты.length > 4) кучаДлина += з.байты.length + (з.байты.length % 2);
  }

  const всего = началоКучи + кучаДлина;
  const буфер = new Uint8Array(всего);
  const вид = new DataView(буфер.buffer);
  const метка = мл ? 0x49 : 0x4d;                // II или MM
  буфер[0] = метка; буфер[1] = метка;
  вид.setUint16(2, 42, мл);
  вид.setUint32(4, началоПервой, мл);

  let куча = началоКучи;
  const писатьОпись = (записи, начало, следующая) => {
    вид.setUint16(начало, записи.length, мл);
    записи.forEach((з, i) => {
      const п = начало + 2 + i * 12;
      вид.setUint16(п, з.номер, мл);
      вид.setUint16(п + 2, з.тип, мл);
      вид.setUint32(п + 4, з.счёт, мл);
      if (з.ссылка) {
        вид.setUint32(п + 8, з.ссылка === 'снимка' ? началоСнимка : началоGps, мл);
        return;
      }
      if (з.байты.length <= 4) {
        буфер.set(з.байты, п + 8);
      } else {
        вид.setUint32(п + 8, куча, мл);
        буфер.set(з.байты, куча);
        куча += з.байты.length + (з.байты.length % 2);
      }
    });
    вид.setUint32(начало + 2 + записи.length * 12, следующая, мл);
  };
  писатьОпись(перваяОпись, началоПервой, 0);
  if (снимка.length) писатьОпись(снимка, началоСнимка, 0);
  if (gps.length) писатьОпись(gps, началоGps, 0);
  return буфер;
}

/**
 * Координаты в обычные градусы. В снимке они лежат тремя дробями (градусы, минуты, секунды)
 * и отдельной буквой стороны света -- без неё юг не отличить от севера.
 */
export function координаты(gps) {
  const собрать = (части, стороны) => {
    if (!Array.isArray(части) || части.length < 3) return null;
    const г = части[0] + части[1] / 60 + части[2] / 3600;
    if (!isFinite(г)) return null;
    return стороны === 'S' || стороны === 'W' ? -г : г;
  };
  const ш = собрать(gps.get(ПОЛЯ_GPS.lat), gps.get(ПОЛЯ_GPS.latRef));
  const д = собрать(gps.get(ПОЛЯ_GPS.lon), gps.get(ПОЛЯ_GPS.lonRef));
  if (ш === null || д === null) return null;
  // Высота: 0 -- над уровнем моря, 1 -- ниже.
  let высота = gps.get(ПОЛЯ_GPS.alt);
  if (typeof высота === 'number' && gps.get(ПОЛЯ_GPS.altRef) === 1) высота = -высота;
  return { широта: ш, долгота: д, высота: typeof высота === 'number' ? высота : null };
}

/** Выдержка человеческим видом: 0.004 → «1/250». Длинные держим числом: 2.5 секунды. */
export function выдержкой(секунды) {
  if (typeof секунды !== 'number' || !isFinite(секунды) || секунды <= 0) return '';
  if (секунды >= 1) return String(Math.round(секунды * 10) / 10);
  return '1/' + Math.round(1 / секунды);
}

