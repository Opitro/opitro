// ---- УДАЛЕНИЕ ПОЛЕЙ ----------------------------------------------------------------------------
//
// Убираем ЛИШНЕЕ, НЕ ТРОГАЯ САМО ИЗОБРАЖЕНИЕ. Точки остаются те же байт в байт: мы лишь
// выбрасываем служебные отрезки файла. Это важнее, чем кажется: расхожий способ «открыть и
// пересохранить» пережимает снимок заново и портит его -- каждое пересохранение JPEG съедает
// качество, и человек, пришедший убрать координаты, незаметно теряет картинку.
//
// ПОВОРОТ ОСТАВЛЯЕМ. Снимок с телефона часто лежит в файле боком, а стоять прямо ему велит
// одно-единственное поле. Выбросив и его, мы «почистили бы» снимок так, что он у всех
// повернулся набок -- и человек решил бы, что мы его испортили. Поворот не говорит о человеке
// ничего, поэтому по умолчанию он остаётся; убрать вместе со всем остальным можно доводом.

/** Отрезки JPEG, которые несут сведения о съёмке, съёмщике и правках. Их и выбрасываем. */
const ЛИШНИЕ_JPEG = new Set([
  0xe1,   // APP1  -- EXIF и XMP (камера, дата, координаты, история правок)
  0xe2,   // APP2  -- FlashPix; цветовой профиль ICC тоже здесь, его бережём отдельно
  0xe3, 0xe4, 0xe5, 0xe6, 0xe7, 0xe8, 0xe9, 0xea, 0xeb,
  0xec,   // APP12 -- заметки некоторых камер
  0xed,   // APP13 -- IPTC: автор, место, подпись к снимку
  0xee, 0xef,
  0xfe,   // COM   -- произвольный комментарий
]);

/** Куски PNG со сведениями: поля EXIF, подписи, время правки. */
const ЛИШНИЕ_PNG = new Set(['eXIf', 'tEXt', 'iTXt', 'zTXt', 'tIME']);

/** Маленький отрезок APP1 с одним-единственным полем поворота. */
function отрезокПоворота(поворот) {
  const тифф = [
    0x49, 0x49, 0x2a, 0x00,            // II* -- младший байт вперёд
    0x08, 0x00, 0x00, 0x00,            // опись начинается сразу за заголовком
    0x01, 0x00,                        // в описи одно поле
    0x12, 0x01,                        // номер поля: поворот (0x0112)
    0x03, 0x00,                        // тип: короткое число
    0x01, 0x00, 0x00, 0x00,            // одна штука
    поворот & 0xff, (поворот >> 8) & 0xff, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00,            // следующей описи нет
  ];
  const голова = [0x45, 0x78, 0x69, 0x66, 0x00, 0x00];   // "Exif\0\0"
  const длина = 2 + голова.length + тифф.length;
  return new Uint8Array([0xff, 0xe1, (длина >> 8) & 0xff, длина & 0xff, ...голова, ...тифф]);
}

function цветовойПрофиль(байты, начало, длина) {
  // ICC лежит в APP2 и начинается словом "ICC_PROFILE". Его выбрасывать нельзя: без профиля
  // цвета снимка поедут, а сведений о человеке в нём нет.
  const имя = String.fromCharCode(...байты.slice(начало + 4, начало + 15));
  return длина > 16 && имя === 'ICC_PROFILE';
}

function чиститьJpeg(байты, оставитьПоворот, поворот) {
  const части = [байты.slice(0, 2)];                    // FFD8
  const убрано = [];
  let i = 2;
  let поворотПоставлен = false;
  while (i + 4 <= байты.length) {
    if (байты[i] !== 0xff) { i++; continue; }
    const метка = байты[i + 1];
    if (метка === 0xd8 || метка === 0x01 || (метка >= 0xd0 && метка <= 0xd7)) {
      части.push(байты.slice(i, i + 2)); i += 2; continue;
    }
    if (метка === 0xda) { части.push(байты.slice(i)); break; }   // дальше сами точки
    const длина = (байты[i + 2] << 8) | байты[i + 3];
    const конец = i + 2 + длина;
    const лишний = ЛИШНИЕ_JPEG.has(метка) && !(метка === 0xe2 && цветовойПрофиль(байты, i, длина));
    if (лишний) {
      убрано.push(метка === 0xfe ? 'comment' : 'app' + (метка - 0xe0));
      // Поворот возвращаем на место первого же выброшенного отрезка -- порядок в файле
      // соблюдён, и читающие программы находят его там, где ждут.
      if (оставитьПоворот && !поворотПоставлен && поворот && поворот !== 1) {
        части.push(отрезокПоворота(поворот));
        поворотПоставлен = true;
      }
    } else {
      части.push(байты.slice(i, конец));
    }
    i = конец;
  }
  return { части, убрано };
}

function чиститьPng(байты) {
  const части = [байты.slice(0, 8)];
  const убрано = [];
  let i = 8;
  while (i + 8 <= байты.length) {
    const длина = чтение32(байты, i, false);
    const имя = String.fromCharCode(байты[i + 4], байты[i + 5], байты[i + 6], байты[i + 7]);
    const конец = i + 12 + длина;
    if (ЛИШНИЕ_PNG.has(имя)) убрано.push(имя);
    else части.push(байты.slice(i, конец));
    if (имя === 'IEND') break;
    i = конец;
  }
  return { части, убрано };
}

function чиститьWebp(байты) {
  const части = [байты.slice(0, 12)];
  const убрано = [];
  let i = 12;
  while (i + 8 <= байты.length) {
    const имя = String.fromCharCode(байты[i], байты[i + 1], байты[i + 2], байты[i + 3]);
    const длина = чтение32(байты, i + 4, true);
    const шаг = 8 + длина + (длина % 2);
    if (имя === 'EXIF' || имя === 'XMP ') {
      убрано.push(имя.trim());
    } else {
      const кусок = байты.slice(i, i + шаг);
      // В заголовке VP8X флажками отмечено, что в файле есть EXIF и XMP. Если куски убраны,
      // а флажки остались, строгий читатель сочтёт файл битым.
      if (имя === 'VP8X' && кусок.length > 8) кусок[8] &= ~0b00001100;
      части.push(кусок);
    }
    i += шаг;
  }
  return { части, убрано };
}

/**
 * Убрать из снимка всё, что рассказывает о съёмке и о человеке.
 *
 * @param {ArrayBuffer} буфер файл как есть
 * @param {{оставитьПоворот?: boolean}} как
 * @returns {{вышло: boolean, причина?: string, байты?: Uint8Array, убрано: string[],
 *            было: number, стало: number, тип: string}}
 */
export function убратьМетаданные(буфер, как = {}) {
  const оставитьПоворот = как.оставитьПоворот !== false;
  const байты = new Uint8Array(буфер);
  const разбор = разобратьExif(буфер);
  // HEIC устроен иначе -- там поля правятся на месте, и это умеет убратьПоля(). Чтобы не
  // держать две дороги к одному делу, «убрать всё» для HEIC ведём через неё же.
  if (этоHeic(буфер)) {
    const ключи = [];
    for (const [карта, метка] of [[разбор.основные, '0'], [разбор.снимка, 'exif'], [разбор.gps, 'gps']]) {
      for (const з of (карта && карта.сырые) || []) {
        if (оставитьПоворот && метка === '0' && з.номер === ПОЛЯ.orientation) continue;
        ключи.push(метка + ':' + з.номер);
      }
    }
    if (!ключи.length) {
      return { вышло: false, причина: 'нет', убрано: [], было: байты.length,
        стало: байты.length, тип: 'heic' };
    }
    const и = убратьПоля(буфер, ключи);
    return { ...и, убрано: ключи, тип: 'heic' };
  }
  const поворот = разбор.есть && разбор.основные ? разбор.основные.get(ПОЛЯ.orientation) : 0;

  let итог = null, тип = разбор.вместилище;
  if (байты.length > 3 && байты[0] === 0xff && байты[1] === 0xd8) {
    итог = чиститьJpeg(байты, оставитьПоворот, поворот);
    тип = 'jpeg';
  } else if (байты.length > 8 && байты[0] === 0x89 && байты[1] === 0x50) {
    итог = чиститьPng(байты);
    тип = 'png';
  } else if (байты.length > 12 && String.fromCharCode(байты[0], байты[1], байты[2], байты[3]) === 'RIFF'
    && String.fromCharCode(байты[8], байты[9], байты[10], байты[11]) === 'WEBP') {
    итог = чиститьWebp(байты);
    тип = 'webp';
  } else {
    return { вышло: false, причина: разбор.причина === 'heic' ? 'heic' : 'чужой',
      убрано: [], было: байты.length, стало: байты.length, тип };
  }

  let всего = 0;
  for (const ч of итог.части) всего += ч.length;
  const собрано = new Uint8Array(всего);
  let место = 0;
  for (const ч of итог.части) { собрано.set(ч, место); место += ч.length; }

  // У WebP размер всего файла записан в заголовке -- после уборки его надо поправить.
  if (тип === 'webp' && собрано.length > 8) {
    const размер = собрано.length - 8;
    собрано[4] = размер & 0xff;
    собрано[5] = (размер >> 8) & 0xff;
    собрано[6] = (размер >> 16) & 0xff;
    собрано[7] = (размер >> 24) & 0xff;
  }

  return {
    вышло: true, байты: собрано, убрано: итог.убрано, тип,
    было: байты.length, стало: собрано.length,
    поворотОставлен: тип === 'jpeg' && оставитьПоворот && !!поворот && поворот !== 1,
  };
}

// ---- ВЫБОРОЧНОЕ УДАЛЕНИЕ -----------------------------------------------------------------------
//
// «Может, я не хочу удалять всё» -- слова владельца, и они верные. Фотограф убирает координаты,
// а выдержку и объектив бережёт: это его записи о съёмке. Поэтому поля можно выбирать по
// одному, а всё, что человек оставил, возвращается в файл ровно таким, каким было.
//
// Ключ поля -- «опись:номер»: 0:271 -- изготовитель в первой описи, exif:33434 -- выдержка,
// gps:2 -- широта. Такой ключ ничего не значит для человека, зато не путается и не зависит от
// языка страницы.

/** Проверочная сумма для кусков PNG: без неё файл считается битым. */
function сумма(байты) {
  let c = ~0;
  for (const б of байты) {
    c ^= б;
    for (let k = 0; k < 8; k++) c = (c >>> 1) ^ (0xEDB88320 & -(c & 1));
  }
  return (~c) >>> 0;
}

function кусокPng(имя, данные) {
  const голова = new Uint8Array(8);
  new DataView(голова.buffer).setUint32(0, данные.length, false);
  for (let i = 0; i < 4; i++) голова[4 + i] = имя.charCodeAt(i);
  const хвост = new Uint8Array(4);
  const тело = new Uint8Array(4 + данные.length);
  for (let i = 0; i < 4; i++) тело[i] = имя.charCodeAt(i);
  тело.set(данные, 4);
  new DataView(хвост.buffer).setUint32(0, сумма(тело), false);
  const всё = new Uint8Array(голова.length + данные.length + 4);
  всё.set(голова, 0); всё.set(данные, 8); всё.set(хвост, 8 + данные.length);
  return всё;
}

function склеить(части) {
  let всего = 0;
  for (const ч of части) всего += ч.length;
  const итог = new Uint8Array(всего);
  let место = 0;
  for (const ч of части) { итог.set(ч, место); место += ч.length; }
  return итог;
}

/**
 * Убрать ВЫБРАННЫЕ поля, остальные вернуть в файл нетронутыми.
 *
 * @param {ArrayBuffer} буфер файл как есть
 * @param {Set<string>|Array<string>} убрать ключи полей вида «0:271», «gps:2»
 * @returns {{вышло: boolean, причина?: string, байты?: Uint8Array, убрано: number,
 *            осталось: number, было: number, стало: number}}
 */
export function убратьПоля(буфер, убрать) {
  const ключи = убрать instanceof Set ? убрать : new Set(убрать || []);
  const байты = new Uint8Array(буфер);
  const разбор = разобратьExif(буфер);
  if (!разбор.есть) {
    return { вышло: false, причина: разбор.причина || 'нет', убрано: 0, осталось: 0,
      было: байты.length, стало: байты.length };
  }

  const отбор = (карта, метка) => (карта.сырые || [])
    .filter((з) => з.номер !== ПОЛЯ.exifIfd && з.номер !== ПОЛЯ.gpsIfd)
    .filter((з) => !ключи.has(метка + ':' + з.номер));
  const остатки = {
    основные: отбор(разбор.основные, '0'),
    снимка: отбор(разбор.снимка, 'exif'),
    gps: отбор(разбор.gps, 'gps'),
  };
  const осталось = остатки.основные.length + остатки.снимка.length + остатки.gps.length;
  const было = (разбор.основные.сырые || []).filter((з) => з.номер !== ПОЛЯ.exifIfd && з.номер !== ПОЛЯ.gpsIfd).length
    + (разбор.снимка.сырые || []).length + (разбор.gps.сырые || []).length;
  const тифф = собратьExif(остатки, { мл: разбор.порядок === 'мл' });

  let итог = null;
  if (байты.length > 3 && байты[0] === 0xff && байты[1] === 0xd8) {
    // JPEG: на месте прежнего APP1 ставим собранный заново; если сохранять нечего -- ничего.
    const части = [байты.slice(0, 2)];
    let i = 2, поставлен = false;
    while (i + 4 <= байты.length) {
      if (байты[i] !== 0xff) { i++; continue; }
      const метка = байты[i + 1];
      if (метка === 0xd8 || метка === 0x01 || (метка >= 0xd0 && метка <= 0xd7)) {
        части.push(байты.slice(i, i + 2)); i += 2; continue;
      }
      if (метка === 0xda) { части.push(байты.slice(i)); break; }
      const длина = (байты[i + 2] << 8) | байты[i + 3];
      const конец = i + 2 + длина;
      const лишний = ЛИШНИЕ_JPEG.has(метка) && !(метка === 0xe2 && цветовойПрофиль(байты, i, длина));
      if (лишний) {
        if (!поставлен && тифф) {
          const дл = 2 + 6 + тифф.length;
          const голова = new Uint8Array([0xff, 0xe1, (дл >> 8) & 0xff, дл & 0xff,
            0x45, 0x78, 0x69, 0x66, 0x00, 0x00]);
          части.push(голова, тифф);
          поставлен = true;
        }
      } else части.push(байты.slice(i, конец));
      i = конец;
    }
    итог = склеить(части);
  } else if (байты.length > 8 && байты[0] === 0x89 && байты[1] === 0x50) {
    const части = [байты.slice(0, 8)];
    let i = 8, поставлен = false;
    while (i + 8 <= байты.length) {
      const длина = чтение32(байты, i, false);
      const имя = String.fromCharCode(байты[i + 4], байты[i + 5], байты[i + 6], байты[i + 7]);
      const конец = i + 12 + длина;
      if (ЛИШНИЕ_PNG.has(имя)) {
        if (имя === 'eXIf' && тифф && !поставлен) { части.push(кусокPng('eXIf', тифф)); поставлен = true; }
      } else части.push(байты.slice(i, конец));
      if (имя === 'IEND') break;
      i = конец;
    }
    итог = склеить(части);
  } else if (байты.length > 12 && String.fromCharCode(байты[0], байты[1], байты[2], байты[3]) === 'RIFF') {
    const части = [байты.slice(0, 12)];
    let i = 12, поставлен = false;
    while (i + 8 <= байты.length) {
      const имя = String.fromCharCode(байты[i], байты[i + 1], байты[i + 2], байты[i + 3]);
      const длина = чтение32(байты, i + 4, true);
      const шаг = 8 + длина + (длина % 2);
      if (имя === 'EXIF' || имя === 'XMP ') {
        if (имя === 'EXIF' && тифф && !поставлен) {
          const голова = new Uint8Array(8);
          for (let k = 0; k < 4; k++) голова[k] = 'EXIF'.charCodeAt(k);
          new DataView(голова.buffer).setUint32(4, тифф.length, true);
          части.push(голова, тифф, ...(тифф.length % 2 ? [new Uint8Array(1)] : []));
          поставлен = true;
        }
      } else {
        const кусок = байты.slice(i, i + шаг);
        if (имя === 'VP8X' && кусок.length > 8 && !тифф) кусок[8] &= ~0b00001100;
        части.push(кусок);
      }
      i += шаг;
    }
    итог = склеить(части);
    const размер = итог.length - 8;
    итог[4] = размер & 0xff; итог[5] = (размер >> 8) & 0xff;
    итог[6] = (размер >> 16) & 0xff; итог[7] = (размер >> 24) & 0xff;
  } else if (этоHeic(буфер)) {
    // HEIC ПРАВИМ НА МЕСТЕ. Сдвигать ничего нельзя: в описи коробки meta записаны смещения
    // всех предметов, и сдвиг одного испортил бы файл целиком. Собранный заново EXIF всегда
    // короче прежнего (полей стало меньше), поэтому он помещается на старое место, а хвост
    // забивается нулями. Точки изображения лежат отдельным предметом и не трогаются.
    const где = найтиExifВHeic(буфер);
    if (!где) {
      return { вышло: false, причина: 'нет', убрано: 0, осталось: 0,
        было: байты.length, стало: байты.length };
    }
    итог = байты.slice();
    const место = где.тифф;
    const запас = где.длинаТифф;
    if (тифф && тифф.length <= запас) итог.set(тифф, место);
    for (let i = место + (тифф ? тифф.length : 0); i < место + запас; i++) итог[i] = 0;
  } else {
    return { вышло: false, причина: 'чужой', убрано: 0, осталось: 0,
      было: байты.length, стало: байты.length };
  }

  return { вышло: true, байты: итог, убрано: было - осталось, осталось,
    было: байты.length, стало: итог.length };
}

// ---- ПОЛНЫЙ РАЗБОР ЧУЖОЙ БИБЛИОТЕКОЙ -----------------------------------------------------------
//
// Свой разбор (выше) быстрый, лёгкий и ничего не качает -- он и остаётся главным: показывает
// то, что человеку важно, и умеет собирать файл обратно без потери качества.
//
// Но снимок с телефона несёт куда больше: заметки производителя, XMP, цветовой профиль, а у
// HEIC вообще другое устройство файла. Догонять ExifTool своими силами -- это месяцы, поэтому
// ширину берём готовой библиотекой (ExifReader, 132 КБ, чистый JS). Она ЧИТАЕТ; собирает файл
// по-прежнему наш код.
//
// Грузится она ТОЛЬКО когда человек выбрал снимок: пустая страница не должна платить за то,
// чем ещё не пользуются.

let ширь = null;

/** Подгрузить широкий разборщик. Первый раз -- сеть, дальше из памяти. */
export async function взятьШирокий() {
  if (!ширь) ширь = (await import('exifreader')).default;
  return ширь;
}

/**
 * Прочитать ВСЁ, что есть в файле: EXIF, GPS, XMP, IPTC, цветовой профиль, заметки
 * производителя. Отдаёт плоский список строк «имя -- значение» плюс сами теги.
 */
export async function прочитатьВсё(буфер) {
  const читатель = await взятьШирокий();
  let теги;
  try {
    теги = читатель.load(буфер, { expanded: true, includeUnknown: true });
  } catch (е) {
    return { вышло: false, причина: String((е && е.message) || е).slice(0, 120), группы: [] };
  }

  // Раскладываем по группам, которые понятны человеку, а не по внутренним именам формата.
  const ИМЕНА_ГРУПП = {
    exif: 'exif', gps: 'gps', xmp: 'xmp', iptc: 'iptc', icc: 'icc',
    file: 'file', jfif: 'file', pngFile: 'file', pngText: 'xmp', riff: 'file',
    Thumbnail: 'thumb', composite: 'exif', photoshop: 'iptc', makerNote: 'maker',
  };
  const группы = new Map();
  const положить = (куда, имя, значение) => {
    if (значение === undefined || значение === null || значение === '') return;
    if (!группы.has(куда)) группы.set(куда, []);
    группы.get(куда).push({ имя, знач: значение });
  };

  for (const [раздел, поля] of Object.entries(теги)) {
    if (!поля || typeof поля !== 'object') continue;
    const куда = ИМЕНА_ГРУПП[раздел] || 'other';
    for (const [имя, тег] of Object.entries(поля)) {
      if (!тег) continue;
      let знач = тег.description !== undefined ? тег.description : тег.value;
      if (Array.isArray(знач)) знач = знач.slice(0, 8).join(', ');
      знач = String(знач);
      // Двоичные хвосты и километровые строки человеку не нужны: он их не прочтёт, а список
      // ими захлебнётся.
      if (!знач || знач.length > 120 || знач === '[object Object]') continue;
      положить(куда, имя, знач);
    }
  }
  let всего = 0;
  for (const список of группы.values()) всего += список.length;
  return { вышло: true, всего, группы: [...группы.entries()].map(([имя, поля]) => ({ имя, поля })) };
}

// ---- HEIC ---------------------------------------------------------------------------------------
//
// Снимки iPhone по умолчанию в HEIC, и сам браузер их не показывает и не разбирает. Раньше
// страница честно говорила «не умеем» -- владелец справедливо возразил, что у соседей умеют.
// Умеют они тем же способом: готовым разбором, собранным в WebAssembly. Берём libheif
// (1,4 МБ + 91 КБ) -- он РИСУЕТ снимок, чтобы человек видел, что открыл.
//
// Грузится только тогда, когда выбран именно HEIC.

let хейф = null;

export async function взятьHeic() {
  if (!хейф) хейф = await import('libheif-js/wasm-bundle');
  return хейф.default || хейф;
}

/** Это HEIC/HEIF? Смотрим по началу файла, а не по имени: имя врёт чаще всего. */
export function этоHeic(буфер) {
  const б = new Uint8Array(буфер);
  if (б.length < 12) return false;
  if (String.fromCharCode(б[4], б[5], б[6], б[7]) !== 'ftyp') return false;
  const вид = String.fromCharCode(б[8], б[9], б[10], б[11]).toLowerCase();
  return ['heic', 'heix', 'hevc', 'heim', 'heis', 'hevm', 'hevs', 'mif1', 'msf1', 'avif']
    .includes(вид);
}

/**
 * Раскрыть HEIC в точки, чтобы показать снимок. Возвращает ImageData -- его можно положить
 * на холст, как любую картинку.
 */
export async function раскрытьHeic(буфер) {
  const libheif = await взятьHeic();
  const декодер = new libheif.HeifDecoder();
  const кадры = декодер.decode(new Uint8Array(буфер));
  if (!кадры || !кадры.length) throw new Error('в файле нет кадров');
  const кадр = кадры[0];
  const ш = кадр.get_width(), в = кадр.get_height();
  const точки = new ImageData(ш, в);
  await new Promise((готово, беда) => {
    кадр.display(точки, (итог) => (итог ? готово(итог) : беда(new Error('не раскрылось'))));
  });
  return точки;
}

// ---- ВНУТРИ HEIC --------------------------------------------------------------------------------
//
// HEIC устроен коробками (тот же строй, что у видео MP4): опись предметов лежит в коробке
// meta, а сами предметы -- в общей куче mdat. EXIF в нём -- такой же предмет, как и картинка,
// и лежит он отдельным куском: это значит, что и прочитать, и убрать его можно, НЕ ТРОГАЯ
// точки изображения.
//
// Убираем, не сдвигая ничего: на месте прежнего EXIF пишем собранный заново (он всегда не
// длиннее прежнего, потому что полей стало меньше), а хвост забиваем нулями. Смещения всех
// остальных предметов остаются прежними, и файл остаётся правильным. Пересжатия нет вовсе.

/** Пройти коробки на одном уровне и отдать их границы. */
function коробки(байты, от, до) {
  const итог = [];
  let i = от;
  while (i + 8 <= до) {
    const вид = new DataView(байты.buffer, байты.byteOffset + i, Math.min(8, до - i));
    let длина = вид.getUint32(0, false);
    const имя = String.fromCharCode(байты[i + 4], байты[i + 5], байты[i + 6], байты[i + 7]);
    let тело = i + 8;
    if (длина === 1) {                       // длина в восьми байтах
      if (i + 16 > до) break;
      const б = new DataView(байты.buffer, байты.byteOffset + i + 8, 8);
      длина = Number(б.getBigUint64(0, false));
      тело = i + 16;
    } else if (длина === 0) длина = до - i;   // коробка до конца файла
    if (длина < 8 || i + длина > до) break;
    итог.push({ имя, начало: i, тело, конец: i + длина });
    i += длина;
  }
  return итог;
}

function найти(байты, список, имя) { return список.find((к) => к.имя === имя); }

/**
 * Где в HEIC лежит EXIF. Возвращает границы самого TIFF внутри файла или null.
 */
export function найтиExifВHeic(буфер) {
  const байты = new Uint8Array(буфер);
  const верх = коробки(байты, 0, байты.length);
  const meta = найти(байты, верх, 'meta');
  if (!meta) return null;
  // meta -- «полная коробка»: перед детьми лежат версия и флаги.
  const дети = коробки(байты, meta.тело + 4, meta.конец);
  const iinf = найти(байты, дети, 'iinf');
  const iloc = найти(байты, дети, 'iloc');
  if (!iinf || !iloc) return null;

  // 1. Какой предмет -- EXIF: смотрим описи infe.
  const вид = new DataView(байты.buffer, байты.byteOffset);
  const версияIinf = байты[iinf.тело];
  let п = iinf.тело + 4;
  const сколько = версияIinf === 0 ? вид.getUint16(п, false) : вид.getUint32(п, false);
  п += версияIinf === 0 ? 2 : 4;
  let нужный = -1;
  for (const infe of коробки(байты, п, iinf.конец)) {
    if (infe.имя !== 'infe') continue;
    const в = байты[infe.тело];
    let к = infe.тело + 4;
    const номер = в < 3 ? вид.getUint16(к, false) : vРазмер(в, вид, к);
    к += в < 3 ? 2 : (в === 3 ? 2 : 4);
    к += 2;                                   // защита (protection_index)
    const тип = String.fromCharCode(байты[к], байты[к + 1], байты[к + 2], байты[к + 3]);
    if (тип === 'Exif') { нужный = номер; break; }
  }
  if (нужный < 0) return null;

  // 2. Где он лежит: опись iloc.
  const вер = байты[iloc.тело];
  let к = iloc.тело + 4;
  const разм = байты[к], разм2 = байты[к + 1];
  const размСмещения = разм >> 4, размДлины = разм & 15;
  const размОсновы = разм2 >> 4, размПорядка = разм2 & 15;
  к += 2;
  const счёт = вер < 2 ? вид.getUint16(к, false) : вид.getUint32(к, false);
  к += вер < 2 ? 2 : 4;
  const число = (сколько, место) => {
    if (сколько === 0) return 0;
    if (сколько === 4) return вид.getUint32(место, false);
    if (сколько === 8) return Number(вид.getBigUint64(место, false));
    if (сколько === 2) return вид.getUint16(место, false);
    return 0;
  };
  for (let i = 0; i < счёт; i++) {
    const номер = вер < 2 ? вид.getUint16(к, false) : вид.getUint32(к, false);
    к += вер < 2 ? 2 : 4;
    if (вер === 1 || вер === 2) к += 2;       // способ размещения
    к += 2;                                    // ссылка на данные
    const основа = число(размОсновы, к);
    к += размОсновы;
    const кусков = вид.getUint16(к, false);
    к += 2;
    for (let j = 0; j < кусков; j++) {
      к += размПорядка;
      const смещение = число(размСмещения, к);
      к += размСмещения;
      const длина = число(размДлины, к);
      к += размДлины;
      if (номер === нужный && j === 0) {
        const начало = основа + смещение;
        if (начало + длина > байты.length) return null;
        // Первые четыре байта -- отступ до заголовка TIFF (обычно ноль).
        const отступ = вид.getUint32(начало, false);
        const тифф = начало + 4 + отступ;
        return { предмет: начало, длинаПредмета: длина, тифф, длинаТифф: длина - 4 - отступ };
      }
    }
  }
  return null;

  function vРазмер(в, вид2, место) { return в === 3 ? вид2.getUint16(место, false) : вид2.getUint32(место, false); }
}
