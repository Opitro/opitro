/**
 * РАСПОЗНАВАНИЕ ТЕКСТА В БРАУЗЕРЕ -- общее для сканера MRZ и сканера текста с фото.
 *
 * Движок (Tesseract) и языковые азбуки лежат у нас же, в /tess/, и приезжают только тогда,
 * когда человек выбрал снимок. Ничего не уходит наружу: ни кадр, ни распознанное. Для
 * страницы, куда несут паспорт или чужое письмо, это не вежливая фраза, а условие.
 *
 * Веса, чтобы решать с открытыми глазами: ядро 2,7 МБ, азбука 1,1--1,9 МБ на язык (по сети
 * меньше -- отдаются сжатыми). Азбука кешируется браузером, второй раз начинается сразу.
 */

/** Умеет ли браузер быстрые команды WebAssembly: с ними чтение заметно скорее. */
function поддержкаSIMD() {
  try {
    return WebAssembly.validate(new Uint8Array([
      0, 97, 115, 109, 1, 0, 0, 0, 1, 5, 1, 96, 0, 1, 123, 3, 2, 1, 0,
      10, 10, 1, 8, 0, 65, 0, 253, 15, 253, 98, 11,
    ]));
  } catch (е) { return false; }
}

const работники = new Map();   // язык -> обещание работника: второй раз поднимать незачем

/**
 * Поднять распознаватель для набора азбук. `языки` -- строка вида 'rus' или 'rus+eng':
 * два языка разом нужны для текста, где кириллица идёт вперемешку с латиницей.
 * `ход` зовётся с долей от 0 до 1, пока едут файлы.
 */
export async function поднятьЧтеца(языки, ход) {
  if (работники.has(языки)) return работники.get(языки);
  const обещание = (async () => {
    const { createWorker } = await import('tesseract.js');
    const ядро = поддержкаSIMD()
      ? '/tess/tesseract-core-simd-lstm.js'
      : '/tess/tesseract-core-lstm.js';
    return createWorker(языки, 1, {
      workerPath: '/tess/worker.min.js',
      // ВОРКЕР ИЗ ФАЙЛА, а не из blob-адреса: внутри blob «рядом со мной» указывает в никуда,
      // и движок молча зависал на шаге инициализации -- ни ошибки, ни отказа.
      workerBlobURL: false,
      corePath: ядро,
      langPath: '/tess/',
      gzip: true,
      logger: (м) => {
        if (ход && м && typeof м.progress === 'number') ход(м.progress, м.status || '');
      },
    });
  })();
  работники.set(языки, обещание);
  try { return await обещание; } catch (е) { работники.delete(языки); throw е; }
}

/**
 * ПОДГОТОВИТЬ СНИМОК К ЧТЕНИЮ.
 *
 * Движок читает тем лучше, чем крупнее и чище буквы. Поэтому: переводим в серое по
 * восприятию, растягиваем контраст по краям гистограммы (снимок с телефона всегда сероват) и
 * увеличиваем до полутора-двух тысяч точек по ширине. Без этого тот же движок на том же
 * снимке ошибается втрое чаще -- проверено на образцах.
 *
 * `часть` -- доля кадра (левая, верхняя, ширина, высота в долях), если человек выделил кусок.
 * `светлыйНаТёмном` -- для снимков экрана с тёмной темой: буквы светлые, фон чёрный, и без
 * обращения цветов движок видит кашу.
 */
export function подготовить(источник, { ш, в, часть = null, светлыйНаТёмном = false,
  ширинаЦели = 0, безКонтраста = false, безВыравнивания = false } = {}) {
  const кх = часть ? Math.round(часть.х * ш) : 0;
  const ку = часть ? Math.round(часть.у * в) : 0;
  const кш = часть ? Math.max(8, Math.round(часть.ш * ш)) : ш;
  const кв = часть ? Math.max(8, Math.round(часть.в * в)) : в;

  // РАЗМЕР. Движку нужны буквы высотой примерно в тридцать точек; на снимке телефона строка
  // часто вдвое мельче. Тянем до двух с половиной тысяч точек по ширине -- дальше растёт
  // только время. Уменьшать не даём вовсе: мелкий текст от этого гибнет.
  // РАСТЯГИВАТЬ НАДО В МЕРУ. Мелкий шрифт от увеличения выигрывает, но иероглифы при
  // сильном растяжении расплываются и рассыпаются: китайская азбука давала 95 процентов на
  // исходном снимке и 53 -- на растянутом втрое. Поэтому тянем не больше чем вдвое и не выше
  // 1800 точек: этого хватает и мелкому шрифту этикетки.
  const цель = ширинаЦели || 1800;
  let к = Math.min(2, Math.max(1, цель / кш));
  // ПОТОЛОК ПО ПЛОЩАДИ. Снимок с телефона -- двенадцать мегапикселей; после увеличения холст
  // разрастался так, что расчёт порога съедал сотню мегабайт и телефон закрывал вкладку.
  // Три мегапикселя хватает: буквы и так крупнее, чем нужно движку.
  const ПРЕДЕЛ_ТОЧЕК = 3.2e6;
  if (кш * кв * к * к > ПРЕДЕЛ_ТОЧЕК) к = Math.sqrt(ПРЕДЕЛ_ТОЧЕК / (кш * кв));
  const холст = document.createElement('canvas');
  холст.width = Math.max(1, Math.round(кш * к));
  холст.height = Math.max(1, Math.round(кв * к));
  const кон = холст.getContext('2d', { willReadFrequently: true });
  кон.imageSmoothingQuality = 'high';
  кон.drawImage(источник, кх, ку, кш, кв, 0, 0, холст.width, холст.height);

  const точки = кон.getImageData(0, 0, холст.width, холст.height);
  const д = точки.data;
  const всего = холст.width * холст.height;
  const серый = new Uint8ClampedArray(всего);
  for (let i = 0, п = 0; i < д.length; i += 4, п++) {
    let г = (д[i] * 299 + д[i + 1] * 587 + д[i + 2] * 114) / 1000 | 0;
    if (светлыйНаТёмном) г = 255 - г;
    серый[п] = г;
  }

  // МЕСТНЫЙ ПОРОГ вместо общего растяжения контраста: тень поперёк листа и лампа сбоку
  // перестают мешать -- порог считается вокруг каждой точки отдельно.
  const чёрнобелый = безКонтраста ? серый : местныйПорог(серый, холст.width, холст.height);
  for (let i = 0, п = 0; i < д.length; i += 4, п++) {
    д[i] = д[i + 1] = д[i + 2] = чёрнобелый[п];
    д[i + 3] = 255;
  }
  кон.putImageData(точки, 0, 0);

  // ВЫРАВНИВАНИЕ. Лист в руках всегда чуть повёрнут, а движок ждёт горизонтальных строк.
  // Поворачиваем на найденный угол, добивая углы белым, -- и только если наклон заметен.
  if (!безВыравнивания) {
    const угол = уголНаклона(чёрнобелый, холст.width, холст.height);
    if (Math.abs(угол) >= 0.5) {
      const ровный = document.createElement('canvas');
      ровный.width = холст.width; ровный.height = холст.height;
      const к2 = ровный.getContext('2d', { willReadFrequently: true });
      к2.fillStyle = '#fff';
      к2.fillRect(0, 0, ровный.width, ровный.height);
      к2.translate(ровный.width / 2, ровный.height / 2);
      к2.rotate((-угол * Math.PI) / 180);
      к2.drawImage(холст, -холст.width / 2, -холст.height / 2);
      return ровный;
    }
  }
  return холст;
}

/**
 * УГОЛ НАКЛОНА СТРОК. Движок читает горизонтальные строки; на снимке из рук лист всегда
 * повёрнут на градус-другой, и это стоит десятков процентов точности.
 *
 * Способ старый и надёжный: поворачиваем мысленно на разные углы и смотрим, при каком
 * СТРОКИ РЕЗЧЕ -- то есть тёмные точки собираются в узкие полосы, а между строками остаётся
 * белое. Мера резкости -- разброс сумм по рядам. Считаем на уменьшенной копии: точность угла
 * от этого не страдает, а времени уходит в разы меньше.
 */
function уголНаклона(серый, ш, в) {
  const шаг = Math.max(1, Math.round(Math.max(ш, в) / 500));
  const мш = Math.floor(ш / шаг), мв = Math.floor(в / шаг);
  const мелкий = new Float32Array(мш * мв);
  for (let у = 0; у < мв; у++) for (let х = 0; х < мш; х++) {
    мелкий[у * мш + х] = 255 - серый[(у * шаг) * ш + (х * шаг)];   // тёмное = крупное число
  }
  const резкость = (угол) => {
    const син = Math.sin(угол), кос = Math.cos(угол);
    const ряды = new Float32Array(мв);
    for (let у = 0; у < мв; у++) {
      for (let х = 0; х < мш; х++) {
        const у2 = Math.round((х - мш / 2) * син + (у - мв / 2) * кос + мв / 2);
        if (у2 >= 0 && у2 < мв) ряды[у2] += мелкий[у * мш + х];
      }
    }
    let сумма = 0, сумма2 = 0;
    for (let у = 0; у < мв; у++) { сумма += ряды[у]; сумма2 += ряды[у] * ряды[у]; }
    const средн = сумма / мв;
    return сумма2 / мв - средн * средн;      // разброс: чем больше, тем ровнее строки
  };
  let лучший = 0, лучшая = -1;
  for (let град = -6; град <= 6; град += 0.5) {
    const р = резкость(град * Math.PI / 180);
    if (р > лучшая) { лучшая = р; лучший = град; }
  }
  return лучший;
}

/**
 * МЕСТНЫЙ ПОРОГ (метод Саувола). Тень от руки, лампа сбоку, серая бумага -- при общем пороге
 * половина листа уходит в чёрное. Здесь порог свой у каждой точки: считается по среднему и
 * разбросу яркости вокруг неё. Считаем через суммы по прямоугольникам, поэтому окно любого
 * размера стоит одинаково дёшево.
 */
function местныйПорог(серый, ш, в, окно = 0, k = 0.34) {
  // Окно порога -- примерно с высоту строки. Слишком широкое стирает тонкие штрихи (на
  // иероглифах это видно сразу), слишком узкое дырявит толстые буквы.
  const р = Math.max(9, Math.min(28, Math.round((окно || в / 45) / 2)));
  // Суммы яркости влезают в целое: 255 × число точек намного меньше предела Uint32. Так
  // таблица занимает вдвое меньше памяти -- на снимке с телефона это десятки мегабайт, и
  // телефон от прежней пары двойных таблиц просто закрывал вкладку.
  const сум = new Uint32Array((ш + 1) * (в + 1));
  const сум2 = new Float64Array((ш + 1) * (в + 1));
  for (let у = 0; у < в; у++) {
    let строка = 0, строка2 = 0;
    for (let х = 0; х < ш; х++) {
      const з = серый[у * ш + х];
      строка += з; строка2 += з * з;
      сум[(у + 1) * (ш + 1) + х + 1] = сум[у * (ш + 1) + х + 1] + строка;
      сум2[(у + 1) * (ш + 1) + х + 1] = сум2[у * (ш + 1) + х + 1] + строка2;
    }
  }
  const вышло = new Uint8ClampedArray(ш * в);
  for (let у = 0; у < в; у++) {
    const у1 = Math.max(0, у - р), у2 = Math.min(в - 1, у + р);
    for (let х = 0; х < ш; х++) {
      const х1 = Math.max(0, х - р), х2 = Math.min(ш - 1, х + р);
      const н = (у2 - у1 + 1) * (х2 - х1 + 1);
      const с = сум[(у2 + 1) * (ш + 1) + х2 + 1] - сум[у1 * (ш + 1) + х2 + 1]
              - сум[(у2 + 1) * (ш + 1) + х1] + сум[у1 * (ш + 1) + х1];
      const с2 = сум2[(у2 + 1) * (ш + 1) + х2 + 1] - сум2[у1 * (ш + 1) + х2 + 1]
               - сум2[(у2 + 1) * (ш + 1) + х1] + сум2[у1 * (ш + 1) + х1];
      const средн = с / н;
      const разброс = Math.sqrt(Math.max(0, с2 / н - средн * средн));
      const порог = средн * (1 + k * (разброс / 128 - 1));
      вышло[у * ш + х] = серый[у * ш + х] > порог ? 255 : 0;
    }
  }
  return вышло;
}

/**
 * Разобрать ответ движка в удобный вид: абзацы, строки, слова -- с их местом на снимке и
 * уверенностью. Место нужно, чтобы подсветить строку прямо на фотографии: человек видит,
 * откуда взялась каждая строка, и сразу замечает, что прочитано мимо.
 *
 * Координаты переводим В ДОЛИ снимка: холст мы увеличивали, а показываем снимок как есть.
 */
export function разобратьЧтение(data, { ш, в, часть = null } = {}) {
  const абзацы = [];
  const вДоли = (р) => {
    const дх = часть ? часть.х : 0, ду = часть ? часть.у : 0;
    const дш = часть ? часть.ш : 1, дв = часть ? часть.в : 1;
    return {
      х: дх + (р.x0 / ш) * дш,
      у: ду + (р.y0 / в) * дв,
      ш: ((р.x1 - р.x0) / ш) * дш,
      в: ((р.y1 - р.y0) / в) * дв,
    };
  };
  for (const блок of data.blocks || []) {
    for (const абзац of блок.paragraphs || []) {
      const строки = [];
      for (const стр of абзац.lines || []) {
        const текст = (стр.text || '').replace(/\s+$/, '');
        if (!текст.trim()) continue;
        строки.push({
          текст,
          уверенность: Math.round(стр.confidence || 0),
          место: вДоли(стр.bbox),
          слова: (стр.words || []).map((с) => ({
            текст: с.text, уверенность: Math.round(с.confidence || 0), место: вДоли(с.bbox),
          })),
        });
      }
      if (строки.length) абзацы.push({ строки });
    }
  }
  // Текст собираем сами, а не берём data.text: в браузерной сборке он приходит ПУСТЫМ, даже
  // когда строки прочитаны, -- на этом я уже обжёгся: страница решила, что не прочитала
  // ничего, и перебрала все азбуки подряд. Заодно абзацы нужны человеку, а не склейка.
  const текст = абзацы.map((а) => а.строки.map((с) => с.текст).join('\n')).join('\n\n');
  // Уверенность тоже считаем сами, по строкам: data.confidence там же и по той же причине ноль.
  let сумма = 0, весов = 0;
  for (const а of абзацы) for (const с of а.строки) {
    const вес = Math.max(1, с.текст.length);
    сумма += с.уверенность * вес; весов += вес;
  }
  const уверенность = весов ? Math.round(сумма / весов) : Math.round(data.confidence || 0);
  return { абзацы, текст, уверенность };
}

/**
 * ЧЕЛОВЕК НЕ ВЫБИРАЕТ АЗБУКУ. Он принёс снимок -- страница обязана прочитать что есть.
 *
 * Движок сравнивает буквы с образцами своего языка, поэтому «читать любой язык одной кнопкой»
 * невозможно в принципе -- но знать об этом человеку незачем. Делаем так: сперва читаем
 * азбукой страницы с латиницей (девять снимков из десяти этим и закрываются), а если вышло
 * пусто или сплошная каша -- молча пробуем другие письменности по очереди и берём лучшую.
 *
 * Азбуки маленькие: китайская 2,5 МБ, арабская 1,4, греческая 1,4 -- качается по одной и
 * только когда понадобилась. Готовые «наборы письменностей» от Tesseract мы не берём: одна
 * латиница там весит 89 МБ.
 */
// Латиница -- это не только английский. Владелец снял бутылку молока с французской этикеткой:
// английская азбука выдала кашу, потому что не знает ни «é», ни «ç», ни французских слов.
// Поэтому у латиницы свой ряд запасных, и пробуем мы его ПЕРВЫМ, если на снимке латиница.
export const ЛАТИНСКИЕ = ['fra', 'deu', 'spa', 'ita', 'por', 'nld', 'pol', 'tur', 'ces'];
// Другие письменности: их не спутать с латиницей, и пробовать их имеет смысл только если
// латиницы на снимке толком нет.
export const ПИСЬМЕННОСТИ = ['chi_sim', 'jpn', 'kor', 'ara', 'ell', 'heb', 'hin', 'tha'];
export const ЗАПАСНЫЕ = [...ЛАТИНСКИЕ, ...ПИСЬМЕННОСТИ];

/**
 * Чего на снимке больше -- латиницы или другой письменности. Смотрим на то, что уже прочитано
 * базовым набором: даже кривое чтение сохраняет род букв. Нужно, чтобы не перебирать восемь
 * азбук подряд, а начать с того ряда, который вероятнее.
 */
function ряднаяДогадка(текст) {
  const латиницы = (текст.match(/[A-Za-zÀ-ÿ]/g) || []).length;
  const кириллицы = (текст.match(/[А-Яа-яЁёЇїІіЄєҐґ]/g) || []).length;
  const прочего = (текст.match(/[\u0370-\u1CFF\u3040-\u9FFF\uAC00-\uD7AF]/g) || []).length;
  if (прочего > латиницы && прочего > кириллицы) return 'иные';
  return латиницы >= кириллицы ? 'латиница' : 'кириллица';
}

/**
 * КАКОЙ ЕВРОПЕЙСКИЙ ЯЗЫК ПЕРЕД НАМИ -- по тому, что уже прочитано, пусть и криво.
 *
 * Даже неверное чтение сохраняет облик слов: «pour», «avec», «température» выдают француза
 * вернее любой уверенности движка. Догадка нужна, чтобы не перебирать девять азбук, а взять
 * одну-две. Если не угадали -- перебор всё равно остаётся, просто он длиннее.
 */
// Приметы нарочно УЗКИЕ: общие слова вроде «de» есть у половины Европы, и по ним голландская
// азбука обошла французскую на французской же этикетке. Берём то, что встречается почти
// только в своём языке -- слова и буквы.
const ПРИМЕТЫ = {
  fra: /\b(les|des|pour|avec|sans|conserver|température|préférence|matières|valeurs|consommer|ingrédients)\b|[èêçôûœ]/i,
  deu: /\b(der|die|das|und|mit|ohne|kühl|mindestens|haltbar|zutaten|nährwerte|gekühlt)\b|[äöüß]/i,
  spa: /\b(los|las|para|con|sin|conservar|valores|grasas|ingredientes|consumir)\b|[ñáíóú]/i,
  ita: /\b(per|con|senza|conservare|valori|ingredienti|grassi|consumare)\b|[àìòù]/i,
  por: /\b(para|com|sem|conservar|valores|ingredientes|gordura|consumir)\b|[ãõ]/i,
  nld: /\b(het|een|met|zonder|houdbaar|ingrediënten|voedingswaarde|bewaren)\b|[ëï]/i,
  pol: /\b(dla|bez|zawiera|wartość|składniki|przechowywać)\b|[ąćęłńśźż]/i,
  tur: /\b(icin|ile|gida|besin|degerleri|saklayiniz)\b|[çğış]/i,
  ces: /\b(pro|bez|obsahuje|hodnoty|složení|skladujte)\b|[čďěňřťůž]/i,
};
export function угадатьЛатинский(текст) {
  const очки = [];
  for (const [язык, примета] of Object.entries(ПРИМЕТЫ)) {
    const н = (текст.match(new RegExp(примета.source, 'gi')) || []).length;
    if (н) очки.push([язык, н]);
  }
  очки.sort((а, б) => б[1] - а[1]);
  return очки.map(([язык]) => язык);
}

/**
 * ЧЕГО СТОИТ ПРОЧИТАННОЕ. Уверенность движка сравнивать между азбуками нельзя: кириллическая
 * азбука на французской этикетке была «уверена на 88 процентов», подставляя «сопзоттег» вместо
 * «consommer». Поэтому к уверенности добавляем главное: ОДНОРОДНОСТЬ письма. Настоящий текст
 * написан одной азбукой, а каша всегда мешает кириллицу с латиницей.
 */
export function ценаЧтения(разбор) {
  const текст = разбор.текст || '';
  const латиницы = (текст.match(/[A-Za-zÀ-ÿ]/g) || []).length;
  const кириллицы = (текст.match(/[А-Яа-яЁёЇїІіЄєҐґ]/g) || []).length;
  const иных = (текст.match(/[\u0370-\u1CFF\u3040-\u9FFF\uAC00-\uD7AF]/g) || []).length;
  const всего = латиницы + кириллицы + иных;
  if (!всего) return 0;
  const своих = Math.max(латиницы, кириллицы, иных);
  const чистота = своих / всего;              // 1 -- одна азбука, 0,5 -- пополам с мусором
  return разбор.уверенность * чистота * чистота;
}

/** Латинская диакритика: её наличие означает, что текст точно не английский. */
const ДИАКРИТИКА = /[àâäãåçéèêëíìîïñóòôöõúùûüýÿšžœæåø]/i;

/**
 * Похоже ли, что прочитано мимо: пусто или движок сам себе не верит.
 *
 * Буквы считаем по \p{L} -- свойству Юникода. Привычное \w знает ТОЛЬКО латиницу, и с ним
 * кириллица за буквы не считалась вовсе: страница решала, что не прочитала ничего, и молча
 * перебирала все азбуки подряд -- двенадцать лишних мегабайт на каждом русском снимке.
 */
export function прочиталосьПлохо(разбор) {
  const букв = (разбор.текст.match(/\p{L}/gu) || []).length;
  return букв < 12 || разбор.уверенность < 55;
}

/**
 * Прочитать снимок, сам подбирая азбуку. `ход(состояние)` зовётся словами о том, что сейчас
 * делается: человеку важно знать, что идёт подбор, а не зависание.
 */
export async function прочитатьСамо(холст, { база, ход, приРезультате } = {}) {
  const читать = async (набор, где) => {
    const чтец = await поднятьЧтеца(набор, (доля, что) => ход && ход({ набор, доля, что }));
    const { data } = await чтец.recognize(где, {}, { text: true, blocks: true, pdf: true });
    return data;
  };
  const оценить = (data, где) => разобратьЧтение(data, { ш: где.width, в: где.height });

  let лучшее = await читать(база, холст);
  let лучшийНабор = база;
  let разбор = оценить(лучшее, холст);
  if (приРезультате) приРезультате(лучшее, база);

  // УВЕРЕННОСТЬ ДВИЖКА ОБМАНЧИВА. На французской этикетке он был уверен на 87 процентов и
  // при этом прочитал «LAIT» как «АТ»: английская азбука не знает французских букв и слов и
  // подставляет похожие. Поэтому смотрим ещё и на буквы -- латинская диакритика значит, что
  // текст не английский, и если в наборе нет подходящего языка, надо пробовать дальше.
  const латиницей = ряднаяДогадка(разбор.текст) === 'латиница';
  const чужаяДиакритика = ДИАКРИТИКА.test(разбор.текст)
    && !ЛАТИНСКИЕ.some((я) => база.includes(я));
  if (!прочиталосьПлохо(разбор) && !чужаяДиакритика && !(латиницей && разбор.уверенность < 80)) {
    return { data: лучшее, набор: база, подбирали: false };
  }

  // ПОДБОР ИДЁТ ПО УМЕНЬШЕННОЙ КОПИИ. На снимке с телефона одно чтение занимает секунды, и
  // девять попыток подряд превращались в минуту ожидания -- а то и в закрытую вкладку.
  // Для выбора азбуки хватает тысячи точек по ширине: язык виден и на ней. Начисто потом
  // читаем ОДИН раз, уже нужной азбукой и по полному снимку.
  const почтиПусто = (разбор.текст.match(/\p{L}/gu) || []).length < 12;
  const проба = document.createElement('canvas');
  // Для латиницы хватает и полутора тысяч точек, а вот иероглифы на уменьшенной копии
  // рассыпаются: подбор переставал их узнавать. Поэтому когда базовое чтение дало почти
  // пустоту -- а это и есть чужая письменность -- пробуем по полному снимку.
  const доля = почтиПусто ? 1 : Math.min(1, 1600 / холст.width);
  проба.width = Math.max(1, Math.round(холст.width * доля));
  проба.height = Math.max(1, Math.round(холст.height * доля));
  проба.getContext('2d').drawImage(холст, 0, 0, проба.width, проба.height);

  // КОГДА ПРОЧИТАНО ПОЧТИ НИЧЕГО, верить облику букв нельзя: движок выдаёт случайный мусор
  // латиницей («(IF TE HR RUE» вместо иероглифов), и по нему выходило, что текст латинский --
  // а значит китайскую азбуку мы даже не пробовали. Мало букв -- значит чужая письменность,
  // и начинать надо с них.
  const догадка = почтиПусто || разбор.уверенность < 45 ? 'иные' : ряднаяДогадка(разбор.текст);
  // Сперва те языки, чьи слова и буквы уже мелькнули в кривом чтении: обычно первого же
  // кандидата хватает, и перебор кончается на одной азбуке вместо девяти.
  const угаданные = угадатьЛатинский(разбор.текст);
  const латинскиеПоПорядку = [...угаданные, ...ЛАТИНСКИЕ.filter((я) => !угаданные.includes(я))];
  const очередь = (догадка === 'иные'
    ? [...ПИСЬМЕННОСТИ, ...латинскиеПоПорядку]
    : [...латинскиеПоПорядку, ...ПИСЬМЕННОСТИ]).slice(0, 6);

  let лучшийПробный = оценить(await читать(база, проба), проба);
  let выбор = база;
  for (const один of очередь) {
    // Родной язык страницы оставляем в наборе: подписи на двух языках -- обычное дело.
    const набор = ЛАТИНСКИЕ.includes(один) ? один + '+eng' : один;
    if (ход) ход({ подбор: true, набор });
    let data;
    try {
      data = await читать(набор, проба);
    } catch (е) {
      // Осечку одной азбуки не показываем человеку -- пробуем следующую. Но и не прячем от
      // себя: складываем, чтобы живая проверка могла спросить, почему подбор не удался.
      if (typeof window !== 'undefined') {
        window.__тсОсечки = (window.__тсОсечки || []).concat(набор + ': ' + (е && е.message || е));
      }
      continue;
    }
    const этот = оценить(data, проба);
    if (ценаЧтения(этот) > ценаЧтения(лучшийПробный) + 1) { лучшийПробный = этот; выбор = набор; }
    if (!прочиталосьПлохо(этот) && ценаЧтения(этот) >= 85) break;
  }

  if (выбор === база) return { data: лучшее, набор: база, подбирали: true };
  // Начисто -- полным снимком и один раз.
  if (ход) ход({ подбор: true, набор: выбор });
  const начисто = await читать(выбор, холст);
  return { data: начисто, набор: выбор, подбирали: true };
}

/** Сколько слов прочитано неуверенно: это и есть «что проверить глазами». */
export function сомнительных(абзацы, порог = 70) {
  let всего = 0, плохих = 0;
  for (const а of абзацы) for (const с of а.строки) for (const сл of с.слова) {
    if (!сл.текст.trim()) continue;
    всего++;
    if (сл.уверенность < порог) плохих++;
  }
  return { всего, плохих };
}
