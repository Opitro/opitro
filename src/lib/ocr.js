/**
 * РАСПОЗНАВАНИЕ ТЕКСТА В БРАУЗЕРЕ -- общее для сканера MRZ и сканера текста с фото.
 *
 * Движок (Tesseract) и языковые азбуки лежат у нас же, в /tess/, и приезжают только тогда,
 * когда человек выбрал снимок. Ничего не уходит наружу: ни кадр, ни распознанное. Для
 * страницы, куда несут паспорт или чужое письмо, это не вежливая фраза, а условие.
 *
 * Веса, чтобы решать с открытыми глазами: ядро 2,7 МБ, азбука 1,1--1,9 МБ на язык (по сети
 * меньше -- отдаются сжатыми). Азбука кешируется браузером, второй раз начинается сразу.
 */

/** Умеет ли браузер быстрые команды WebAssembly: с ними чтение заметно скорее. */
function поддержкаSIMD() {
  try {
    return WebAssembly.validate(new Uint8Array([
      0, 97, 115, 109, 1, 0, 0, 0, 1, 5, 1, 96, 0, 1, 123, 3, 2, 1, 0,
      10, 10, 1, 8, 0, 65, 0, 253, 15, 253, 98, 11,
    ]));
  } catch (е) { return false; }
}

const работники = new Map();   // язык -> обещание работника: второй раз поднимать незачем

/**
 * Поднять распознаватель для набора азбук. `языки` -- строка вида 'rus' или 'rus+eng':
 * два языка разом нужны для текста, где кириллица идёт вперемешку с латиницей.
 * `ход` зовётся с долей от 0 до 1, пока едут файлы.
 */
export async function поднятьЧтеца(языки, ход) {
  if (работники.has(языки)) return работники.get(языки);
  const обещание = (async () => {
    const { createWorker } = await import('tesseract.js');
    const ядро = поддержкаSIMD()
      ? '/tess/tesseract-core-simd-lstm.js'
      : '/tess/tesseract-core-lstm.js';
    return createWorker(языки, 1, {
      workerPath: '/tess/worker.min.js',
      // ВОРКЕР ИЗ ФАЙЛА, а не из blob-адреса: внутри blob «рядом со мной» указывает в никуда,
      // и движок молча зависал на шаге инициализации -- ни ошибки, ни отказа.
      workerBlobURL: false,
      corePath: ядро,
      langPath: '/tess/',
      gzip: true,
      logger: (м) => {
        if (ход && м && typeof м.progress === 'number') ход(м.progress, м.status || '');
      },
    });
  })();
  работники.set(языки, обещание);
  try { return await обещание; } catch (е) { работники.delete(языки); throw е; }
}

/**
 * ПОДГОТОВИТЬ СНИМОК К ЧТЕНИЮ.
 *
 * Движок читает тем лучше, чем крупнее и чище буквы. Поэтому: переводим в серое по
 * восприятию, растягиваем контраст по краям гистограммы (снимок с телефона всегда сероват) и
 * увеличиваем до полутора-двух тысяч точек по ширине. Без этого тот же движок на том же
 * снимке ошибается втрое чаще -- проверено на образцах.
 *
 * `часть` -- доля кадра (левая, верхняя, ширина, высота в долях), если человек выделил кусок.
 * `светлыйНаТёмном` -- для снимков экрана с тёмной темой: буквы светлые, фон чёрный, и без
 * обращения цветов движок видит кашу.
 */
export function подготовить(источник, { ш, в, часть = null, светлыйНаТёмном = false, ширинаЦели = 1800, безКонтраста = false } = {}) {
  const кх = часть ? Math.round(часть.х * ш) : 0;
  const ку = часть ? Math.round(часть.у * в) : 0;
  const кш = часть ? Math.max(8, Math.round(часть.ш * ш)) : ш;
  const кв = часть ? Math.max(8, Math.round(часть.в * в)) : в;

  const к = Math.min(3, Math.max(1, ширинаЦели / кш));
  const холст = document.createElement('canvas');
  холст.width = Math.round(кш * к);
  холст.height = Math.round(кв * к);
  const кон = холст.getContext('2d', { willReadFrequently: true });
  кон.imageSmoothingQuality = 'high';
  кон.drawImage(источник, кх, ку, кш, кв, 0, 0, холст.width, холст.height);

  const точки = кон.getImageData(0, 0, холст.width, холст.height);
  const д = точки.data;
  const гисто = new Uint32Array(256);
  for (let i = 0; i < д.length; i += 4) {
    let г = (д[i] * 299 + д[i + 1] * 587 + д[i + 2] * 114) / 1000 | 0;
    if (светлыйНаТёмном) г = 255 - г;
    д[i] = д[i + 1] = д[i + 2] = г;
    гисто[г]++;
  }
  // РАСТЯЖЕНИЕ КОНТРАСТА -- ТОЛЬКО ТАМ, ГДЕ ОНО НУЖНО.
  //
  // Отрезали по пять процентов с краёв -- и на обычном листе, где белого девять десятых,
  // нижний порог уезжал почти в белое: картинка превращалась в кашу, и целые письменности
  // переставали читаться (китайский давал ноль строк там, где без обработки читался на 93%).
  // Поэтому: край отрезаем на процент, а если снимок и так контрастный -- не трогаем вовсе.
  const всего = холст.width * холст.height;
  let низ = 0, сумма = 0;
  while (низ < 255 && сумма < всего * 0.01) { сумма += гисто[низ++]; }
  let верх = 255; сумма = 0;
  while (верх > 0 && сумма < всего * 0.01) { сумма += гисто[верх--]; }
  const размах = верх - низ;
  if (безКонтраста || размах >= 150 || размах < 40) { кон.putImageData(точки, 0, 0); return холст; }
  for (let i = 0; i < д.length; i += 4) {
    const з = Math.max(0, Math.min(255, ((д[i] - низ) * 255) / размах));
    д[i] = д[i + 1] = д[i + 2] = з;
  }
  кон.putImageData(точки, 0, 0);
  return холст;
}

/**
 * Разобрать ответ движка в удобный вид: абзацы, строки, слова -- с их местом на снимке и
 * уверенностью. Место нужно, чтобы подсветить строку прямо на фотографии: человек видит,
 * откуда взялась каждая строка, и сразу замечает, что прочитано мимо.
 *
 * Координаты переводим В ДОЛИ снимка: холст мы увеличивали, а показываем снимок как есть.
 */
export function разобратьЧтение(data, { ш, в, часть = null } = {}) {
  const абзацы = [];
  const вДоли = (р) => {
    const дх = часть ? часть.х : 0, ду = часть ? часть.у : 0;
    const дш = часть ? часть.ш : 1, дв = часть ? часть.в : 1;
    return {
      х: дх + (р.x0 / ш) * дш,
      у: ду + (р.y0 / в) * дв,
      ш: ((р.x1 - р.x0) / ш) * дш,
      в: ((р.y1 - р.y0) / в) * дв,
    };
  };
  for (const блок of data.blocks || []) {
    for (const абзац of блок.paragraphs || []) {
      const строки = [];
      for (const стр of абзац.lines || []) {
        const текст = (стр.text || '').replace(/\s+$/, '');
        if (!текст.trim()) continue;
        строки.push({
          текст,
          уверенность: Math.round(стр.confidence || 0),
          место: вДоли(стр.bbox),
          слова: (стр.words || []).map((с) => ({
            текст: с.text, уверенность: Math.round(с.confidence || 0), место: вДоли(с.bbox),
          })),
        });
      }
      if (строки.length) абзацы.push({ строки });
    }
  }
  // Текст собираем сами, а не берём data.text: в браузерной сборке он приходит ПУСТЫМ, даже
  // когда строки прочитаны, -- на этом я уже обжёгся: страница решила, что не прочитала
  // ничего, и перебрала все азбуки подряд. Заодно абзацы нужны человеку, а не склейка.
  const текст = абзацы.map((а) => а.строки.map((с) => с.текст).join('\n')).join('\n\n');
  // Уверенность тоже считаем сами, по строкам: data.confidence там же и по той же причине ноль.
  let сумма = 0, весов = 0;
  for (const а of абзацы) for (const с of а.строки) {
    const вес = Math.max(1, с.текст.length);
    сумма += с.уверенность * вес; весов += вес;
  }
  const уверенность = весов ? Math.round(сумма / весов) : Math.round(data.confidence || 0);
  return { абзацы, текст, уверенность };
}

/**
 * ЧЕЛОВЕК НЕ ВЫБИРАЕТ АЗБУКУ. Он принёс снимок -- страница обязана прочитать что есть.
 *
 * Движок сравнивает буквы с образцами своего языка, поэтому «читать любой язык одной кнопкой»
 * невозможно в принципе -- но знать об этом человеку незачем. Делаем так: сперва читаем
 * азбукой страницы с латиницей (девять снимков из десяти этим и закрываются), а если вышло
 * пусто или сплошная каша -- молча пробуем другие письменности по очереди и берём лучшую.
 *
 * Азбуки маленькие: китайская 2,5 МБ, арабская 1,4, греческая 1,4 -- качается по одной и
 * только когда понадобилась. Готовые «наборы письменностей» от Tesseract мы не берём: одна
 * латиница там весит 89 МБ.
 */
export const ЗАПАСНЫЕ = ['chi_sim', 'jpn', 'kor', 'ara', 'ell', 'heb', 'hin', 'tha'];

/**
 * Похоже ли, что прочитано мимо: пусто или движок сам себе не верит.
 *
 * Буквы считаем по \p{L} -- свойству Юникода. Привычное \w знает ТОЛЬКО латиницу, и с ним
 * кириллица за буквы не считалась вовсе: страница решала, что не прочитала ничего, и молча
 * перебирала все азбуки подряд -- двенадцать лишних мегабайт на каждом русском снимке.
 */
export function прочиталосьПлохо(разбор) {
  const букв = (разбор.текст.match(/\p{L}/gu) || []).length;
  return букв < 12 || разбор.уверенность < 55;
}

/**
 * Прочитать снимок, сам подбирая азбуку. `ход(состояние)` зовётся словами о том, что сейчас
 * делается: человеку важно знать, что идёт подбор, а не зависание.
 */
export async function прочитатьСамо(холст, { база, ход, приРезультате } = {}) {
  const читать = async (набор) => {
    const чтец = await поднятьЧтеца(набор, (доля, что) => ход && ход({ набор, доля, что }));
    const { data } = await чтец.recognize(холст, {}, { text: true, blocks: true, pdf: true });
    return data;
  };

  const оценить = (data) => разобратьЧтение(data, { ш: холст.width, в: холст.height });

  let лучшее = await читать(база);
  let лучшийНабор = база;
  let разбор = оценить(лучшее);
  if (приРезультате) приРезультате(лучшее, база);
  if (!прочиталосьПлохо(разбор)) return { data: лучшее, набор: база, подбирали: false };

  // Пошёл подбор: буквы на снимке явно не той письменности, что мы пробовали.
  for (const набор of ЗАПАСНЫЕ) {
    if (ход) ход({ подбор: true, набор });
    let data;
    try {
      data = await читать(набор);
    } catch (е) {
      // Осечку одной азбуки не показываем человеку -- пробуем следующую. Но и не прячем от
      // себя: складываем, чтобы живая проверка могла спросить, почему подбор не удался.
      if (typeof window !== 'undefined') {
        window.__тсОсечки = (window.__тсОсечки || []).concat(набор + ': ' + (е && е.message || е));
      }
      continue;
    }
    const этот = оценить(data);
    if (этот.уверенность > разбор.уверенность) { лучшее = data; лучшийНабор = набор; разбор = этот; }
    if (!прочиталосьПлохо(этот)) break;
  }
  return { data: лучшее, набор: лучшийНабор, подбирали: true };
}

/** Сколько слов прочитано неуверенно: это и есть «что проверить глазами». */
export function сомнительных(абзацы, порог = 70) {
  let всего = 0, плохих = 0;
  for (const а of абзацы) for (const с of а.строки) for (const сл of с.слова) {
    if (!сл.текст.trim()) continue;
    всего++;
    if (сл.уверенность < порог) плохих++;
  }
  return { всего, плохих };
}
